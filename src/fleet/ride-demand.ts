export const RIDE_DEMAND_VERSION = '059-ride-demand-v1' as const;

/**
 * Fixed budgets. A scenario cannot grow the generated schedule or the pending queue past these
 * values; there is no retained history and no wall-clock driven growth.
 */
export const RIDE_DEMAND_LIMITS = Object.freeze({
  version: RIDE_DEMAND_VERSION,
  /** Bounded scenario schedule entries. */
  windows: 256,
  /** Bounded requests generated by one plan, across every window. */
  requests: 1024,
  /** Bounded requests inside one schedule window. */
  requestsPerWindow: 256,
  /** Bounded pending (not yet dequeued) requests. Overflow policy is explicit. */
  pendingRequests: 64,
  /** Request and plan identifiers stay inside the 006 identity part limit. */
  idCodeUnits: 256,
  windowIdCodeUnits: 64,
  scenarioIdCodeUnits: 256,
  namespaceCodeUnits: 64,
});

/** Explicit overflow policy: the newest request is rejected, never silently queued. */
export const RIDE_DEMAND_OVERFLOW_POLICY = 'REJECT_NEWEST' as const;

export const demandLevels = ['LOW', 'NORMAL', 'HIGH'] as const;
export type DemandLevel = (typeof demandLevels)[number];

export const RIDE_REQUEST_VALIDATION_STATUSES = [
  'READY',
  'UNKNOWN_ORIGIN',
  'UNKNOWN_DESTINATION',
  'NOT_PICKUP_ZONE',
  'NOT_DROPOFF_ZONE',
  'ACCESS_MISMATCH',
  'SAME_ZONE',
  'NO_ROUTE',
] as const;
export type RideRequestValidationStatus = (typeof RIDE_REQUEST_VALIDATION_STATUSES)[number];

export const RIDE_DEMAND_REJECTION_REASONS = ['INVALID_REQUEST', 'QUEUE_OVERFLOW'] as const;
export type RideDemandRejectionReason = (typeof RIDE_DEMAND_REJECTION_REASONS)[number];

export interface RideDemandWindow {
  /** Semantic schedule identity; it participates in every request identity in the window. */
  readonly windowId: string;
  readonly startTick: number;
  /** Exclusive. Every request spawn tick stays inside `[startTick, endTick)`. */
  readonly endTick: number;
  readonly demandLevel: DemandLevel;
  readonly requestCount: number;
  /** Optional authored constraint. A missing zone is derived deterministically from the seed. */
  readonly originZoneId: string | null;
  readonly destinationZoneId: string | null;
}

export interface RideDemandPlan {
  readonly schemaVersion: 1;
  readonly units: 'SI';
  readonly scenarioId: string;
  /** The schedule belongs to exactly one validated 032 map and its real service zones. */
  readonly mapId: string;
  readonly seed: number;
  readonly namespace: string;
  /** Canonical order: start tick, then window id. Input array order is not significant. */
  readonly windows: readonly RideDemandWindow[];
}

export interface RideRequest {
  readonly requestId: string;
  readonly scenarioId: string;
  readonly windowId: string;
  /** Zero-based position inside its window; semantic, not a global event counter. */
  readonly ordinal: number;
  readonly spawnTick: number;
  readonly demandLevel: DemandLevel;
  readonly access: 'TAXI';
  /** A real 032 service-zone id; the module never forges a parallel zone identity. */
  readonly originZoneId: string;
  readonly destinationZoneId: string;
}

export interface RideRequestValidation {
  readonly requestId: string;
  readonly status: RideRequestValidationStatus;
  /** Raw 041 status when the planner was consulted, otherwise null. */
  readonly routeStatus: RouteStatus | null;
  readonly costSeconds: number | null;
  readonly laneCount: number | null;
}

export interface RideDemandRejection {
  readonly requestId: string;
  readonly spawnTick: number;
  readonly reason: RideDemandRejectionReason;
  readonly validationStatus: RideRequestValidationStatus | null;
}

export interface RideDemandAdvance {
  readonly tick: number;
  readonly admitted: readonly RideRequest[];
  readonly pending: readonly RideRequest[];
  readonly overflowed: readonly RideRequest[];
}

export interface RideDemandStats {
  readonly version: typeof RIDE_DEMAND_VERSION;
  readonly windows: number;
  readonly requests: number;
  readonly valid: number;
  readonly invalid: number;
  readonly pending: number;
  readonly admitted: number;
  readonly dequeued: number;
  readonly overflow: number;
  readonly routeSearches: number;
  readonly queueLimit: number;
  readonly plannerOwned: boolean;
  readonly plannerDisposed: boolean;
  readonly disposed: boolean;
}

export interface RideDemandOptions {
  readonly plan: unknown;
  readonly map: unknown;
  readonly graph?: LaneGraph;
  readonly planner?: RoutePlanner;
  readonly graphVersion?: string;
  readonly costVersion?: string;
  /** Bounded override; defaults to RIDE_DEMAND_LIMITS.pendingRequests. */
  readonly queueLimit?: number;
}

export interface RideDemand {
  readonly plan: RideDemandPlan;
  /** Every generated request, including invalid ones, sorted by spawn tick then request id. */
  requests(): readonly RideRequest[];
  validation(requestId: string): RideRequestValidation | undefined;
  /** Rejected requests: impossible ones validated before allocation, plus queue overflow. */
  rejections(): readonly RideDemandRejection[];
  /** Validated requests waiting for 060; bounded by the queue limit. */
  pending(): readonly RideRequest[];
  /** Admits every request whose schedule tick is at or before `atTick`; never future ones. */
  advance(atTick: number): RideDemandAdvance;
  /** Stable FIFO removal of the oldest pending request. */
  dequeue(): RideRequest | undefined;
  stats(): RideDemandStats;
  dispose(): void;
}

const windowFields = [
  'windowId',
  'startTick',
  'endTick',
  'demandLevel',
  'requestCount',
  'originZoneId',
  'destinationZoneId',
] as const;

const planFields = [
  'schemaVersion',
  'units',
  'scenarioId',
  'mapId',
  'seed',
  'namespace',
  'windows',
] as const;

const optionFields = [
  'plan',
  'map',
  'graph',
  'planner',
  'graphVersion',
  'costVersion',
  'queueLimit',
] as const;

function boundedText(value: unknown, maximum: number, label: string): string {
  const result = text(value);
  requireContract(
    result.length <= maximum && result.trim() === result,
    `Invalid ${label} identifier`,
  );
  return result;
}

function compareText(left: string, right: string): number {
  return left < right ? -1 : left > right ? 1 : 0;
}

function readSeed(value: unknown): RandomSeed {
  const seed = number(value, 0, 0xffff_ffff);
  requireContract(Number.isSafeInteger(seed), 'Ride demand seed must be a uint32');
  return seed;
}

function readCount(value: unknown, minimum: number, maximum: number, label: string): number {
  const count = number(value, minimum, maximum);
  requireContract(Number.isSafeInteger(count), `${label} must be an integer`);
  return count;
}

function readOptionalZoneId(value: unknown): string | null {
  if (value === undefined || value === null) return null;
  return boundedText(value, RIDE_DEMAND_LIMITS.idCodeUnits, 'service zone');
}

function readWindow(value: unknown): RideDemandWindow {
  const data = record(value);
  for (const key of Object.keys(data))
    requireContract(
      (windowFields as readonly string[]).includes(key),
      'Unknown ride demand window field',
    );
  const windowId = boundedText(
    data.windowId,
    RIDE_DEMAND_LIMITS.windowIdCodeUnits,
    'ride demand window',
  );
  const startTick = tick(data.startTick);
  const endTick = tick(data.endTick);
  requireContract(endTick > startTick, 'Ride demand window must have a positive span');
  const demandLevel = choice(data.demandLevel, demandLevels);
  const requestCount = readCount(
    data.requestCount,
    1,
    RIDE_DEMAND_LIMITS.requestsPerWindow,
    'Ride demand request count',
  );
  return Object.freeze({
    windowId,
    startTick,
    endTick,
    demandLevel,
    requestCount,
    originZoneId: readOptionalZoneId(data.originZoneId),
    destinationZoneId: readOptionalZoneId(data.destinationZoneId),
  });
}

function requestSlot(ordinal: number): string {
  return `r${String(ordinal).padStart(4, '0')}`;
}

/** Stable 006 identity: schedule window plus its per-window ordinal. */
export function rideRequestId(namespace: string, windowId: string, ordinal: number): string {
  return createStableId('ride-request', namespace, [windowId, requestSlot(ordinal)]);
}

/**
 * Deterministic, strictly bounded spawn tick inside `[startTick, endTick)`.
 * The quotient/remainder split distributes requests evenly without `start + i * span / count`
 * precision loss, and the clamp is only reachable when a window asks for more requests than ticks.
 */
export function rideRequestSpawnTick(schedule: RideDemandWindow, ordinal: number): number {
  requireContract(
    Number.isSafeInteger(ordinal) && ordinal >= 0 && ordinal < schedule.requestCount,
    'Invalid ride request ordinal',
  );
  const span = schedule.endTick - schedule.startTick;
  requireContract(span > 0, 'Ride demand window must have a positive span');
  const quotient = Math.floor(span / schedule.requestCount);
  const remainder = span % schedule.requestCount;
  const offset = Math.min(span - 1, quotient * ordinal + Math.min(ordinal, remainder));
  return schedule.startTick + offset;
}

export function parseRideDemandPlan(value: unknown): RideDemandPlan {
  const data = fields(value, planFields);
  requireContract(
    data.schemaVersion === 1 && data.units === 'SI',
    'Unsupported ride demand schema version or units',
  );
  const scenarioId = boundedText(
    data.scenarioId,
    RIDE_DEMAND_LIMITS.scenarioIdCodeUnits,
    'ride demand scenario',
  );
  const mapId = boundedText(data.mapId, RIDE_DEMAND_LIMITS.idCodeUnits, 'ride demand map');
  const seed = readSeed(data.seed);
  const namespace = boundedText(
    data.namespace,
    RIDE_DEMAND_LIMITS.namespaceCodeUnits,
    'ride demand namespace',
  );
  const windows = list(data.windows, readWindow);
  requireContract(
    windows.length > 0 && windows.length <= RIDE_DEMAND_LIMITS.windows,
    'Ride demand window capacity violated',
  );
  const ids = new Set<string>();
  let total = 0;
  for (const entry of windows) {
    requireContract(!ids.has(entry.windowId), 'Duplicate ride demand window id');
    ids.add(entry.windowId);
    total += entry.requestCount;
    requireContract(
      rideRequestId(namespace, entry.windowId, entry.requestCount - 1).length <=
        RIDE_DEMAND_LIMITS.idCodeUnits,
      'Ride request identity exceeds the code-unit limit',
    );
  }
  requireContract(total <= RIDE_DEMAND_LIMITS.requests, 'Ride demand request capacity violated');
  // Canonical plan order makes the caller's array order irrelevant.
  const canonical = windows
    .slice()
    .sort(
      (left, right) =>
        left.startTick - right.startTick || compareText(left.windowId, right.windowId),
    );
  return Object.freeze({
    schemaVersion: 1,
    units: 'SI',
    scenarioId,
    mapId,
    seed,
    namespace,
    windows: Object.freeze(canonical),
  });
}

function eligibleZones(map: RoadMap, role: 'PICKUP' | 'DROPOFF'): readonly ServiceZone[] {
  const zones = map.serviceZones.filter((zone) => {
    if (!zone.access.includes('TAXI')) return false;
    return role === 'PICKUP' ? zone.kind !== 'DROPOFF' : zone.kind !== 'PICKUP';
  });
  return Object.freeze(zones.slice().sort((left, right) => compareText(left.id, right.id)));
}

/** Deterministic round-robin selection that never returns `excludeId` unless it is unavoidable. */
function pickZone(zones: readonly ServiceZone[], sample: number, excludeId: string | null): string {
  const start = sample % zones.length;
  for (let step = 0; step < zones.length; step += 1) {
    const zone = zones[(start + step) % zones.length]!;
    if (zone.id !== excludeId) return zone.id;
  }
  return zones[start]!.id;
}

function buildRequests(
  plan: RideDemandPlan,
  pickupZones: readonly ServiceZone[],
  dropoffZones: readonly ServiceZone[],
): readonly RideRequest[] {
  const scenarioSeed = deriveScenarioSeed(plan.seed, plan.scenarioId);
  const requests: RideRequest[] = [];
  for (const entry of plan.windows) {
    for (let ordinal = 0; ordinal < entry.requestCount; ordinal += 1) {
      const originZoneId =
        entry.originZoneId ??
        pickZone(
          pickupZones,
          randomUint32(scenarioSeed, `origin:${entry.windowId}`, ordinal),
          entry.destinationZoneId,
        );
      const destinationZoneId =
        entry.destinationZoneId ??
        pickZone(
          dropoffZones,
          randomUint32(scenarioSeed, `destination:${entry.windowId}`, ordinal),
          originZoneId,
        );
      requests.push(
        Object.freeze({
          requestId: rideRequestId(plan.namespace, entry.windowId, ordinal),
          scenarioId: plan.scenarioId,
          windowId: entry.windowId,
          ordinal,
          spawnTick: rideRequestSpawnTick(entry, ordinal),
          demandLevel: entry.demandLevel,
          access: 'TAXI' as const,
          originZoneId,
          destinationZoneId,
        }),
      );
    }
  }
  return Object.freeze(
    requests.sort(
      (left, right) =>
        left.spawnTick - right.spawnTick || compareText(left.requestId, right.requestId),
    ),
  );
}

function routeValidationStatus(status: RouteStatus): RideRequestValidationStatus {
  switch (status) {
    case 'READY':
      return 'READY';
    case 'ORIGIN_UNKNOWN':
      return 'UNKNOWN_ORIGIN';
    case 'DESTINATION_UNKNOWN':
      return 'UNKNOWN_DESTINATION';
    case 'SERVICE_ACCESS_MISMATCH':
      return 'ACCESS_MISMATCH';
    case 'BLOCKED':
    case 'UNREACHABLE':
    case 'BUDGET_EXHAUSTED':
      return 'NO_ROUTE';
  }
}

interface Validator {
  validate(request: RideRequest): RideRequestValidation;
  routeSearches(): number;
}

function createValidator(
  zones: ReadonlyMap<string, ServiceZone>,
  planner: RoutePlanner,
): Validator {
  let searches = 0;
  return {
    routeSearches: () => searches,
    validate(request: RideRequest): RideRequestValidation {
      const origin = zones.get(request.originZoneId);
      if (!origin)
        return Object.freeze({
          requestId: request.requestId,
          status: 'UNKNOWN_ORIGIN',
          routeStatus: null,
          costSeconds: null,
          laneCount: null,
        });
      const destination = zones.get(request.destinationZoneId);
      if (!destination)
        return Object.freeze({
          requestId: request.requestId,
          status: 'UNKNOWN_DESTINATION',
          routeStatus: null,
          costSeconds: null,
          laneCount: null,
        });
      if (!origin.access.includes('TAXI') || !destination.access.includes('TAXI'))
        return Object.freeze({
          requestId: request.requestId,
          status: 'ACCESS_MISMATCH',
          routeStatus: null,
          costSeconds: null,
          laneCount: null,
        });
      if (origin.kind === 'DROPOFF')
        return Object.freeze({
          requestId: request.requestId,
          status: 'NOT_PICKUP_ZONE',
          routeStatus: null,
          costSeconds: null,
          laneCount: null,
        });
      if (destination.kind === 'PICKUP')
        return Object.freeze({
          requestId: request.requestId,
          status: 'NOT_DROPOFF_ZONE',
          routeStatus: null,
          costSeconds: null,
          laneCount: null,
        });
      if (origin.id === destination.id)
        return Object.freeze({
          requestId: request.requestId,
          status: 'SAME_ZONE',
          routeStatus: null,
          costSeconds: null,
          laneCount: null,
        });
      searches += 1;
      const route = planner.findRoute({
        origin: origin.id,
        destination: destination.id,
        access: 'TAXI',
      });
      const status = routeValidationStatus(route.status);
      return Object.freeze({
        requestId: request.requestId,
        status,
        routeStatus: route.status,
        costSeconds: status === 'READY' && route.path ? route.costSeconds : null,
        laneCount: status === 'READY' && route.path ? route.path.length : null,
      });
    },
  };
}

function readOptions(value: unknown): {
  plan: unknown;
  map: unknown;
  graph: LaneGraph | null;
  planner: RoutePlanner | null;
  graphVersion: string;
  costVersion: string;
  queueLimit: number;
} {
  const data = record(value);
  for (const key of Object.keys(data))
    requireContract(
      (optionFields as readonly string[]).includes(key),
      'Unknown ride demand option',
    );
  requireContract(data.plan !== undefined, 'Ride demand requires a scenario plan');
  requireContract(data.map !== undefined, 'Ride demand requires a road map');
  const graph = data.graph === undefined ? null : (data.graph as LaneGraph);
  if (graph !== null)
    requireContract(
      typeof graph.getLane === 'function' && typeof graph.getDirectedPath === 'function',
      'Invalid ride demand lane graph',
    );
  const planner = data.planner === undefined ? null : (data.planner as RoutePlanner);
  if (planner !== null)
    requireContract(
      typeof planner.findRoute === 'function' &&
        typeof planner.resolveDestination === 'function' &&
        typeof planner.getStats === 'function',
      'Invalid ride demand route planner',
    );
  const graphVersion =
    data.graphVersion === undefined
      ? '033-lane-graph-v1'
      : boundedText(data.graphVersion, 128, 'ride demand graph version');
  const costVersion =
    data.costVersion === undefined
      ? ROUTE_COST_MODEL.version
      : boundedText(data.costVersion, 128, 'ride demand cost version');
  const queueLimit =
    data.queueLimit === undefined
      ? RIDE_DEMAND_LIMITS.pendingRequests
      : readCount(
          data.queueLimit,
          1,
          RIDE_DEMAND_LIMITS.pendingRequests,
          'Ride demand queue limit',
        );
  return {
    plan: data.plan,
    map: data.map,
    graph,
    planner,
    graphVersion,
    costVersion,
    queueLimit,
  };
}

function zeroStats(
  queueLimit: number,
  plannerOwned: boolean,
  plannerDisposed: boolean,
  disposed: boolean,
): RideDemandStats {
  return Object.freeze({
    version: RIDE_DEMAND_VERSION,
    windows: 0,
    requests: 0,
    valid: 0,
    invalid: 0,
    pending: 0,
    admitted: 0,
    dequeued: 0,
    overflow: 0,
    routeSearches: 0,
    queueLimit,
    plannerOwned,
    plannerDisposed,
    disposed,
  });
}

export function createRideDemand(options: unknown): RideDemand {
  const read = readOptions(options);
  const plan = parseRideDemandPlan(read.plan);
  const map = parseRoadMap(read.map);
  requireContract(plan.mapId === map.mapId, 'Ride demand plan/map id mismatch');
  const pickupZones = eligibleZones(map, 'PICKUP');
  const dropoffZones = eligibleZones(map, 'DROPOFF');
  requireContract(
    pickupZones.length > 0 && dropoffZones.length > 0,
    'Ride demand requires TAXI pickup and dropoff service zones',
  );
  let planner = read.planner;
  let ownedPlanner = false;
  if (planner === null) {
    const graph = read.graph ?? createLaneGraph(map);
    planner = createRoutePlanner({
      graph,
      map,
      graphVersion: read.graphVersion,
      costVersion: read.costVersion,
    });
    ownedPlanner = true;
  }
  const plannerOwned = ownedPlanner;
  // A supplied planner must be able to resolve this map's real service zones.
  for (const zone of [pickupZones[0]!, dropoffZones[0]!]) {
    const resolved = planner.resolveDestination(zone.id, 'TAXI');
    requireContract(
      resolved !== null && resolved.kind === 'ZONE',
      'Ride demand planner does not resolve the map service zones',
    );
  }
  const zoneLookup = new Map<string, ServiceZone>();
  for (const zone of map.serviceZones) zoneLookup.set(zone.id, zone);
  const requests: RideRequest[] = [...buildRequests(plan, pickupZones, dropoffZones)];
  const validator = createValidator(zoneLookup, planner);
  const validations = new Map<string, RideRequestValidation>();
  const rejections: RideDemandRejection[] = [];
  const valid: RideRequest[] = [];
  for (const request of requests) {
    const validation = validator.validate(request);
    validations.set(request.requestId, validation);
    if (validation.status === 'READY') valid.push(request);
    else
      rejections.push(
        Object.freeze({
          requestId: request.requestId,
          spawnTick: request.spawnTick,
          reason: 'INVALID_REQUEST' as const,
          validationStatus: validation.status,
        }),
      );
  }
  const pending: RideRequest[] = [];
  const limit = read.queueLimit;
  let cursor = 0;
  let cursorTick = -1;
  let admitted = 0;
  let dequeued = 0;
  let overflow = 0;
  let disposed = false;

  function assertLive(): void {
    if (disposed) throw new Error('Ride demand disposed');
  }

  function snapshot(): readonly RideRequest[] {
    return Object.freeze(pending.slice());
  }

  return Object.freeze({
    plan,
    requests(): readonly RideRequest[] {
      return disposed ? Object.freeze([]) : Object.freeze(requests.slice());
    },
    validation(requestId: string): RideRequestValidation | undefined {
      if (disposed) return undefined;
      return validations.get(requestId);
    },
    rejections(): readonly RideDemandRejection[] {
      return disposed ? Object.freeze([]) : Object.freeze(rejections.slice());
    },
    pending(): readonly RideRequest[] {
      return disposed ? Object.freeze([]) : snapshot();
    },
    advance(atTick: number): RideDemandAdvance {
      assertLive();
      const nextTick = tick(atTick);
      if (nextTick < cursorTick) throw new RangeError('Stale ride demand tick');
      cursorTick = nextTick;
      const admittedNow: RideRequest[] = [];
      const overflowed: RideRequest[] = [];
      while (cursor < requests.length && requests[cursor]!.spawnTick <= nextTick) {
        const request = requests[cursor++]!;
        const validation = validations.get(request.requestId)!;
        if (validation.status !== 'READY') continue;
        if (pending.length >= limit) {
          overflow += 1;
          overflowed.push(request);
          rejections.push(
            Object.freeze({
              requestId: request.requestId,
              spawnTick: request.spawnTick,
              reason: 'QUEUE_OVERFLOW' as const,
              validationStatus: 'READY' as const,
            }),
          );
          continue;
        }
        pending.push(request);
        admitted += 1;
        admittedNow.push(request);
      }
      return Object.freeze({
        tick: nextTick,
        admitted: Object.freeze(admittedNow),
        pending: snapshot(),
        overflowed: Object.freeze(overflowed),
      });
    },
    dequeue(): RideRequest | undefined {
      assertLive();
      const request = pending.shift();
      if (request !== undefined) dequeued += 1;
      return request;
    },
    stats(): RideDemandStats {
      const plannerDisposed = planner === null || planner.getStats().disposed;
      if (disposed) return zeroStats(limit, plannerOwned, plannerDisposed, true);
      return Object.freeze({
        version: RIDE_DEMAND_VERSION,
        windows: plan.windows.length,
        requests: requests.length,
        valid: valid.length,
        invalid: requests.length - valid.length,
        pending: pending.length,
        admitted,
        dequeued,
        overflow,
        routeSearches: validator.routeSearches(),
        queueLimit: limit,
        plannerOwned,
        plannerDisposed,
        disposed: false,
      });
    },
    dispose(): void {
      if (disposed) return;
      disposed = true;
      requests.length = 0;
      valid.length = 0;
      pending.length = 0;
      validations.clear();
      rejections.length = 0;
      cursor = 0;
      admitted = 0;
      dequeued = 0;
      overflow = 0;
      if (ownedPlanner) {
        planner!.dispose();
        planner = null;
      }
    },
  });
}
