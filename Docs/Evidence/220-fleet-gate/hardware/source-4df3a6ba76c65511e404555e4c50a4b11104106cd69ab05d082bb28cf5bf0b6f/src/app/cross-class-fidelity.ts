import {
  CROSS_CLASS_FIDELITY_VERSION,
  crossClassTolerances,
  evaluateCrossClassFidelity,
} from '../experiments';
import type {
  CrossClassCommonProfile,
  CrossClassFidelityOptions,
  CrossClassFidelityReport,
  CrossClassKeyRow,
  CrossClassStyleRun,
  CrossClassTrendRow,
} from '../experiments';

/**
 * Report/composition adapter for 106. It runs the offline harness, adds no UI and no persistence,
 * and never publishes a profile or writes a fleet. `MANUAL` and ineligible `LEARNING` produce no
 * candidate; an eligible `LEARNING` run produces an in-memory candidate only.
 */
export const CROSS_CLASS_FIDELITY_APP_VERSION = '106-cross-class-fidelity-app-v1' as const;

export function runCrossClassFidelityValidation(
  options: CrossClassFidelityOptions = {},
): CrossClassFidelityReport {
  return evaluateCrossClassFidelity(options);
}

const BACKTICK = '`';

function code(value: string | number | boolean | null): string {
  return `${BACKTICK}${String(value)}${BACKTICK}`;
}

function cell(value: string | number | null): string {
  return value === null ? '—' : String(value).replaceAll('|', '\\|');
}

function numeric(value: number | null, digits = 4): number | null {
  return value === null ? null : Number(value.toFixed(digits));
}

function keyRow(run: CrossClassStyleRun, row: CrossClassKeyRow): string {
  return (
    '| ' +
    [
      run.style,
      run.classId,
      row.key,
      cell(numeric(row.target)),
      cell(numeric(row.estimate)),
      cell(numeric(row.tolerance.effective)),
      code(row.evidence.distinctEpisodes),
      code(row.status),
    ].join(' | ') +
    ' |'
  );
}

function trendRow(row: CrossClassTrendRow): string {
  return (
    '| ' +
    [
      row.key,
      code(row.direction),
      cell(numeric(row.estimates.sedan.cautious)),
      cell(numeric(row.estimates.sedan.assertive)),
      cell(numeric(row.estimates.compact.cautious)),
      cell(numeric(row.estimates.compact.assertive)),
      cell(numeric(row.agreement)),
      cell(numeric(row.tolerance.effective)),
      row.orderPreserved ? 'PASS' : 'FAIL',
      row.normalizedAgreement ? 'PASS' : 'FAIL',
    ].join(' | ') +
    ' |'
  );
}

function commonProfileRow(profile: CrossClassCommonProfile): string {
  return (
    '| ' +
    [
      profile.style,
      profile.derivedFrom,
      profile.values.map((value) => `${value.key}=${numeric(value.value)}`).join('; '),
      profile.sameAcrossDriverKinds ? 'PASS' : 'FAIL',
      profile.appliedToBothClasses ? 'PASS' : 'FAIL',
      profile.fleetApplication.every(
        (application) => application.classSpecificOverrides.length === 0,
      )
        ? 0
        : profile.fleetApplication.reduce(
            (total, application) => total + application.classSpecificOverrides.length,
            0,
          ),
    ].join(' | ') +
    ' |'
  );
}

export function crossClassFidelityReportMarkdown(report: CrossClassFidelityReport): string {
  const lines: string[] = [];
  lines.push(
    '# 106 cross-class fidelity report',
    '',
    'Machine-readable transcript: [report.json](report.json). Generated by ' +
      code('npm run learning:cross-class') +
      ';',
    'no wall-clock value, browser state, store, fleet or random source participates. Version: ' +
      code(CROSS_CLASS_FIDELITY_VERSION) +
      ';',
    'app adapter: ' +
      code(CROSS_CLASS_FIDELITY_APP_VERSION) +
      '; root seed: ' +
      String(report.rootSeed) +
      '; tick rate: ' +
      String(report.tickHz) +
      ' Hz.',
    '',
    '## Contract',
    '',
    'Classes: ' +
      report.contract.classes.join(', ') +
      '. Styles: ' +
      report.contract.styles.join(', ') +
      ' (' +
      report.contract.styles
        .map((style) => `${style}=${report.contract.styleSources[style]}`)
        .join(', ') +
      ').',
    'Scenarios: ' +
      report.contract.scenarios.join(', ') +
      '. Keys: ' +
      String(report.contract.keys.length) +
      '; trend keys: ' +
      String(report.contract.trendKeys.length) +
      '; per-key tolerances: ' +
      String(report.contract.tolerances.length) +
      '.',
    'The style targets are the 105 known-profile targets; the class ceilings come from the real 023',
    'catalog and are never redeclared here. The reference class is ' +
      code(report.contract.referenceClass) +
      '.',
    '',
    '## Summary',
    '',
    '- Style/class runs: ' + String(report.runs.length),
    '- Key rows: ' + String(report.overall.keyRows),
    '- Trend preserved: ' + code(report.trendPreserved),
    '- Normalized agreement: ' + code(report.normalizedAgreement),
    '- Mechanical capability copied: ' + code(report.mechanicalCopied),
    '- Common profile identical for TAXI/CIVILIAN: ' +
      code(report.overall.commonProfileSameAcrossKinds),
    '- MANUAL no learning: ' + code(report.overall.manualNoLearning),
    '- LEARNING eligible changed: ' + code(report.overall.learningEligibleChanged),
    '- LEARNING ineligible unchanged: ' + code(report.overall.learningIneligibleUnchanged),
    '- Same physical route in both modes: ' + code(report.overall.sameRoute),
    '- Unrepresentable behaviours reported: ' + code(report.overall.unrepresentableReported),
    '- Overall: ' + (report.overall.pass ? 'PASS' : 'FAIL'),
    '',
    '## Mechanical vs normalized',
    '',
    '| Class | Max accel | Max decel | Max lateral | Raw p50 accel | Raw p50 decel | Raw p50 lateral | Normalized accel | Normalized decel | Normalized lateral |',
    '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |',
    ...report.runs.map(
      (run) =>
        `| ${run.classId} | ${numeric(run.mechanical.capability.maxAccelerationMps2)} | ${numeric(run.mechanical.capability.maxDecelerationMps2)} | ${numeric(run.mechanical.capability.maxLateralAccelerationMps2)} | ${numeric(run.mechanical.rawP50.accelerationMps2)} | ${numeric(run.mechanical.rawP50.decelerationMps2)} | ${numeric(run.mechanical.rawP50.lateralMps2)} | ${numeric(run.mechanical.normalizedP50.acceleration)} | ${numeric(run.mechanical.normalizedP50.deceleration)} | ${numeric(run.mechanical.normalizedP50.lateral)} |`,
    ),
    '',
    'Raw SI values are class-specific. The normalized fractions are the style and are the only',
    'values eligible for the common profile.',
    '',
    '## Per-class/per-style recovery',
    '',
    '| Style | Class | Key | Target | Estimate | Tolerance | Episodes | Status |',
    '| --- | --- | --- | ---: | ---: | ---: | ---: | --- |',
    ...report.runs.flatMap((run) => run.keys.map((row) => keyRow(run, row))),
    '',
    '## Trend preservation and cross-class agreement',
    '',
    '| Key | Direction | Sedan cautious | Sedan assertive | Compact cautious | Compact assertive | Max diff | Tolerance | Order | Agreement |',
    '| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | --- | --- |',
    ...report.trend.map(trendRow),
    '',
    '## Common profile',
    '',
    '| Style | Derived from | Values | Same TAXI/CIVILIAN | Both classes | Class-specific overrides |',
    '| --- | --- | --- | --- | --- | ---: |',
    ...report.commonProfiles.map(commonProfileRow),
    '',
    'Copy detector: ' +
      code(report.mechanicalCopyCode ?? 'NONE') +
      '. A copied class ceiling or the non-reference class raw p50 is never a style value.',
    '',
    '## MANUAL vs LEARNING',
    '',
    '| Mode | Eligible | Profile changed | Candidate | Version | Reason | Gate | Route digest |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
    ...[
      report.modeFidelity.manual,
      report.modeFidelity.learningEligible,
      report.modeFidelity.learningIneligible,
    ].map(
      (result) =>
        `| ${result.mode} | ${result.eligible} | ${result.profileChanged} | ${result.candidate === null ? '—' : result.candidate.value} | ${cell(result.versionId)} | ${code(result.reason)} | ${code(result.gate.reason ?? result.gate.status)} | ${code(result.route.routeDigest)} |`,
    ),
    '',
    'Physical route identical across modes: ' + code(report.modeFidelity.routeIdentical) + '.',
    '',
    '## Unrepresentable behaviours',
    '',
    '| Behaviour | Result | Estimate | Key | Value | Reason |',
    '| --- | --- | --- | --- | --- | --- |',
    ...report.unrepresentable.map(
      (entry) =>
        `| ${entry.behaviour} | ${code(entry.result)} | ${cell(entry.estimate)} | ${cell(entry.key)} | ${cell(entry.value)} | ${code(entry.reason)} |`,
    ),
    '',
    'Out-of-scope manoeuvre: ' +
      code(report.outOfScopeManoeuvre.manoeuvre) +
      ' → ' +
      code(report.outOfScopeManoeuvre.result) +
      ' with ' +
      code('estimate: null') +
      '. ' +
      report.outOfScopeManoeuvre.description,
    '',
    '## Tolerances',
    '',
    '| Key | Absolute | Relative | Effective | Source |',
    '| --- | ---: | ---: | ---: | --- |',
    ...crossClassTolerances.map(
      (entry) =>
        `| ${entry.key} | ${entry.absoluteTolerance} | ${entry.relativeTolerance} | ${entry.effective} | ${code(entry.source)} |`,
    ),
    '',
    '## Limitations',
    '',
    '- Synthetic, deterministic observation streams, not captured gameplay or browser sessions.',
    '- The harness builds the 086/087/088 records and feeds the real 089 normalizer and the real',
    '  094/095 estimators; it does not run the 103 worker, a profile store or a real fleet.',
    '- The 094 curve candidate is reconstructed with the observed class ceiling, so its cross-class',
    '  SI agreement uses the documented wider 106 tolerance instead of the 105 inverse tolerance.',
    '- Tolerances are documented calibration bounds, not statistical confidence intervals.',
    '- No browser capture, FPS/GPU measurement or hardware claim is made.',
    '',
  );
  return lines.join('\n');
}
