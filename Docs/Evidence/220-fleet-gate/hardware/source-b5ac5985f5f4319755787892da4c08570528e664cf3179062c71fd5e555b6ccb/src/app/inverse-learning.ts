import {
  evaluateInverseLearning,
  INVERSE_LEARNING_TICK_HZ,
  inverseTolerances,
} from '../experiments';
import type { InverseKeyResult, InverseLearningPorts, InverseLearningReport } from '../experiments';

/** Report/composition layer for 105. It adds no UI, persistence or publication path. */
export const INVERSE_LEARNING_APP_VERSION = '105-inverse-learning-app-v1' as const;

export interface InverseLearningValidationOptions {
  /** Optional estimator overrides; the default run always uses the real 094–099 functions. */
  readonly ports?: Partial<InverseLearningPorts>;
}

/**
 * Runs the frozen inverse-validation report. The four known profiles and the three contract probes
 * are executed through the real estimators unless a caller deliberately injects a port.
 */
export function runInverseLearningValidation(
  options: InverseLearningValidationOptions = {},
): InverseLearningReport {
  return evaluateInverseLearning(options);
}

const BACKTICK = '`';

function code(value: string | number | boolean): string {
  return `${BACKTICK}${String(value)}${BACKTICK}`;
}

function cell(value: string | number | null): string {
  if (value === null) return '—';
  return String(value).replaceAll('|', '\\|');
}

function numeric(value: number | null, digits = 4): string | number | null {
  return value === null ? null : Number(value.toFixed(digits));
}

function resultRow(result: InverseKeyResult): string {
  const value = (input: string | number | null): string | number => (input === null ? '—' : input);
  return (
    '| ' +
    [
      result.key,
      value(numeric(result.target)),
      value(numeric(result.estimate)),
      result.interval === null
        ? '—'
        : `[${numeric(result.interval[0])}, ${numeric(result.interval[1])}]`,
      value(numeric(result.error)),
      value(numeric(result.tolerance.effective)),
      code(result.status),
      cell(result.reason),
      result.evidence.distinctEpisodes,
      code(result.evidence.status),
    ].join(' | ') +
    ' |'
  );
}

export function inverseLearningReportMarkdown(report: InverseLearningReport): string {
  const lines: string[] = [];
  lines.push(
    '# 105 inverse learning report',
    '',
    'Machine-readable transcript: [report.json](report.json). Generated by ' +
      code('npm run learning:inverse') +
      ';',
    'no wall-clock value, browser state or global random source participates. Version: ' +
      code(report.version) +
      ';',
    'app adapter: ' +
      code(INVERSE_LEARNING_APP_VERSION) +
      '; root seed: ' +
      String(report.rootSeed) +
      '; tick rate: ' +
      String(INVERSE_LEARNING_TICK_HZ) +
      ' Hz.',
    '',
    '## Contract',
    '',
    'Four known profiles (' +
      report.contract.profiles.join(', ') +
      ') are demonstrated through six independent',
    'scenario streams (' +
      report.contract.demonstrationScenarios.join(', ') +
      ') and the real 094–099',
    'estimators. Every one of the ' +
      String(report.contract.keys.length) +
      ' M keys has an explicit tolerance; R keys',
    'are excluded. Statuses: ' + report.contract.evaluationStatuses.join(', ') + '.',
    '',
    'The effective tolerance is ' +
      code('absolute + relative × |target|') +
      '. ' +
      String(inverseTolerances.length) +
      ' documented',
    'tolerances are declared in ' +
      code('src/experiments/inverse-learning.ts') +
      '; none is a shared default.',
    '',
    '## Summary',
    '',
    '- Keys evaluated: ' + String(report.overall.keysEvaluated),
    '- Within tolerance: ' + String(report.overall.withinTolerance),
    '- Outside tolerance: ' + String(report.overall.outsideTolerance),
    '- Not identifiable: ' + String(report.overall.notIdentifiable),
    '- No estimate: ' + String(report.overall.noEstimate),
    '- Profile failures (OUTSIDE/NO_ESTIMATE in the four profile runs): ' +
      String(report.overall.profileFailures),
    '- Retained probe failures: ' + String(report.overall.retainedProbeFailures),
    '- Overall: ' + (report.overall.pass ? 'PASS' : 'FAIL'),
    '',
  );

  const failures = report.scenarios.flatMap((scenario) =>
    scenario.results
      .filter((result) => result.status === 'OUTSIDE_TOLERANCE' || result.status === 'NO_ESTIMATE')
      .map(
        (result) =>
          '- ' +
          code(`${scenario.scenarioId}/${result.key}`) +
          ': ' +
          result.status +
          ' (target ' +
          String(result.target) +
          ', tolerance ' +
          String(result.tolerance.effective) +
          ')',
      ),
  );
  lines.push(
    '## Retained failures',
    '',
    failures.length === 0 ? 'None.' : failures.join('\n'),
    '',
    'The out-of-tolerance probe is expected to fail: it proves that a deliberately wrong estimate stays',
    'visible as ' +
      code('OUTSIDE_TOLERANCE') +
      ' instead of being hidden. A failing probe is therefore a detector',
    'failure, not a passing validation.',
    '',
  );

  for (const scenario of report.scenarios) {
    lines.push(
      '### ' + scenario.scenarioId,
      '',
      'Kind: ' +
        code(scenario.kind) +
        (scenario.probe === null ? '' : ' · probe ' + code(scenario.probe)) +
        ' · target profile: ' +
        code(scenario.profileId) +
        ' · expected failure: ' +
        code(scenario.expectedFailure),
      '',
      '| Within | Outside | Not identifiable | No estimate | Passed |',
      '| ---: | ---: | ---: | ---: | --- |',
      '| ' +
        String(scenario.withinTolerance) +
        ' | ' +
        String(scenario.outsideTolerance) +
        ' | ' +
        String(scenario.notIdentifiable) +
        ' | ' +
        String(scenario.noEstimate) +
        ' | ' +
        (scenario.passed ? 'PASS' : 'FAIL') +
        ' |',
      '',
      'Demonstration seeds: ' + scenario.demonstrationSeeds.join(', ') + '.',
      '',
      '| Key | Target | Estimate | Interval | Error | Tolerance | Status | Reason | Episodes | Evidence |',
      '| --- | ---: | ---: | --- | ---: | ---: | --- | --- | ---: | --- |',
      scenario.results.map(resultRow).join('\n'),
      '',
    );
  }

  lines.push(
    '## Limitations',
    '',
    '- Synthetic, deterministic observation streams, not captured gameplay or browser sessions.',
    '- The harness feeds the real estimators but supplies the 086/087/088 records itself; no worker,',
    '  profile store, publication, ledger write or MANUAL/AUTO learning path is exercised.',
    '- Opportunity kinds are identity carriers from the closed 086 vocabulary; the vocabulary has no',
    '  FOLLOWING kind, so leader/queue episodes attach to GREEN/STOP opportunities.',
    '- Interval keys (yield and lane gaps) are validated against their observed interval; the midpoint is',
    '  never reported as a precise point estimate.',
    '- Tolerances are documented starting values for calibration, not statistical confidence intervals.',
    '',
  );
  return lines.join('\n');
}
