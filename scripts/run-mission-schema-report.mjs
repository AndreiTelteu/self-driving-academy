import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  directory = join(root, 'Docs', 'Evidence', '116-mission-schema'),
  defaultOutput = join(directory, 'report.json'),
  reportMarkdown = join(directory, 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function markdown(report) {
  const checks = report.checks
      .map(
        (entry) =>
          `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
      )
      .join('\n'),
    catalog = report.catalog.rows
      .map(
        (row) =>
          `| \`${row.missionId}\` | ${row.version} | ${row.objectives
            .map((objective) => `${objective.kind}:${objective.target}`)
            .join(', ')} | ${row.rewards
            .map((reward) => `${reward.kind}${reward.amount > 0 ? `:${reward.amount}` : ''}`)
            .join(
              ', ',
            )} | ${row.replay.profileSource} | ${row.windowTicks ?? 'until completed'} | ${row.incidentBudget ?? 'none'} | ${row.prerequisites.join(', ') || '—'} |`,
      )
      .join('\n'),
    objectives = report.objectives.rows
      .map(
        (row) =>
          `| \`${row.objectiveId}\` | ${row.kind} | ${row.progress}/${row.target} | ${row.satisfied} |`,
      )
      .join('\n'),
    lifecycle = report.lifecycle,
    duplicates = report.duplicates,
    failure = report.failure,
    replay = report.replay,
    identity = report.identity,
    restore = report.restore,
    reset = report.reset,
    real = report.realSimulation,
    bounds = report.bounds;
  return `# 116 mission definitions and lifecycle report

Machine-readable transcript: [report.json](report.json). Generated by
\`${report.generatedBy}\`; the transcript has no wall-clock value and is deterministic.

Version: \`${report.version}\`. Namespace: \`${report.contract.namespace}\`.

Oracle rule: ${report.oracleRule}

## Catalog

| Mission | Version | Objectives | Rewards | Replay | Evaluation window | Incident budget | Prerequisites |
| --- | --- | --- | --- | --- | --- | --- | --- |
${catalog}

Campaign order from the prerequisite DAG: ${report.catalog.order.map((id) => `\`${id}\``).join(' → ')}.

## Objective probes

Mission state: ${report.objectives.state}. Each row is the real event payload result for one
objective kind; targets and the FULL_STOP floor come from the definition.

| Objective | Kind | Progress | Satisfied |
| --- | --- | --- | --- |
${objectives}

## Lifecycle over the real 007 bus

| Field | Value |
| --- | --- |
| Start state | ${lifecycle.startState} |
| Repeated start is a duplicate | ${lifecycle.duplicateStart} |
| Final state | ${lifecycle.state} |
| Objective progress / target | ${lifecycle.progress} / ${lifecycle.target} |
| Completed tick | ${lifecycle.completedTick} |
| Applied events | ${lifecycle.appliedEvents} |
| Rewards granted to the instance | ${lifecycle.rewardsGranted} |
| Reward ledger entries | ${lifecycle.rewardLedger} |
| Instances / active / completed | ${lifecycle.stats.instances} / ${lifecycle.stats.active} / ${lifecycle.stats.completed} |
| Accepted events / duplicates | ${lifecycle.stats.acceptedEvents} / ${lifecycle.stats.duplicates} |

## Duplicate events

| Field | Value |
| --- | --- |
| Manual start then duplicate, dropoff then duplicate | ${duplicates.manual.join(' → ')} |
| Objective progress after duplicates | ${duplicates.progressAfterDuplicates} |
| Mission state after duplicates | ${duplicates.stateAfterDuplicates} |
| Rewards after first delivery / after duplicate | ${duplicates.rewardsAfterFirst} / ${duplicates.rewardsAfterDuplicate} |
| Conflicting reuse of the same event id rejected | ${duplicates.conflictRejected} |
| Duplicate counter | ${duplicates.duplicates} |

## Failure

| Probe | State | Reason | Tick / incidents | Rewards |
| --- | --- | --- | --- | --- |
| Evaluation window | ${failure.window.state} | ${failure.window.reason} | ${failure.window.failedTick} | ${failure.window.rewards} |
| Incident budget | ${failure.incident.state} | ${failure.incident.reason} | ${failure.incident.incidents} | ${failure.incident.rewards} |

A late terminal event after the window leaves the instance at ${failure.window.lateCompletionState}.

## Replay

| Field | Value |
| --- | --- |
| First attempt | ${replay.firstState} |
| Replay attempt | ${replay.attempt} |
| Replayed-from matches | ${replay.replayedFromMatches} |
| New attempt state / progress | ${replay.state} / ${replay.progress} |
| Declared profile source | ${replay.profileSource} |
| Declared snapshot | ${replay.snapshotId} |
| Comparison profiles | ${replay.comparisonProfiles.join(', ')} |
| Rewards after first attempt / after replay / after third attempt | ${replay.rewardsAfterFirstAttempt} / ${replay.rewardsAfterReplay} / ${replay.rewardsAfterThirdAttempt} |
| Rewards granted to the third attempt | ${replay.rewardsGrantedThirdAttempt} |
| Refused reward duplicates | ${replay.rewardDuplicates} |

## Identity and version

| Field | Value |
| --- | --- |
| Namespace | ${identity.namespace} |
| Instance id prefix | ${identity.instanceIdPrefix} |
| Instance ids stable / attempts distinct | ${identity.instanceIdsStable} / ${identity.attemptsDistinct} |
| Reward id stable / version-scoped | ${identity.rewardIdStable} / ${identity.rewardVersionScoped} |
| Reward identity matches mission \`campaign-1-first-taxi@1\` | ${identity.rewardIdentityMatches} |

## Snapshot and restore

| Field | Value |
| --- | --- |
| Restored state / progress | ${restore.restoredState} / ${restore.restoredProgress} |
| Duplicate event after restore | ${restore.duplicateAfterRestore} |
| Continued state | ${restore.continuedState} |
| Rewards after the restored completion | ${restore.rewards} |
| Restored terminal state | ${restore.terminalState} |
| Replay attempt after restore | ${restore.replayAttempt} |
| Forged instance rejected | ${restore.forgedInstanceRejected} |
| Version mismatch rejected | ${restore.versionMismatchRejected} |

## Scenario reset

| Field | Value |
| --- | --- |
| Cleared instances / after reset | ${reset.clearedInstances} / ${reset.instancesAfter} |
| Rewards kept | ${reset.rewardsKept} |
| Re-started mission completed | ${reset.completedAfterReset} |
| Rewards after second completion | ${reset.rewardsAfterSecondCompletion} |
| Rewards granted to the second completion | ${reset.rewardsGrantedSecondCompletion} |
| Preserved processed events | ${reset.preservedEvents} |

## Real simulation

Real 057 fleet, real 059 schedule, real 060 assignments, real 061 lifecycle and real 063 dropoff
decisions feed the real 007 bus.

| Metric | Value |
| --- | --- |
| Real rides completed | ${real.rides} |
| Every 063 decision completed | ${real.allDecisionsCompleted} |
| Objective progress / state | ${real.progress} / ${real.state} |
| Rewards | ${real.rewards} |
| Accepted events | ${real.acceptedEvents} |
| Unique taxis / rides | ${real.uniqueTaxis} / ${real.uniqueRides} |
| First / last dropoff tick | ${real.firstDropoffTick} / ${real.lastDropoffTick} |

## Bounded work

| Metric | Value |
| --- | --- |
| Ingested events | ${bounds.ingested} |
| Retained event identities | ${bounds.retainedEvents} |
| Retained event code units | ${bounds.retainedEventCodeUnits} |
| Dropped identities (FIFO) | ${bounds.droppedEvents} |
| Active instances during the burst | ${bounds.activeInstances} |
| Retained per-instance evidence ids | ${bounds.recentEventsPerInstance} |
| Objective progress | ${bounds.objectiveProgress} |
| Very old duplicate outcome | ${bounds.ancientDuplicate} |

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'missions', 'mission-schema-report.ts')).href
  ),
  report = reportModule.runMissionSchemaReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, missions ${report.catalog.missions}, real rides ${report.realSimulation.rides}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`Mission schema report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`Mission schema report is current: ${output}`);
} else {
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
