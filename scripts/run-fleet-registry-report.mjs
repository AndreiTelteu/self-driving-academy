import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  defaultOutput = join(root, 'Docs', 'Evidence', '057-fleet-registry', 'report.json'),
  reportMarkdown = join(root, 'Docs', 'Evidence', '057-fleet-registry', 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(value) {
  return typeof value === 'string' ? value : JSON.stringify(value);
}

function markdown(report) {
  const configurations = report.configurations
    .map(
      (entry) =>
        `| ${entry.taxiCount}/${entry.civilianCount} | ${entry.report.total} | ${entry.report.taxis} | ${entry.report.civilians} | ${entry.report.byClass.sedan} | ${entry.report.byClass.compact} | ${entry.uniqueIds ? 'PASS' : 'FAIL'} | ${entry.deterministicAcrossRuns ? 'PASS' : 'FAIL'} | ${entry.stateIndependent ? 'PASS' : 'FAIL'} | ${entry.disposedToZero ? 'PASS' : 'FAIL'} |`,
    )
    .join('\n');
  const matrix = report.configurations
    .flatMap((entry) =>
      entry.report.matrix.map(
        (row) =>
          `| ${entry.taxiCount}/${entry.civilianCount} | ${row.driverKind} | ${row.classId} | ${row.count} |`,
      ),
    )
    .join('\n');
  const checks = report.checks
    .map(
      (entry) =>
        `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} |`,
    )
    .join('\n');
  const taxis = report.defaultTaxis
    .map(
      (vehicle) =>
        `| ${vehicle.slot} | ${vehicle.vehicleId} | ${vehicle.classId} | ${vehicle.appliedProfileVersion} |`,
    )
    .join('\n');
  return `# 057 fleet registry report

Machine-readable transcript: [report.json](report.json). Generated by
\`npm run fleet:registry\`; the transcript contains no wall-clock value and is deterministic.

Registry version: \`${report.registryVersion}\`; mechanical class version: \`${report.engineVersion}\`;
seed: ${report.seed}; scenario: \`${report.scenarioId}\`.

## Configured populations

| Taxis/civilians | Total | Taxis | Civilians | Sedan | Compact | Unique IDs | Deterministic | Independent state | Disposed to zero |
| --- | ---: | ---: | ---: | ---: | ---: | --- | --- | --- | --- |
${configurations}

## Counts by class and driverKind

| Taxis/civilians | driverKind | Class | Count |
| --- | --- | --- | ---: |
${matrix}

## Checks

| Check | Expected | Actual | Result |
| --- | --- | --- | --- |
${checks}

## Default taxi roster (24)

| Slot | Stable ID | Class | Applied profile |
| ---: | --- | --- | --- |
${taxis}

## State and vehicle field contracts

- Vehicle fields: ${report.vehicleFields.map((field) => `\`${field}\``).join(', ')}
- State fields: ${report.stateFields.map((field) => `\`${field}\``).join(', ')}

## Summary

- Configurations: ${report.summary.configurations}
- Checks: ${report.summary.checksPassed}/${report.summary.checks}
- Maximum population: ${report.summary.maximumVehicles}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'fleet', 'fleet-registry-report.ts')).href
  ),
  report = reportModule.runFleetRegistryReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const configuration of report.configurations)
  console.log(
    `${configuration.uniqueIds && configuration.deterministicAcrossRuns && configuration.stateIndependent && configuration.disposedToZero ? 'PASS' : 'FAIL'} ${configuration.taxiCount} taxis / ${configuration.civilianCount} civilians (${configuration.report.total} vehicles)`,
  );
for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY configurations ${report.summary.configurations}, checks ${report.summary.checksPassed}/${report.summary.checks}, maximum ${report.summary.maximumVehicles}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`Fleet registry report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`Fleet registry report is current: ${output}`);
} else {
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
