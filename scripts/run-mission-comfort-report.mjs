import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  directory = join(root, 'Docs', 'Evidence', '121-mission-comfort'),
  defaultOutput = join(directory, 'report.json'),
  reportMarkdown = join(directory, 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function markdown(report) {
  const checks = report.checks
      .map(
        (entry) =>
          `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
      )
      .join('\n'),
    scenarios = report.scenarios
      .map(
        (entry) =>
          `| ${entry.name} | ${entry.status} | ${entry.reason ?? '—'} | ${entry.peakAccelerationMps2} | ${entry.peakJerkMps3} | ${entry.accelerationSamples} | ${entry.jerkSamples} | ${entry.accelerationViolations} / ${entry.jerkViolations} | ${entry.excludedSpans} / ${entry.excludedSamples} / ${entry.excludedIntervals} | ${entry.teleports} |`,
      )
      .join('\n'),
    objective = report.objective,
    provenance = report.provenance,
    mission = report.mission;
  return `# 121 comfort objective report

Machine-readable transcript: [report.json](report.json). Generated by
\`${report.generatedBy}\`; the transcript has no wall-clock value and is deterministic.

Version: \`${report.version}\`. Tick rate: ${report.tickHz} Hz.

Oracle rule: ${report.oracleRule}

## Objective

| Field | Value |
| --- | --- |
| Objective id | \`${objective.objectiveId}\` |
| Passenger required | ${objective.passengerRequired} |
| Artifact policy | ${objective.artifactPolicy} |
| Style fidelity / style score | ${objective.separation.styleFidelity} / ${objective.separation.styleScore} |
| Acceleration threshold | ${objective.thresholds.maxAccelerationMps2} m/s² (${objective.thresholdSource.maxAccelerationMps2}) |
| Jerk threshold | ${objective.thresholds.maxJerkMps3} m/s³ (${objective.thresholdSource.maxJerkMps3}) |
| Evaluation window | ${objective.windowTicks} ticks |
| Minimum usable intervals | ${objective.minimumSamples} |

## Provenance

| Field | Value |
| --- | --- |
| Threshold keys | ${provenance.thresholdKeys.join(', ')} |
| Catalog acceleration default | ${provenance.catalogAcceleration} m/s² |
| Catalog jerk default | ${provenance.catalogJerk} m/s³ |
| Passenger ride states (061) | ${provenance.passengerRideStates.join(', ')} |
| Telemetry segments (085) | ${provenance.telemetrySegments.join(', ')} |
| Telemetry control mode | ${provenance.telemetryControlMode} |
| Telemetry learning eligible | ${provenance.telemetryLearningEligible} |
| Telemetry samples | ${provenance.telemetrySamples} |
| Derived vs recorded acceleration | ${provenance.derivedAgainstRecordedMps2} m/s² |

## Mission

| Field | Value |
| --- | --- |
| Mission id | \`${mission.missionId}\` |
| Title | ${mission.title} |
| Namespace | ${mission.namespace} |
| 116 objectives | ${mission.objectives.join(', ')} |
| Incident budget | ${mission.incidentBudget ?? 'none'} |
| Prerequisites | ${mission.prerequisites.join(', ') || '—'} |
| Comfort statuses | ${mission.statuses.join(', ')} |

## Scenarios

Every row is recorded by the real 085 tick-sample recorder and filtered by the real 088 artefact
filter; the thresholds are the shipped catalog defaults.

| Scenario | Status | Reason | Peak a (m/s²) | Peak jerk (m/s³) | a samples | jerk samples | Violations a / jerk | Spans / excluded samples / excluded intervals | Teleports |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${scenarios}

## Style separation

| Field | Value |
| --- | --- |
| Style fidelity in result | ${report.separation.styleFidelityInResult} |
| Style score used | ${report.separation.styleScoreUsed} |
| Injected style score rejected | ${report.separation.injectedStyleScoreRejected} |

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'missions', 'mission-comfort-report.ts')).href
  ),
  report = reportModule.runMissionComfortReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, scenarios ${report.scenarios.length}, teleports excluded ${report.scenarios.find((entry) => entry.name === 'recovery-segment-closed-088')?.teleports ?? 0}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`Mission comfort report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`Mission comfort report is current: ${output}`);
} else {
  await mkdir(directory, { recursive: true });
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
