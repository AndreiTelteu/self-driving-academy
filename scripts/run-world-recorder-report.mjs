function markdownCosts(cost) {
  const line = (label, stats) => `| ${label} | ${stats.min} | ${stats.median} | ${stats.max} |`;
  return `# 207 real world-recorder cost

Machine-readable values: [cost.json](cost.json). This is the only wall-clock measurement of PBI
207; it is **not** part of the deterministic transcript. It was produced by \`--cost\` on the machine
that ran it.

Contract: ${cost.contract}

- Samples: ${cost.sampleCount}
- Vehicles: ${cost.vehicles}
- Recorded ticks per sample: ${cost.recordedTicks}
- Chunk bytes: ${cost.chunkBytes}
- Peak charged bytes: ${cost.peakChargedBytes} of ${cost.ramByteCap}
- Measured at: ${cost.measuredAt}

| Phase | Min (ms) | Median (ms) | Max (ms) |
| --- | --- | --- | --- |
${[
  line('Record 600 ticks + 40 events', cost.recordTickMs),
  line('Seal one incident chunk', cost.sealChunkMs),
  line('Verify a sealed chunk', cost.readChunkMs),
].join('\n')}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'replay', 'world-recorder-report.ts')).href
  ),
  report = reportModule.runWorldRecorderReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`World recorder report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`World recorder report is current: ${output}`);
} else {
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}

if (process.argv.includes('--cost')) {
  const samples = Number(argument('--samples') ?? '20');
  const cost = reportModule.measureWorldRecorderCosts(
    Number.isSafeInteger(samples) && samples > 0 ? samples : 20,
  );
  await writeFile(costOutput, `${JSON.stringify(cost, null, 2)}\n`);
  await writeFile(costMarkdown, markdownCosts(cost));
  console.log(
    `COST record ${cost.recordTickMs.min}/${cost.recordTickMs.median}/${cost.recordTickMs.max} ms, seal ${cost.sealChunkMs.min}/${cost.sealChunkMs.median}/${cost.sealChunkMs.max} ms, read ${cost.readChunkMs.min}/${cost.readChunkMs.median}/${cost.readChunkMs.max} ms over ${cost.sampleCount} samples, chunk ${cost.chunkBytes} bytes`,
  );
  console.log(`Wrote ${costOutput}`);
  console.log(`Wrote ${costMarkdown}`);
}
