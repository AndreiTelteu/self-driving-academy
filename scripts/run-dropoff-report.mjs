import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  defaultOutput = join(root, 'Docs', 'Evidence', '063-dropoff', 'report.json'),
  reportMarkdown = join(root, 'Docs', 'Evidence', '063-dropoff', 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function markdown(report) {
  const checks = report.checks
      .map(
        (entry) =>
          `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
      )
      .join('\n'),
    reasons = report.checks.find((entry) => entry.name === 'rejection-reasons')?.actual ?? [],
    simulation = report.simulation,
    zoneRejections = report.zoneRejections;
  return `# 063 dropoff report

Machine-readable transcript: [report.json](report.json). Generated by
\`npm run ride:dropoff\`; the transcript contains no wall-clock value and is deterministic.

Version: \`${report.version}\`; ${report.fleet.taxis} taxis and ${report.fleet.civilians} civilians from
the real 057 registry, ${report.fleet.requests} requests from the real 059 schedule and real 060
assignments, resolved against the real 032 service-zone polygons.

## Rules

| Rule | Value |
| --- | ---: |
| Tick rate | ${report.defaults.tickRateHz} Hz |
| Speed threshold | ${report.defaults.speedThresholdMps} m/s |
| Required dwell | ${report.defaults.dwellTicks} ticks (${report.defaults.dwellTicks / report.defaults.tickRateHz} s) |
| Displacement tolerance | ${report.defaults.displacementToleranceM} m |

Closed rejection reasons: ${reasons.join(', ')}.

## Exact dwell

| Field | Value |
| --- | --- |
| Start tick | ${report.exactDwell.startTick} |
| Complete tick | ${report.exactDwell.completeTick} |
| Pending dwell before completion | ${report.exactDwell.pendingBeforeComplete} |
| Dwell at completion | ${report.exactDwell.dwellAtComplete} ticks (${report.exactDwell.dwellSeconds} s) |
| State after completion | ${report.exactDwell.stateAfterComplete} |
| Events | ${report.exactDwell.events.join(' → ')} |
| Transition ticks | ${report.exactDwell.transitionTicks.join(', ')} |
| Release reason / taxi status | ${report.exactDwell.releaseReason} / ${report.exactDwell.taxiStatus} |
| Trip metrics preserved | ${report.exactDwell.metricsPreserved} |
| Replay duplicate | ${report.exactDwell.replayDuplicate} |
| Transitions after replay | ${report.exactDwell.transitionsAfterReplay} |

## Rejections

| Probe | Result |
| --- | --- |
| Fast pass | ${report.fastPass.samples} samples (${report.fastPass.insideSamples} inside the zone), reasons ${report.fastPass.reasons.join(', ')}, max dwell ${report.fastPass.maxDwell}, state ${report.fastPass.state} |
| Outside the destination zone | ${zoneRejections.outside.samples} samples, ${zoneRejections.outside.reason} |
| Other authored dropoff zone (${zoneRejections.otherDropoffZone.zoneId}) | ${zoneRejections.otherDropoffZone.samples} samples, ${zoneRejections.otherDropoffZone.reason} |
| Pickup-only zone (${zoneRejections.pickupZone.zoneId}) | ${zoneRejections.pickupZone.samples} samples, ${zoneRejections.pickupZone.reason} |
| Incompatible destination id | ${report.incompatibleZone.reason}, in zone=${report.incompatibleZone.inDropoffZone} |
| Exact boundary | in zone=${report.boundary.exactBoundaryInZone}, ${report.boundary.exactBoundaryReason} |
| Just outside the boundary | ${report.boundary.outsideReason} |
| Re-entered zone | ${report.boundary.reentryReason}, completes at ${report.boundary.completeTick} |
| Unknown / foreign / not on trip / cancelled / failed ride | ${report.wrongRide.unknown} / ${report.wrongRide.foreign} / ${report.wrongRide.notOnTrip} / ${report.wrongRide.cancelled} / ${report.wrongRide.failed} |
| Stale before / after advance | ${report.stale.staleBefore} / ${report.stale.staleAfterAdvance} |
| Same-tick / later completion replay | ${report.idempotency.sameTickDuplicate} / ${report.idempotency.laterDuplicate} |
| Missing 060 claim | rejected=${report.release.attemptedCompletionRejected}, state ${report.release.stateAfterAttempt} |

## Manual and autonomous

| Metric | Value |
| --- | --- |
| Identical evaluation | ${report.equivalence.identical} |
| Manual / autonomous state | ${report.equivalence.manualState} / ${report.equivalence.autonomousState} |
| Manual / autonomous dwell | ${report.equivalence.manualDwellTicks} / ${report.equivalence.autonomousDwellTicks} ticks |
| Complete tick | ${report.equivalence.completeTick} |

## Simulation (real 059 schedule, real 060 dispatcher, real 062 pickup, real 032 zones)

| Metric | Value |
| --- | ---: |
| Requests | ${simulation.requests} |
| Assignments / boarded / completed | ${simulation.assignments} / ${simulation.boarded} / ${simulation.completed} |
| Failed / cancelled | ${simulation.failed} / ${simulation.cancelled} |
| Active after horizon | ${simulation.active} |
| Dispatcher releases | ${simulation.releases} |
| Unique dropoff zones | ${simulation.uniqueDropoffZones} |
| Unique completion event ids | ${simulation.uniqueCompleteEvents} |
| Delivery dwell min / max | ${simulation.minCompleteDwellTicks} / ${simulation.maxCompleteDwellTicks} |
| Rides with exact delivery dwell | ${simulation.exactDwellRides} |
| Pickup rejections / duplicates | ${simulation.pickupRejections} / ${simulation.pickupDuplicates} |
| Dropoff rejections / duplicates | ${simulation.dropoffRejections} / ${simulation.dropoffDuplicates} |
| Transitions per ride min / max | ${simulation.minTransitions} / ${simulation.maxTransitions} |
| Duplicate taxi ownership | ${simulation.duplicateTaxis} |

## Disposal

| Metric | Value |
| --- | --- |
| Disposed | ${report.disposal.disposed} |
| Attempts / completions after disposal | ${report.disposal.attempts} / ${report.disposal.completions} |
| Observations / completed / tick after disposal | ${report.disposal.observations} / ${report.disposal.completed} / ${report.disposal.tick} |
| Ride state / taxi status / releases | ${report.disposal.rideState} / ${report.disposal.taxiStatus} / ${report.disposal.releases} |

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'fleet', 'dropoff-report.ts')).href
  ),
  report = reportModule.runDropoffReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, completed ${report.simulation.completed}, dwell ${report.defaults.dwellTicks} ticks, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`Dropoff report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`Dropoff report is current: ${output}`);
} else {
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
