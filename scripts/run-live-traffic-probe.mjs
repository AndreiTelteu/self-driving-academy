import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { createServer } from 'node:http';
import { dirname, extname, join, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/**
 * PBI283 browser probe.
 *
 * It shows the real 036 signal state, an AI taxi stopped at its red movement, then takes that same
 * car over as a player (MANUAL) and crosses the authored stop line while the movement is still red.
 * The consequence is the live 283 violation event and the visible in-game notice. Playwright is
 * optional: without it the report is NOT_RUN with the real reason, never a fabricated PASS.
 */
const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  directory = join(root, 'Docs', 'Evidence', '283-live-traffic'),
  browserJson = join(directory, 'browser.json'),
  reportMarkdown = join(directory, 'browser.md'),
  screenshots = join(directory, 'screenshots'),
  buildDirectory = join(root, '.pbi-validation-283', 'build');

async function loadPlaywright() {
  const explicit = process.env.PLAYWRIGHT_MODULE;
  try {
    if (explicit) {
      const resolved = resolve(explicit);
      const entry = /\.(?:c|m)?js$/.test(resolved) ? resolved : join(resolved, 'index.js');
      return await import(pathToFileURL(entry).href);
    }
    return await import('playwright');
  } catch {
    return null;
  }
}

function mimeType(file) {
  return (
    {
      '.html': 'text/html; charset=utf-8',
      '.js': 'text/javascript; charset=utf-8',
      '.css': 'text/css; charset=utf-8',
      '.json': 'application/json',
      '.png': 'image/png',
      '.svg': 'image/svg+xml',
      '.wasm': 'application/wasm',
      '.glb': 'model/gltf-binary',
      '.ktx2': 'image/ktx2',
    }[extname(file)] ?? 'application/octet-stream'
  );
}

async function serve(directoryPath) {
  const server = createServer(async (request, response) => {
    try {
      if (request.method !== 'GET') {
        response.writeHead(405).end();
        return;
      }
      const url = new URL(request.url ?? '/', 'http://127.0.0.1');
      const pathname = decodeURIComponent(url.pathname);
      const file = resolve(directoryPath, '.' + (pathname === '/' ? '/index.html' : pathname));
      if (!file.startsWith(directoryPath + sep) || !(await stat(file)).isFile()) {
        response.writeHead(404).end();
        return;
      }
      const data = await readFile(file);
      response.writeHead(200, {
        'Content-Type': mimeType(file),
        'Cache-Control': 'no-store',
        'Content-Length': data.length,
      });
      response.end(data);
    } catch {
      response.writeHead(404);
      response.end();
    }
  });
  await new Promise((ready) => server.listen(0, '127.0.0.1', ready));
  const address = server.address();
  return {
    server,
    origin: `http://127.0.0.1:${typeof address === 'object' && address !== null ? address.port : 0}`,
  };
}

function markdown(result) {
  if (result.status === 'NOT_RUN') {
    return `# 283 - browser probe

Generated by \`npm run traffic:live:probe\` on ${result.generatedAt}.

**NOT_RUN** - ${result.reason}

No PASS is simulated. The deterministic CPU report and tests cover the signal/STOP/yield/lane
contracts; this probe alone would have shown the in-game red consequence.
`;
  }
  const run = result.run,
    checks = run.checks
      .map((check) => `- \`${check.name}\`: ${check.pass ? 'PASS' : 'FAIL'} - ${check.detail}`)
      .join('\n');
  return `# 283 - browser probe

Generated by \`npm run traffic:live:probe\` on ${result.generatedAt}; Chromium ${run.browser},
backend ${run.actualBackend}, viewport ${run.viewport}.

Real sequence in the browser fixture (same 032/033/058/283 modules, 2D canvas): live 036 red
movement -> AI taxi stopped at its own signal line -> explicit PLAYER authority on that same taxi
-> it crosses the authored line while the movement is still red -> the live 283 violation and the
visible fixture notice. Screenshots:
${(run.screenshots ?? []).map((file) => `[${file}](${file})`).join(', ')}.

${checks}

Limitation: the full Babylon shell pauses with the 012 overload cause in headless software
rendering before a 226 s signal cycle can be observed. This fixture drives the same authoritative
traffic/rules owners in a real Chromium page; it is not a hardware FPS/GPU gate and not a claim
that the full rendered shell was exercised end-to-end.
`;
}

const playwright = await loadPlaywright();
await mkdir(directory, { recursive: true });
await mkdir(screenshots, { recursive: true });
const generatedAt = new Date().toISOString();

if (playwright === null) {
  const result = {
    version: '283-live-traffic-browser-v1',
    generatedAt,
    status: 'NOT_RUN',
    reason:
      'Playwright is not installed in this checkout (no `playwright` module and no PLAYWRIGHT_MODULE); the browser probe was not run.',
    run: null,
  };
  await writeFile(browserJson, `${JSON.stringify(result, null, 2)}\n`);
  await writeFile(reportMarkdown, markdown(result));
  console.log(`Wrote ${browserJson}`);
  console.log(`Wrote ${reportMarkdown}`);
  console.log('Live traffic browser probe NOT_RUN: Playwright is not installed.');
  process.exit(0);
}

const { build } = await import('vite');
await build({
  configFile: join(root, 'vite.config.ts'),
  logLevel: 'error',
  build: {
    outDir: buildDirectory,
    emptyOutDir: true,
    rollupOptions: { input: join(root, 'tests', 'browser', 'traffic-rules', 'index.html') },
  },
});
const { server, origin } = await serve(buildDirectory);
const { chromium } = playwright.default ?? playwright;
const channel = process.env.PLAYWRIGHT_CHANNEL || undefined;
let browser;
try {
  browser = await chromium.launch({
    headless: true,
    ...(channel === undefined ? {} : { channel }),
    args: [
      '--use-gl=angle',
      '--use-angle=swiftshader',
      '--enable-unsafe-swiftshader',
      '--disable-gpu-sandbox',
      '--disable-frame-rate-limit',
    ],
  });
} catch (error) {
  const result = {
    version: '283-live-traffic-browser-v1',
    generatedAt,
    status: 'NOT_RUN',
    reason: `Browser launch failed: ${error instanceof Error ? error.message : String(error)}`,
    run: null,
  };
  await writeFile(browserJson, `${JSON.stringify(result, null, 2)}\n`);
  await writeFile(reportMarkdown, markdown(result));
  server.close();
  console.log('Live traffic browser probe NOT_RUN: browser launch failed.');
  process.exit(0);
}

const checks = [];
const check = (name, pass, detail) => checks.push({ name, pass, detail });
const pageErrors = [];
const consoleErrors = [];
let activePage = null;

try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 720 } });
  const page = await context.newPage();
  activePage = page;
  page.on('pageerror', (error) => pageErrors.push(String(error)));
  page.on('console', (message) => {
    if (message.type() === 'error') consoleErrors.push(message.text());
  });
  await page.bringToFront();
  await page.goto(`${origin}/tests/browser/traffic-rules/index.html`, {
    waitUntil: 'load',
    timeout: 90000,
  });
  const saveShot = async (name) =>
    page.screenshot({ path: join(screenshots, name), timeout: 120000 });
  await page.waitForFunction(
    () => {
      const probe = globalThis.__trafficProbe;
      return probe !== undefined && probe !== null && probe.status !== 'RUNNING';
    },
    null,
    { timeout: 180000, polling: 200 },
  );
  const stopped = await page.evaluate(() => globalThis.__trafficProbe);
  const aiStopped = stopped.status === 'AI_STOPPED' || stopped.status === 'VIOLATION';
  check(
    'ai-stops-at-red',
    aiStopped && stopped.actorId !== null && stopped.signal?.state === 'RED',
    aiStopped
      ? `${stopped.actorId} stopped at ${stopped.signal.signalId}/${stopped.signal.movementId} with a red movement; ${stopped.detail}`
      : `status ${stopped.status}: ${stopped.detail}`,
  );
  await saveShot('ai-stopped-at-red.png');
  await page.waitForFunction(
    () => {
      const probe = globalThis.__trafficProbe;
      return probe !== undefined && ['VIOLATION', 'PARTIAL', 'FAIL'].includes(probe.status);
    },
    null,
    { timeout: 180000, polling: 200 },
  );
  const final = await page.evaluate(() => globalThis.__trafficProbe);
  check(
    'player-crosses-on-red',
    final.status === 'VIOLATION' && final.violation !== null,
    final.status === 'VIOLATION' && final.violation !== null
      ? `${final.violation.eventId} at tick ${final.violation.tick}, signal ${final.violation.signalId}, line ${final.violation.stopLineId}, ${final.violation.frontDistanceBeforeM.toFixed(2)} -> ${final.violation.frontDistanceAfterM.toFixed(2)} m`
      : `status ${final.status}: ${final.detail}`,
  );
  const noticeVisible = await page.evaluate(() => {
    const node = globalThis.document.querySelector('#notice');
    return (
      node !== null &&
      node.style.display !== 'none' &&
      (node.textContent ?? '').includes('Încălcare')
    );
  });
  check(
    'visible-consequence',
    noticeVisible,
    noticeVisible
      ? 'the fixture #notice shows the real red-light violation'
      : 'the violation notice was not visible',
  );
  await saveShot('player-red-violation.png');
  check(
    'no-page-errors',
    pageErrors.length === 0,
    pageErrors.length === 0 ? 'no page errors' : pageErrors.join(' | '),
  );
  check(
    'no-console-errors',
    consoleErrors.length === 0,
    consoleErrors.length === 0 ? 'no console errors' : consoleErrors.join(' | '),
  );
  const pass = checks.every((entry) => entry.pass);
  const run = {
    browser: await browser.version(),
    actualBackend: 'CANVAS2D fixture over the real 032/033/058/283 modules',
    viewport: '900x620 fixture',
    stopped,
    final,
    noticeVisible,
    pageErrors,
    consoleErrors,
    checks,
    screenshots: ['screenshots/ai-stopped-at-red.png', 'screenshots/player-red-violation.png'],
  };
  const result = {
    version: '283-live-traffic-browser-v1',
    generatedAt,
    status: pass ? 'PASS' : 'PARTIAL',
    reason: pass ? null : 'one or more real browser checks failed; see checks',
    run,
  };
  await writeFile(browserJson, `${JSON.stringify(result, null, 2)}\n`);
  await writeFile(reportMarkdown, markdown(result));
  console.log(`Wrote ${browserJson}`);
  console.log(`Wrote ${reportMarkdown}`);
  console.log(
    `Live traffic browser probe ${result.status}: ${checks.filter((c) => c.pass).length}/${checks.length} checks`,
  );
} catch (error) {
  let diagnostics = null;
  if (activePage !== null) {
    try {
      diagnostics = await activePage.evaluate(() => ({
        bodyText: globalThis.document?.body?.innerText?.slice(0, 500) ?? '',
        shellState:
          globalThis.document?.querySelector('.game-shell')?.getAttribute('data-state') ?? null,
        ready: globalThis.__v3Composition?.ready?.() ?? null,
        hasApi: typeof globalThis.__v3Composition,
      }));
      await activePage.screenshot({ path: join(screenshots, 'failure.png'), timeout: 120000 });
    } catch {
      diagnostics = null;
    }
  }
  const result = {
    version: '283-live-traffic-browser-v1',
    generatedAt,
    status: 'FAIL',
    reason: error instanceof Error ? (error.stack ?? error.message) : String(error),
    run: { checks, pageErrors, consoleErrors, diagnostics },
  };
  await writeFile(browserJson, `${JSON.stringify(result, null, 2)}\n`);
  await writeFile(reportMarkdown, markdown(result));
  console.log(`Wrote ${browserJson}`);
  console.log(`Live traffic browser probe FAIL: ${result.reason.split('\n')[0]}`);
} finally {
  await browser.close();
  server.close();
}
