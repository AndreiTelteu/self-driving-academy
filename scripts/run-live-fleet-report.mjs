import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  directory = join(root, 'Docs', 'Evidence', '262-live-fleet'),
  reportJson = join(directory, 'report.json'),
  reportMarkdown = join(directory, 'report.md'),
  costJson = join(directory, 'cost.json');

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function markdown(report) {
  const fixtures = report.fixtures
      .map(
        (fixture) =>
          `| ${fixture.taxis} / ${fixture.civilians} | ${fixture.actors} | ${fixture.uniqueIds} | ${fixture.readyRoutes} | ${fixture.routesFromPlanner} | ${fixture.accessMatches} | ${fixture.uniqueOriginLanes} | ${fixture.onLane} |`,
      )
      .join('\n'),
    checks = report.checks
      .map(
        (entry) =>
          `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
      )
      .join('\n');
  return `# 262 live fleet report

Machine-readable transcript: [report.json](report.json). Generated by \`npm run fleet:live\`; the
transcript contains no wall-clock value and is deterministic.

Version: \`${report.version}\`; ambient contract: \`${report.contract.ambientVersion}\`; traffic:
\`${report.contract.trafficVersion}\`. Normal population: ${report.contract.normal.taxis} taxis +
${report.contract.normal.civilians} civilians. Limits: ${report.contract.limits.taxis[0]}–${report.contract.limits.taxis[1]} taxis,
${report.contract.limits.civilians[0]}–${report.contract.limits.civilians[1]} civilians, maximum
${report.contract.limits.vehicles} vehicles. Frame ceiling ${report.contract.frameVehicles} vehicles at
${report.contract.tickHz} Hz.

## Fixtures

| Taxis / civilians | Actors | Unique IDs | READY routes | Routes from 041 | Kind access | Unique origin lanes | On lane |
| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |
${fixtures}

## Spawn

| Metric | Value |
| --- | ---: |
| Player clearance (m) | ${report.spawn.clearanceToPlayerM} |
| Static vehicle clearance (m) | ${report.spawn.clearanceToStaticVehiclesM} |
| Minimum pairwise centre distance (m) | ${report.spawn.minimumPairwiseCentreM} |
| Overlapping SAT pairs | ${report.spawn.overlappingPairs} |
| Minimum decor gap (m) | ${report.spawn.minimumDecorGapM} |
| Unique origin lanes | ${report.spawn.uniqueOriginLanes} |
| Same seed deterministic | ${report.spawn.deterministic} |

## Off-camera simulation

| Metric | Value |
| --- | ---: |
| Observation window (m) | ${report.offCamera.windowM} |
| Ticks | ${report.offCamera.ticks} |
| Actors | ${report.offCamera.actors} |
| Actors starting outside the window | ${report.offCamera.outsideWindow} |
| Outside actors that moved | ${report.offCamera.outsideMoved} |
| Minimum outside move (m) | ${report.offCamera.minimumOutsideMoveM} |
| All actors that moved | ${report.offCamera.allMoved} |
| Last registry tick | ${report.offCamera.lastRegistryTick} |

## Profile

| Metric | Value |
| --- | ---: |
| Initial active version | \`${report.profile.initialVersion}\` |
| New active version | \`${report.profile.activeVersion}\` |
| Existing actors unchanged before refresh | ${report.profile.existingBeforeRefresh} |
| Existing actors on the active version after refresh | ${report.profile.existingAfterRefresh} |
| Unique versions after refresh | ${report.profile.uniqueVersionsAfterRefresh} |
| Common registry tick | ${report.profile.commonRegistryTick} |
| New taxi version | \`${report.profile.newTaxiVersion}\` |
| New civilian version | \`${report.profile.newCivilianVersion}\` |

## Cleanup

| Metric | Value |
| --- | ---: |
| Disposed | ${report.cleanup.disposed} |
| Actors | ${report.cleanup.actors} |
| Longitudinal actors | ${report.cleanup.longitudinalActors} |
| Road-context vehicles | ${report.cleanup.roadContextVehicles} |
| Registry vehicles | ${report.cleanup.registryVehicles} |
| Report vehicles | ${report.cleanup.reportVehicles} |
| Step after dispose rejected | ${report.cleanup.stepRejected} |

## Cost probe

The deterministic transcript above contains no timing. The separate 70-vehicle cost probe is written
by \`npm run fleet:live -- --measure\` to [cost.json](cost.json); it compares 40 civilians with
30 taxis + 40 civilians on the 058 traffic subsystem, 120 warmup ticks + 3 paired repetitions × 600
measured ticks, and uses the 8 ms laptop tick p95 budget from Docs/25. It is a headless subsystem
probe, not a browser frame or hardware certificate.

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const wantsCheck = process.argv.includes('--check'),
  wantsMeasure = process.argv.includes('--measure'),
  reportModule = await import(
    pathToFileURL(join(root, 'tests', 'fleet', 'live-fleet-report.ts')).href
  ),
  report = reportModule.runLiveFleetReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  md = markdown(report);

if (wantsCheck) {
  const savedJson = await readFile(reportJson, 'utf8').catch(() => null),
    savedMarkdown = await readFile(reportMarkdown, 'utf8').catch(() => null);
  if (savedJson !== json) console.error(`Live fleet report is stale: ${reportJson}`);
  if (savedMarkdown !== md) console.error(`Live fleet markdown is stale: ${reportMarkdown}`);
  if (savedJson !== json || savedMarkdown !== md) process.exitCode = 1;
  else console.log(`Live fleet report is current: ${reportJson}`);
  if (!report.summary.pass) process.exitCode = 1;
} else {
  await import('node:fs/promises').then(({ mkdir }) => mkdir(directory, { recursive: true }));
  await writeFile(reportJson, json);
  await writeFile(reportMarkdown, md);
  console.log(`Wrote ${reportJson}`);
  console.log(`Wrote ${reportMarkdown}`);
  for (const entry of report.checks) {
    if (!entry.pass) console.error(`FAIL ${entry.name}: ${value(entry.actual)}`);
  }
  console.log(
    `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, off-camera ${report.offCamera.outsideMoved}/${report.offCamera.outsideWindow}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
  );
  if (!report.summary.pass) process.exitCode = 1;
}

if (wantsMeasure) {
  const cost = reportModule.measureLiveFleetCost();
  await import('node:fs/promises').then(({ mkdir }) => mkdir(directory, { recursive: true }));
  await writeFile(costJson, `${JSON.stringify(cost, null, 2)}\n`);
  console.log(`Wrote ${costJson}`);
  console.log(
    `COST 40 civilians p95 ${cost.baseline40Civilians.p95Ms} ms, 70 vehicles p95 ${cost.live70Vehicles.p95Ms} ms, delta ${cost.additionalCostMs} ms, budget ${cost.protocol.budgetMs} ms, ${cost.pass ? 'PASS' : 'FAIL'}`,
  );
  if (!cost.pass) process.exitCode = 1;
}
