import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  directory = join(root, 'Docs', 'Evidence', '284-civil-autonomy'),
  reportJson = join(directory, 'report.json'),
  reportMarkdownPath = join(directory, 'report.md'),
  costJson = join(directory, 'cost.json'),
  costMarkdownPath = join(directory, 'cost.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function reportMarkdown(report) {
  const checks = report.checks
    .map(
      (entry) =>
        `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
    )
    .join('\n');
  return `# 284 civil autonomy report

Machine-readable transcript: [report.json](report.json). Generated by \`npm run civil:autonomy\`.
The transcript contains no wall-clock value and is deterministic for the same seed.

Contract: \`${report.version}\`; ${report.contract.civilians} civilians + ${report.contract.taxis} taxis,
${report.contract.tickHz} Hz, spawn clearance ${report.contract.spawnClearanceM} m.

## Rules on the live fleet

| Metric | Value |
| --- | ---: |
| Ticks | ${report.rules.ticks} |
| Actors | ${report.rules.actors} |
| 036 signals in the 044 frame | ${report.rules.signals} |
| Actors with a 283 command | ${report.rules.commandedActors} |
| Civil signal holds | ${report.rules.civilSignalHolds} |
| Civil STOP holds | ${report.rules.civilStopHolds} |
| Civil yield holds | ${report.rules.civilYieldHolds} |
| Civil lane-change requests | ${report.rules.civilLaneChanges} |
| Red stop episodes | ${report.rules.signalStops} |
| STOP approaches / full stops | ${report.rules.stopApproaches} / ${report.rules.stopFullStops} |
| Yield checks / holds | ${report.rules.yieldChecks} / ${report.rules.yieldHolds} |
| Lane changes validated / applied | ${report.rules.laneChangeValidated} / ${report.rules.laneChangeApplied} |
| Blocked reroutes / stays | ${report.rules.blockedReroutes} / ${report.rules.deadlockStays} |
| Moving actors | ${report.rules.movingActors}/${report.rules.actors} |
| Off-camera actors moving | ${report.rules.outsideMoved}/${report.rules.outsideWindow} |

## Recovery

| Metric | Value |
| --- | --- |
| Civil actor / lane | ${report.recovery.vehicleId} / ${report.recovery.laneId} |
| Destination lane | ${report.recovery.destinationLaneId} |
| Blocked episodes / decisions | ${report.recovery.blockedEpisodes} / ${report.recovery.blockedCommands} |
| Reroute requests / applied | ${report.recovery.rerouteRequests} / ${report.recovery.applied} |
| Recovery action | ${report.recovery.recoveryAction ?? 'none'} |

## Takeover and resume

| Metric | Value |
| --- | --- |
| Vehicle | ${report.takeover.vehicleId} |
| Route before / frozen / resumed | ${report.takeover.routeBefore.length} / ${report.takeover.routeAfterFreeze.length} / ${report.takeover.routeAfterResume.length} lanes |
| Destination before / after | ${report.takeover.destinationBefore ?? 'none'} / ${report.takeover.destinationAfter ?? 'none'} |
| Distance before / frozen / driven / resumed (m) | ${report.takeover.distanceBefore.toFixed(3)} / ${report.takeover.frozenDistance.toFixed(3)} / ${report.takeover.drivenDistance.toFixed(3)} / ${report.takeover.resumedDistance.toFixed(3)} |
| Frozen displacement (m) | ${report.takeover.freezeMovedM.toFixed(6)} |
| First AUTO step jump (m) | ${report.takeover.exitJumpM.toFixed(6)} |
| Resumed movement (m) | ${report.takeover.resumedMovedM.toFixed(3)} |
| Actors before / after | ${report.takeover.actorCountBefore} / ${report.takeover.actorCountAfter} |
| Authority during / after | ${report.takeover.authorityDuringManual} / ${report.takeover.authorityAfterResume} |

## Common profile and new vehicle

| Metric | Value |
| --- | ---: |
| Profile | ${report.profile.profileId} |
| Version before / after | ${report.profile.versionBefore} / ${report.profile.versionAfter} |
| Taxis / civilians refreshed | ${report.profile.taxisAfterRefresh} / ${report.profile.civiliansAfterRefresh} |
| New taxi / civilian version | ${report.profile.newTaxiVersion} / ${report.profile.newCivilianVersion} |
| New civilian player clearance (m) | ${report.profile.newCivilianClearanceM.toFixed(3)} |
| Registry / unique IDs | ${report.profile.registryVehicles} / ${report.profile.uniqueVehicleIds} |
| Actors before / after | ${report.profile.actorCountBefore} / ${report.profile.actorCountAfter} |

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

function costMarkdown(report) {
  const rows = report.samples
    .map(
      (sample) =>
        `| ${sample.classification} | ${sample.taxis} | ${sample.civilians} | ${sample.actors} | ${sample.p50Ms.toFixed(4)} | ${sample.p95Ms.toFixed(4)} | ${sample.p99Ms.toFixed(4)} | ${sample.maxMs.toFixed(4)} | ${sample.withinBudget ? 'PASS' : 'OVER'} |`,
    )
    .join('\n');
  return `# 284 civil autonomy cost

Machine-readable measurement: [cost.json](cost.json). Generated by \`npm run civil:autonomy:cost\`
on ${report.measuredAt}; Node ${report.environment.node}, ${report.environment.platform}/${report.environment.arch},
CPU ${report.environment.cpu ?? 'unknown'}, renderer NONE_HEADLESS.

Protocol: ${report.protocol.repetitions} repetitions × ${report.protocol.measuredTicks} measured ticks
after ${report.protocol.warmupTicks} warmup ticks; subsystem: ${report.protocol.subsystem}; budget
${report.protocol.budgetMs} ms p95 (${report.protocol.budgetSource}).

| Class | Taxis | Civilians | Actors | p50 (ms) | p95 (ms) | p99 (ms) | max (ms) | Budget |
| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |
${rows}

Extra p95 from 24 to 40 civilians: **${report.additional40Vs24P95Ms} ms**.

Normal 24–40 civilian gate: **${report.pass ? 'PASS' : 'FAIL'}** against the ${report.protocol.budgetMs} ms p95 budget.
30-taxi maximum workload, reported separately: **${report.stressPass ? 'PASS' : 'OVER_BUDGET'}**.

${report.limits.map((limit) => `- ${limit}`).join('\n')}
`;
}

await mkdir(directory, { recursive: true });
const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'fleet', 'civil-autonomy-report.ts')).href
  ),
  costMode = process.argv.includes('--cost');

if (costMode) {
  const cost = reportModule.measureCivilAutonomyCost(),
    json = `${JSON.stringify(cost, null, 2)}\n`,
    output = argument('--output') ?? costJson;
  for (const sample of cost.samples)
    console.log(
      `${sample.taxis} taxis + ${sample.civilians} civilians: p95 ${sample.p95Ms.toFixed(4)} ms, p99 ${sample.p99Ms.toFixed(4)} ms`,
    );
  console.log(
    `SUMMARY cost ${cost.samples.length} populations, normal budget ${cost.protocol.budgetMs} ms ${cost.pass ? 'PASS' : 'FAIL'}, 30-taxi stress ${cost.stressPass ? 'PASS' : 'OVER_BUDGET'}`,
  );
  if (process.argv.includes('--check')) {
    // A cost transcript contains wall-clock samples and a timestamp, so --check verifies the
    // committed measurement still passes the normal budget instead of comparing bytes.
    const saved = JSON.parse(await readFile(output, 'utf8'));
    const committedPass =
      saved.pass === true &&
      Array.isArray(saved.samples) &&
      saved.samples
        .filter((sample) => sample.classification === 'NORMAL')
        .every((sample) => sample.withinBudget === true);
    if (!committedPass) {
      console.error(`Civil autonomy cost report is outside budget: ${output}`);
      process.exitCode = 1;
    } else console.log(`Civil autonomy cost report is within budget: ${output}`);
  } else {
    await writeFile(output, json);
    await writeFile(costMarkdownPath, costMarkdown(cost));
    console.log(`Wrote ${output}`);
    console.log(`Wrote ${costMarkdownPath}`);
    if (!cost.pass) process.exitCode = 1;
  }
} else {
  const report = reportModule.runCivilAutonomyReport(),
    json = `${JSON.stringify(report, null, 2)}\n`,
    output = argument('--output') ?? reportJson;
  for (const entry of report.checks)
    console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
  console.log(
    `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, civil holds ${report.rules.civilSignalHolds} signal / ${report.rules.civilStopHolds} stop / ${report.rules.civilYieldHolds} yield, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
  );
  if (process.argv.includes('--check')) {
    const saved = await readFile(output, 'utf8');
    if (saved !== json) {
      console.error(`Civil autonomy report is stale: ${output}`);
      process.exitCode = 1;
    } else console.log(`Civil autonomy report is current: ${output}`);
  } else {
    await writeFile(output, json);
    await writeFile(reportMarkdownPath, reportMarkdown(report));
    console.log(`Wrote ${output}`);
    console.log(`Wrote ${reportMarkdownPath}`);
    if (!report.summary.pass) process.exitCode = 1;
  }
}
