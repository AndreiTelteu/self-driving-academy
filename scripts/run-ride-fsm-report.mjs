import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  defaultOutput = join(root, 'Docs', 'Evidence', '061-ride-fsm', 'report.json'),
  reportMarkdown = join(root, 'Docs', 'Evidence', '061-ride-fsm', 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function markdown(report) {
  const checks = report.checks
      .map(
        (entry) =>
          `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
      )
      .join('\n'),
    states = report.checks.find((entry) => entry.name === 'states')?.actual ?? [],
    transitions = report.checks.find((entry) => entry.name === 'transitions')?.actual ?? {},
    transitionRows = Object.entries(transitions)
      .map(
        ([from, targets]) =>
          `| ${from} | ${targets.length === 0 ? 'terminal' : targets.join(', ')} |`,
      )
      .join('\n'),
    simulation = report.simulation,
    restore = report.restore,
    selection = report.selection,
    reasons = report.reasons;
  return `# 061 ride lifecycle report

Machine-readable transcript: [report.json](report.json). Generated by
\`npm run ride:lifecycle\`; the transcript contains no wall-clock value and is deterministic.

Version: \`${report.version}\`; ${report.fleet.taxis} taxis and ${report.fleet.civilians} civilians from
the real 057 registry, ${report.fleet.requests} requests from the real 059 schedule and real 060
assignments.

## States and transitions

States: ${states.join(' → ')}. Each edge is listed below; terminal states have no outgoing edge.

| From | Allowed targets |
| --- | --- |
${transitionRows}

Failure reasons: ${report.checks.find((entry) => entry.name === 'closed-vocabularies')?.expected.failureReasons ?? 'n/a'} closed values.
Cancellation reasons: ${report.checks.find((entry) => entry.name === 'closed-vocabularies')?.expected.cancelReasons ?? 'n/a'} closed values.

## Full path

| Field | Value |
| --- | --- |
| States | ${report.path.states.join(' → ')} |
| Events | ${report.path.events.join(' → ')} |
| Transitions | ${report.path.transitions} |
| Release reason | ${report.path.releaseReason} |
| Assignment released | ${report.path.assignmentReleased} |
| Taxi status / available | ${report.path.taxiStatus} / ${report.path.available} |

## Terminal outcomes

| Probe | State | Reason | Dispatcher release | Assignment released | Taxi status |
| --- | --- | --- | --- | --- | --- |
| Complete | ${report.path.states.at(-1)} | none | ${report.path.releaseReason} | ${report.path.assignmentReleased} | ${report.path.taxiStatus} |
| Cancel | ${report.cancel.state} | ${report.cancel.reason} | ${report.cancel.releaseReason} | ${report.cancel.assignmentReleased} | ${report.cancel.taxiStatus} |
| Fail | ${report.failure.state} | ${report.failure.reason} | ${report.failure.releaseReason} | ${report.failure.assignmentReleased} | ${report.failure.taxiStatus} |

## Rejection probes

| Probe | Result |
| --- | --- |
| Duplicate event | begin=${report.duplicates.beginDuplicate}, replay=${report.duplicates.replayDuplicate}, transitions=${report.duplicates.transitionsAfterReplay}, releases=${report.duplicates.releasesAfterReplay} |
| Conflicting event id | rejected=${report.duplicates.conflictRejected} |
| Illegal transition | rejected=${report.illegal.rejected}, state=${report.illegal.stateAfter}, releases=${report.illegal.releasesAfter}, claim=${report.illegal.claimIntact} |
| Double terminal | rejected=${report.doubleTerminal.rejected}, state=${report.doubleTerminal.state}, releases=${report.doubleTerminal.releases}, transitions=${report.doubleTerminal.transitions} |
| Stale tick | event=${report.stale.eventRejected}, advance=${report.stale.advanceRejected}, tick=${report.stale.tick}, state=${report.stale.stateAfter} |
| Missing failure reason | rejected=${reasons.missingFailureRejected} |
| Missing cancel reason | rejected=${reasons.missingCancelRejected} |
| Wrong reason vocabulary | rejected=${reasons.wrongVocabularyRejected} |
| Reason on progress | rejected=${reasons.reasonOnProgressRejected}, release=${reasons.releaseOnProgress} |
| Terminal without claim | external=${report.claimLeak.externalReleaseReason}, rejected=${report.claimLeak.terminalRejected}, state=${report.claimLeak.stateAfter}, lifecycle releases=${report.claimLeak.lifecycleReleases} |
| Selection change | retarget rejected=${selection.retargetRejected}, ride state=${selection.firstState}, claim=${selection.claimIntact}, releases=${selection.releases} |

## Restore

| Field | Value |
| --- | --- |
| Restored state | ${restore.restoredState} |
| Taxi matches dispatcher claim | ${restore.restoredTaxiMatches} |
| Restored event ids | ${restore.appliedEventIds} |
| Duplicate replay after restore | ${restore.duplicateAfterRestore} |
| Terminal ride rejected | ${restore.terminalRejected} |
| Unclaimed ride rejected | ${restore.unclaimedRejected} |
| Continued state | ${restore.continuedState} |

## Simulation (real 059 schedule, real 060 dispatcher)

| Metric | Value |
| --- | ---: |
| Ticks | 1501 |
| Assignments / rides begun | ${simulation.assignments} |
| Completed / failed / cancelled | ${simulation.completed} / ${simulation.failed} / ${simulation.cancelled} |
| Active rides after horizon | ${simulation.active} |
| Explicit dispatcher releases | ${simulation.releases} |
| Dispatcher claims left | ${simulation.dispatcherAssignments} |
| Unique rides / taxis | ${simulation.uniqueRides} / ${simulation.uniqueTaxis} |
| Max concurrent rides | ${simulation.maxConcurrentRides} |
| Duplicate taxi ownership | ${simulation.duplicateTaxis} |
| First / last begin tick | ${simulation.firstBeginTick} / ${simulation.lastBeginTick} |

## Disposal and identity

| Metric | Value |
| --- | --- |
| Disposed | ${report.disposal.disposed} |
| Rides / active / releases after disposal | ${report.disposal.rides} / ${report.disposal.active} / ${report.disposal.releases} |
| Injected claim kept | ${report.disposal.claimKept} |
| Ride id derived from request namespace | ${report.identity.rideIdDerived} |
| Transition ids stable / unique | ${report.identity.transitionIdsStable} / ${report.identity.transitionIdsUnique} |

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'fleet', 'ride-fsm-report.ts')).href
  ),
  report = reportModule.runRideFsmReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, rides ${report.simulation.assignments}, releases ${report.simulation.releases}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`Ride lifecycle report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`Ride lifecycle report is current: ${output}`);
} else {
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
