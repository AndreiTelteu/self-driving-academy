import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { createServer } from 'node:http';
import { dirname, extname, join, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/**
 * PBI284 browser probe.
 *
 * The real 032/033/058/283 composition runs in Chromium. A live civil AI is observed stopped in
 * traffic, taken over through the real composition, driven by the PLAYER seat, braked, exited and
 * resumed in AUTO. The probe reads only the authoritative composition/civil read model. Playwright
 * is optional: without it the report is NOT_RUN with the real reason, never a fabricated PASS.
 */
const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  directory = join(root, 'Docs', 'Evidence', '284-civil-autonomy'),
  browserJson = join(directory, 'browser.json'),
  browserMarkdown = join(directory, 'browser.md'),
  screenshots = join(directory, 'screenshots'),
  buildDirectory = join(root, '.pbi-validation-284', 'build');

async function loadPlaywright() {
  const explicit = process.env.PLAYWRIGHT_MODULE;
  try {
    if (explicit) {
      const resolved = resolve(explicit);
      const entry = /\.(?:c|m)?js$/.test(resolved) ? resolved : join(resolved, 'index.js');
      return await import(pathToFileURL(entry).href);
    }
    return await import('playwright');
  } catch {
    return null;
  }
}

function mimeType(file) {
  return (
    {
      '.html': 'text/html; charset=utf-8',
      '.js': 'text/javascript; charset=utf-8',
      '.css': 'text/css; charset=utf-8',
      '.json': 'application/json',
      '.png': 'image/png',
      '.svg': 'image/svg+xml',
      '.wasm': 'application/wasm',
      '.glb': 'model/gltf-binary',
      '.ktx2': 'image/ktx2',
    }[extname(file)] ?? 'application/octet-stream'
  );
}

async function serve(directoryPath) {
  const server = createServer(async (request, response) => {
    try {
      if (request.method !== 'GET') {
        response.writeHead(405).end();
        return;
      }
      const url = new URL(request.url ?? '/', 'http://127.0.0.1'),
        pathname = decodeURIComponent(url.pathname);
      if (pathname === '/favicon.ico') {
        response.writeHead(204).end();
        return;
      }
      const file = resolve(directoryPath, '.' + (pathname === '/' ? '/index.html' : pathname));
      if (!file.startsWith(directoryPath + sep) || !(await stat(file)).isFile()) {
        response.writeHead(404).end();
        return;
      }
      const data = await readFile(file);
      response.writeHead(200, {
        'Content-Type': mimeType(file),
        'Cache-Control': 'no-store',
        'Content-Length': data.length,
      });
      response.end(data);
    } catch {
      response.writeHead(404);
      response.end();
    }
  });
  await new Promise((ready) => server.listen(0, '127.0.0.1', ready));
  const address = server.address(),
    origin = `http://127.0.0.1:${
      typeof address === 'object' && address !== null ? address.port : 0
    }`;
  return { server, origin };
}

function markdown(result) {
  if (result.status === 'NOT_RUN') {
    return `# 284 — browser probe

Generated by \`npm run civil:autonomy:probe\` on ${result.generatedAt}.

**NOT_RUN** — ${result.reason}

No PASS is simulated. The deterministic 284 report and tests cover the same takeover, suspension
and resume contract.
`;
  }
  const run = result.run,
    checks = run.checks
      .map((check) => `- \`${check.name}\`: ${check.pass ? 'PASS' : 'FAIL'} — ${check.detail}`)
      .join('\n');
  return `# 284 — browser probe

Generated by \`npm run civil:autonomy:probe\` on ${result.generatedAt}; Chromium ${run.browser},
fixture ${run.viewport}. The probe runs the real 032/033/058/283 composition in a Chromium page.

Real sequence: a civil AI is observed stopped (30 consecutive ticks, no leader) → the composition
takes it over as MANUAL → its 058 route is suspended → the PLAYER drives it → brake → exit → the same
actor returns to AUTO and resumes. Screenshots: ${(run.screenshots ?? []).map((file) => `[${file}](${file})`).join(', ')}.

| Metric | Value |
| --- | --- |
| Vehicle | ${run.vehicleId} |
| Route before / after | ${run.routeBefore.length} / ${run.routeAfter.length} lanes |
| Destination before / after | ${run.destinationBefore} / ${run.destinationAfter} |
| Suspended route drift | ${run.frozenDeltaM} m |
| Player-driven distance | ${run.drivenM} m |
| Exit jump | ${run.exitJumpM} m |
| Resumed movement | ${run.resumedM} m |
| Actors before / after | ${run.actorCountBefore} / ${run.actorCountAfter} |
| Authority after exit | ${run.authority} |

${checks}

Final status: **${result.status}** — ${result.reason ?? 'all checks passed'}.

Limitation: this is a Chromium fixture over the real composition modules and a 2D canvas, not the
fully rendered Babylon shell; it is not a hardware FPS/GPU gate.
`;
}

const playwright = await loadPlaywright();
await mkdir(directory, { recursive: true });
await mkdir(screenshots, { recursive: true });
const generatedAt = new Date().toISOString();

if (playwright === null) {
  const result = {
    version: '284-civil-autonomy-browser-v1',
    generatedAt,
    status: 'NOT_RUN',
    reason:
      'Playwright is not installed in this checkout (no `playwright` module and no PLAYWRIGHT_MODULE); the browser probe was not run.',
    run: null,
  };
  await writeFile(browserJson, `${JSON.stringify(result, null, 2)}\n`);
  await writeFile(browserMarkdown, markdown(result));
  console.log(`Wrote ${browserJson}`);
  console.log(`Wrote ${browserMarkdown}`);
  console.log('Civil autonomy browser probe NOT_RUN: Playwright is not installed.');
  process.exit(0);
}

const { build } = await import('vite');
await build({
  configFile: join(root, 'vite.config.ts'),
  logLevel: 'error',
  build: {
    outDir: buildDirectory,
    emptyOutDir: true,
    rollupOptions: { input: join(root, 'tests', 'browser', 'civil-autonomy', 'index.html') },
  },
});
const { server, origin } = await serve(buildDirectory);
const { chromium } = playwright.default ?? playwright;
const channel = process.env.PLAYWRIGHT_CHANNEL || undefined;
let browser;
try {
  browser = await chromium.launch({
    headless: true,
    ...(channel === undefined ? {} : { channel }),
    args: [
      '--use-gl=angle',
      '--use-angle=swiftshader',
      '--enable-unsafe-swiftshader',
      '--disable-gpu-sandbox',
      '--disable-frame-rate-limit',
    ],
  });
} catch (error) {
  const result = {
    version: '284-civil-autonomy-browser-v1',
    generatedAt,
    status: 'NOT_RUN',
    reason: `Browser launch failed: ${error instanceof Error ? error.message : String(error)}`,
    run: null,
  };
  await writeFile(browserJson, `${JSON.stringify(result, null, 2)}\n`);
  await writeFile(browserMarkdown, markdown(result));
  server.close();
  console.log('Civil autonomy browser probe NOT_RUN: browser launch failed.');
  process.exit(0);
}

const pageErrors = [];
const consoleErrors = [];
let activePage = null;
try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 720 } });
  const page = await context.newPage();
  activePage = page;
  page.on('pageerror', (error) => pageErrors.push(String(error)));
  page.on('console', (message) => {
    if (message.type() === 'error') consoleErrors.push(message.text());
  });
  await page.bringToFront();
  await page.goto(`${origin}/tests/browser/civil-autonomy/index.html`, {
    waitUntil: 'load',
    timeout: 90000,
  });
  const captured = [];
  try {
    await page.waitForFunction(() => globalThis.__civilAutonomyProbe?.status === 'STOPPED', null, {
      timeout: 240000,
      polling: 100,
    });
    await page.screenshot({ path: join(screenshots, 'civil-stopped.png'), timeout: 120000 });
    captured.push('screenshots/civil-stopped.png');
    await page.waitForFunction(() => globalThis.__civilAutonomyProbe?.status === 'DRIVEN', null, {
      timeout: 120000,
      polling: 50,
    });
    await page.screenshot({ path: join(screenshots, 'civil-driven.png'), timeout: 120000 });
    captured.push('screenshots/civil-driven.png');
  } catch {
    // A real transition may be too fast for the capture; the terminal evidence is still recorded.
  }
  const terminal = ['PASS', 'PARTIAL', 'FAIL'];
  await page.waitForFunction(
    (terminalStates) => {
      const probe = globalThis.__civilAutonomyProbe;
      return probe !== undefined && probe !== null && terminalStates.includes(probe.status);
    },
    terminal,
    { timeout: 240000, polling: 200 },
  );
  const state = await page.evaluate(() => globalThis.__civilAutonomyProbe);
  const checks = [...state.checks];
  checks.push(
    {
      name: 'browser-status',
      pass: state.status === 'PASS',
      detail: `terminal status ${state.status}`,
    },
    {
      name: 'no-page-errors',
      pass: pageErrors.length === 0,
      detail: pageErrors.length === 0 ? 'no page errors' : pageErrors.join(' | '),
    },
    {
      name: 'no-console-errors',
      pass: consoleErrors.length === 0,
      detail: consoleErrors.length === 0 ? 'no console errors' : consoleErrors.join(' | '),
    },
  );
  const pass = state.status === 'PASS' && checks.every((check) => check.pass);
  await page.screenshot({ path: join(screenshots, 'civil-resumed.png'), timeout: 120000 });
  captured.push('screenshots/civil-resumed.png');
  const run = {
    browser: await browser.version(),
    viewport: '1280x720',
    status: state.status,
    vehicleId: state.vehicleId,
    routeBefore: state.routeBefore,
    routeAfter: state.routeAfter,
    destinationBefore: state.destinationBefore,
    destinationAfter: state.destinationAfter,
    frozenDeltaM: state.frozenDeltaM,
    drivenM: state.drivenM,
    ambientMoveM: state.ambientMoveM,
    exitJumpM: state.exitJumpM,
    exitDetail: state.exitDetail,
    resumedM: state.resumedM,
    actorCountBefore: state.actorCountBefore,
    actorCountAfter: state.actorCountAfter,
    authority: state.authority,
    checks,
    trace: state.trace,
    pageErrors,
    consoleErrors,
    screenshots: captured,
  };
  const result = {
    version: '284-civil-autonomy-browser-v1',
    generatedAt,
    status: pass ? 'PASS' : 'PARTIAL',
    reason: pass ? null : (state.error ?? 'one or more real browser checks failed; see checks'),
    run,
  };
  await writeFile(browserJson, `${JSON.stringify(result, null, 2)}\n`);
  await writeFile(browserMarkdown, markdown(result));
  console.log(`Wrote ${browserJson}`);
  console.log(`Wrote ${browserMarkdown}`);
  console.log(
    `Civil autonomy browser probe ${result.status}: ${checks.filter((check) => check.pass).length}/${checks.length} checks`,
  );
} catch (error) {
  let diagnostics = null;
  if (activePage !== null) {
    try {
      diagnostics = await activePage.evaluate(() => ({
        bodyText: globalThis.document?.body?.innerText?.slice(0, 500) ?? '',
        probe: globalThis.__civilAutonomyProbe ?? null,
        hasApi: typeof globalThis.__civilAutonomyProbe,
      }));
      await activePage.screenshot({ path: join(screenshots, 'failure.png'), timeout: 120000 });
    } catch {
      diagnostics = null;
    }
  }
  const result = {
    version: '284-civil-autonomy-browser-v1',
    generatedAt,
    status: 'FAIL',
    reason: error instanceof Error ? (error.stack ?? error.message) : String(error),
    run: { checks: [], pageErrors, consoleErrors, diagnostics, screenshots: [] },
  };
  await writeFile(browserJson, `${JSON.stringify(result, null, 2)}\n`);
  await writeFile(browserMarkdown, markdown(result));
  console.log(`Wrote ${browserJson}`);
  console.log(`Wrote ${browserMarkdown}`);
  console.log(`Civil autonomy browser probe FAIL: ${result.reason.split('\n')[0]}`);
} finally {
  await browser.close();
  server.close();
}
