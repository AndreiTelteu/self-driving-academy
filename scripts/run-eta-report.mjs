import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  defaultOutput = join(root, 'Docs', 'Evidence', '064-eta', 'report.json'),
  reportMarkdown = join(root, 'Docs', 'Evidence', '064-eta', 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function markdown(report) {
  const checks = report.checks
      .map(
        (entry) =>
          `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
      )
      .join('\n'),
    reasons = report.checks.find((entry) => entry.name === 'unavailable-reasons')?.actual ?? [],
    basis = report.routeBasis,
    remaining = report.remainingRoute,
    monotonic = report.monotonic,
    reprojection = report.reprojection,
    antiSnap = report.antiSnap,
    missing = report.missingRoute,
    invalid = report.invalidRoutes,
    stale = report.staleRoute,
    service = report.service,
    reroute = report.reroute,
    arrivals = report.arrivals,
    simulation = report.simulation;
  return `# 064 ETA report

Machine-readable transcript: [report.json](report.json). Generated by
\`npm run ride:eta\`; the transcript contains no wall-clock value and is deterministic.

Version: \`${report.version}\`; ${report.fleet.taxis} taxis and ${report.fleet.civilians} civilians from
the real 057 registry, ${report.fleet.requests} requests from the real 059 schedule, real 060
assignments and the real 041 routes over the real 032 map.

## Rules

| Rule | Value |
| --- | ---: |
| Tick rate | ${report.defaults.tickRateHz} Hz |
| Off-route tolerance | ${report.defaults.offRouteToleranceM} m |
| Forward reprojection window | ${report.defaults.reprojectionLanes} lanes |
| Service state | ${report.defaults.serviceState} |
| Active estimates | ${report.limits.rides} |
| Lanes per route | ${report.limits.routeLanes} |

Closed unavailable reasons: ${reasons.join(', ')}.

Uncertainty (speed factors around the real route basis):

| Service | Nominal | Min | Max |
| --- | ---: | ---: | ---: |
| FREE_FLOW | ${report.uncertainty.FREE_FLOW.nominalSpeedFactor} | ${report.uncertainty.FREE_FLOW.minSpeedFactor} | ${report.uncertainty.FREE_FLOW.maxSpeedFactor} |
| CONGESTED | ${report.uncertainty.CONGESTED.nominalSpeedFactor} | ${report.uncertainty.CONGESTED.minSpeedFactor} | ${report.uncertainty.CONGESTED.maxSpeedFactor} |
| BLOCKED | — | — | — |

## Route basis

| Field | Value |
| --- | --- |
| Route lanes | ${basis.routeLaneIds.join(' → ')} |
| Route distance | ${basis.totalDistanceM} m |
| Planned mean speed | ${basis.plannedSpeedMps} m/s |
| Real 041 pickup cost | ${basis.pickupCostSeconds} s |
| Planned remaining time | ${basis.plannedRemainingSeconds} s |
| ETA / min / max | ${basis.etaSeconds} / ${basis.etaMinSeconds} / ${basis.etaMaxSeconds} s |
| Bounds ordered | ${basis.boundsOrdered} |
| Initial progress | ${basis.initialProgress} |

## Remaining route and monotonic progress

| Probe | Result |
| --- | --- |
| Full leg ETA | ${remaining.fullEtaSeconds} s |
| Near-end ETA | ${remaining.nearEndEtaSeconds} s at progress ${remaining.nearEndProgress} |
| Near-end / full ratio | ${remaining.nearEndRatio} |
| Progress before backward observation | ${monotonic.progressBefore} |
| Progress after backward observation | ${monotonic.progressAfterBackward} |
| Backward reason / ETA | ${monotonic.backwardReason} / ${monotonic.backwardEta} |
| No rewind | ${monotonic.noRewind} |
| Forward progress afterwards | ${monotonic.forwardProgress} |

## Reprojection

| Probe | Result |
| --- | --- |
| Adjacent lane | ${reprojection.adjacentLaneId} at ${reprojection.adjacentDistanceM} m |
| Adjacent status / segment | ${reprojection.adjacentStatus} / ${reprojection.adjacentSegmentIndex} ${reprojection.adjacentSegmentLaneId} (reprojected=${reprojection.adjacentReprojected}) |
| Intersection gap status | ${reprojection.gapStatus} (${reprojection.gapKind} to ${reprojection.gapSegmentLaneId}) |
| Gap distance / progress / ETA | ${reprojection.gapOffRouteDistanceM} m / ${reprojection.gapProgress} / ${reprojection.gapEta} s |
| Backward anti-snap reason | ${antiSnap.reason} |
| Progress before / after | ${antiSnap.progressBefore} / ${antiSnap.progressAfter} (preserved=${antiSnap.progressPreserved}) |
| Anti-snap ETA | ${antiSnap.etaSeconds} |

## Missing, invalid and stale routes

| Probe | Result |
| --- | --- |
| Missing route | ${missing.status} / ${missing.reason} / ETA ${missing.etaSeconds} / remaining ${missing.remainingDistanceM} |
| Negative-cost route | ${invalid.negativeCostReason} / ETA ${invalid.negativeCostEta} |
| Disconnected route | ${invalid.disconnectedReason} (stale=${invalid.disconnectedStale}) / ETA ${invalid.disconnectedEta} |
| Replan before observation | ${stale.beforeStatus} → ${stale.afterReason} / ETA ${stale.afterEta} / remaining ${stale.afterRemaining} |
| Stale flag / recovered | ${stale.staleFlag} / ${stale.recoveredStatus} at ${stale.recoveredProgress} |
| Estimate created after replan | ${stale.lateCreatedReason} / ETA ${stale.lateCreatedEta} |

## Service states and reroute

| Probe | Result |
| --- | --- |
| Free-flow ETA | ${service.freeEtaSeconds} s |
| Congested ETA / ratio | ${service.congestedEtaSeconds} s / ${service.congestedRatio} |
| Congested min / max | ${service.congestedMinSeconds} / ${service.congestedMaxSeconds} s |
| Blocked | ${service.blockedReason} / ETA ${service.blockedEta} / progress ${service.blockedProgress} |
| Restored ETA | ${service.restoredEtaSeconds} s |
| Free route | ${reroute.freeRouteLaneIds.join(' → ')} |
| Replanned route | ${reroute.replannedRouteLaneIds.join(' → ')} |
| Route differs | ${reroute.routeDiffers} |
| Free / replanned trip cost | ${reroute.freeTripCostSeconds} / ${reroute.replannedTripCostSeconds} s |
| Free / replanned ETA | ${reroute.freeEtaSeconds} / ${reroute.replannedEtaSeconds} s |
| Old route after replan | ${reroute.oldRouteAfterReplanReason} / ETA ${reroute.oldRouteAfterReplanEta} |

## Arrival and validation

| Probe | Result |
| --- | --- |
| Pickup arrival | ${arrivals.pickupStatus} / ETA ${arrivals.pickupEta} |
| Dropoff arrival | ${arrivals.dropoffStatus} / ETA ${arrivals.dropoffEta} |
| Terminal ride | ${arrivals.terminalState} / ${arrivals.terminalReason} / ETA ${arrivals.terminalEta} |
| NaN / negative / infinite speed | ${report.validation.nanSpeed} / ${report.validation.negativeSpeed} / ${report.validation.infiniteSpeed} |
| NaN position / stale tick | ${report.validation.nanPosition} / ${report.validation.staleTick} |
| Unknown field | ${report.validation.unknownField} |
| Wrong ride / foreign vehicle | ${report.validation.wrongRide} / ${report.validation.foreignVehicle} |

## Simulation (real 059 schedule, real 060 dispatcher, real 041 routes)

| Metric | Value |
| --- | ---: |
| Requests / assignments / completed | ${simulation.requests} / ${simulation.assignments} / ${simulation.completed} |
| Failed / cancelled / active | ${simulation.failed} / ${simulation.cancelled} / ${simulation.active} |
| ETA samples (pickup / trip) | ${simulation.samples} (${simulation.pickupSamples} / ${simulation.tripSamples}) |
| Progress rewind violations | ${simulation.monotonicViolations} |
| ETA inversion violations | ${simulation.etaViolations} |
| Off-route / unavailable / arrived samples | ${simulation.offRoute} / ${simulation.unavailable} / ${simulation.arrived} |
| Zero-cost 041 samples | ${simulation.zeroCostSamples} |
| Route loads | ${simulation.routeLoads} |
| ETA min / max | ${simulation.minEta} / ${simulation.maxEta} s |

## Disposal

| Metric | Value |
| --- | --- |
| Disposed | ${report.disposal.disposed} |
| Observations / estimated / arrived / unavailable | ${report.disposal.observations} / ${report.disposal.estimated} / ${report.disposal.arrived} / ${report.disposal.unavailable} |
| Tick / route loads | ${report.disposal.tick} / ${report.disposal.routeLoads} |
| Ride state / release reason | ${report.disposal.state} / ${report.disposal.releaseReason} |

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'fleet', 'eta-report.ts')).href
  ),
  report = reportModule.runEtaReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, completed ${report.simulation.completed}, samples ${report.simulation.samples}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`Eta report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`Eta report is current: ${output}`);
} else {
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
