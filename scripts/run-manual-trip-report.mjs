import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  defaultOutput = join(root, 'Docs', 'Evidence', '072-manual-trip', 'report.json'),
  reportMarkdown = join(root, 'Docs', 'Evidence', '072-manual-trip', 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function segmentRows(trip) {
  return trip.segments
    .map(
      (segment) =>
        `| ${segment.segmentId} | ${segment.mode} | ${segment.learningEligible} | ${segment.startTick} | ${segment.endTick ?? '—'} | ${segment.completeness} | ${segment.closeReason ?? '—'} | ${segment.samples} | ${segment.publishedParameters.length} |`,
    )
    .join('\n');
}

function handoverRows(trip) {
  if (trip.handovers.length === 0) return '| — | — | — | — | — | — | — |';
  return trip.handovers
    .map(
      (handover) =>
        `| ${handover.decisionTick} | ${handover.closedMode ?? '—'} | ${handover.authority} | ${handover.segmentCloseReason ?? '—'} | ${handover.reason} | ${handover.statePreserved} | ${handover.violations.join(', ') || '—'} |`,
    )
    .join('\n');
}

function tripSection(title, trip) {
  return `### ${title}

| Metric | Value |
| --- | --- |
| Ride id | ${trip.ride?.rideId ?? '—'} |
| Same ride / request / taxi as begin | ${trip.sameRide} / ${trip.sameRequest} / ${trip.sameTaxi} |
| State | ${trip.ride?.state ?? '—'} |
| Pickup zone / dropoff zone | ${trip.ride?.pickupZoneId ?? '—'} / ${trip.ride?.dropoffZoneId ?? '—'} |
| Boarding tick / completion tick | ${trip.ride?.boardingTick ?? '—'} / ${trip.ride?.completionTick ?? '—'} |
| Release reason | ${trip.ride?.releaseReason ?? '—'} |
| Lifecycle rides / releases / transitions | ${trip.lifecycleRides} / ${trip.lifecycleReleases} / ${trip.lifecycleTransitions} |
| Dispatcher releases | ${trip.dispatcherReleases} |
| Final mode | ${trip.finalMode} |
| Intake entries / publications | ${trip.intakeEntries} / ${trip.publications} |
| Profile unchanged | ${trip.profileUnchanged} |
| Ticks AUTO / MANUAL / LEARNING | ${trip.ticks.AUTO} / ${trip.ticks.MANUAL} / ${trip.ticks.LEARNING} |
| Samples appended / skipped | ${trip.samplesAppended} / ${trip.samplesSkipped} |

| Segment | Mode | Eligible | Start | End | Completeness | Close reason | Samples | Published |
| --- | --- | --- | ---: | ---: | --- | --- | ---: | ---: |
${segmentRows(trip)}

| Handover | Closed mode | Authority | Close reason | Continuity | State preserved | Violations |
| --- | --- | --- | --- | --- | --- | --- |
${handoverRows(trip)}
`;
}

function markdown(report) {
  const checks = report.checks
      .map(
        (entry) =>
          `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
      )
      .join('\n'),
    refusals = Object.entries(report.refusals.reasons)
      .map(([reason, actual]) => `| ${reason} | ${actual} |`)
      .join('\n');
  return `# 072 Manual trip report

Machine-readable transcript: [report.json](report.json). Generated by \`npm run trip:manual\`; the
transcript contains no wall-clock value and is deterministic.

Version: \`${report.version}\`; one real 061 ride over the real 060 assignment, real 062 pickup, real
063 dropoff and real 041 routes, with the real 066 seat, real 067 mode intents, real 068 selection,
real 069 segments and the real 071 continuity layer.

## Oracle

${report.oracleRule}

## Timeline

| Field | Value |
| --- | ---: |
| Begin tick | ${report.timeline.beginTick} |
| Boarding tick / pickup dwell | ${report.timeline.boardingTick} / ${report.timeline.pickupDwellTicks} |
| Drive start / drive ticks / speed | ${report.timeline.driveStartTick} / ${report.timeline.driveTicks} / ${report.timeline.driveSpeedMps} |
| Dropoff start tick | ${report.timeline.dropoffStartTick} |
| Completion tick / dropoff dwell | ${report.timeline.completionTick} / ${report.timeline.dropoffDwellTicks} |

## Mixed AUTO → MANUAL → AUTO ride

${tripSection('Mixed trip', report.mixed)}

## Complete MANUAL trip

${tripSection('Manual trip', report.manual)}

## LEARNING demonstration

${tripSection('Learning trip', report.learning)}

## Ride completed while MANUAL

${tripSection('Completion boundary', report.completionBoundary)}

## Closed refusals

| Reason | Actual |
| --- | --- |
${refusals}

Refused interventions leave the ride in \`${report.refusals.rideState}\`, with
${report.refusals.segments} segment(s) and ${report.refusals.lifecycleRides} ride(s).

## Disposal

| Metric | Value |
| --- | --- |
| Disposed | ${report.disposal.disposed} |
| Open segments | ${report.disposal.openSegments} |
| Ride state | ${report.disposal.rideState} |
| Dispatcher taxi status | ${report.disposal.taxiStatus} |

Determinism: ${report.determinism.identical} across ${report.determinism.scenarios} identical scenarios.

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'app', 'manual-trip-report.ts')).href
  ),
  report = reportModule.runManualTripReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, mixed ${report.mixed.segments.length} segment(s), manual ${report.manual.segments.length} segment(s), overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`Manual trip report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`Manual trip report is current: ${output}`);
} else {
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
