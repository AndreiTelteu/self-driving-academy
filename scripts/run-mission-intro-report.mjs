import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  directory = join(root, 'Docs', 'Evidence', '117-mission-intro'),
  defaultOutput = join(directory, 'report.json'),
  reportMarkdown = join(directory, 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function markdown(report) {
  const checks = report.checks
      .map(
        (entry) =>
          `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
      )
      .join('\n'),
    steps = report.steps
      .map(
        (step) =>
          `| ${step.order} | \`${step.stepId}\` | ${step.requirement} | ${step.mode ?? '—'} | ${step.title} |`,
      )
      .join('\n'),
    play = report.playthrough,
    skip = report.skipResume,
    learning = report.learning,
    access = report.taxiAccess,
    ride = report.ride,
    bus = report.bus,
    ui = report.ui;
  return `# 117 control tutorial report

Machine-readable transcript: [report.json](report.json). Generated by
\`${report.generatedBy}\`; the transcript has no wall-clock value and is deterministic.

Version: \`${report.version}\`.

Oracle rule: ${report.oracleRule}

## Authored steps

| Order | Step | Requirement | Mode | Title |
| --- | --- | --- | --- | --- |
${steps}

## Full playthrough

| Field | Value |
| --- | --- |
| Observations | ${play.steps.join(' → ')} |
| State | ${play.state} |
| Completed by | ${play.completedBy} |
| Completed tick | ${play.completedTick} |
| Skipped steps | ${play.skippedSteps} |
| Learning jobs | ${play.learningJobs} |
| Profile versions | ${play.profileVersions} |
| PROFILE_ACTIVATE observed | ${play.learningActivationsObserved} |
| Blocked selections | ${play.blockedSelections} |

## Skip and resume

| Field | Value |
| --- | --- |
| Steps after skipping one | ${skip.afterStepSkip.join(' / ')} |
| Skipped steps after skip-all | ${skip.skippedSteps} |
| State after skip-all | ${skip.stateAfterSkipAll} |
| Completed by | ${skip.completedBy} |
| Paused state | ${skip.pausedState} |
| Observation while paused | ${skip.ignoredWhilePaused} |
| Resumed step index | ${skip.resumedStepIndex} |
| First observation after resume | ${skip.resumedStatus} |

## No accidental learning

| Field | Value |
| --- | --- |
| Eligible LEARNING refused | ${learning.refusedEligibleLearning} |
| Unknown eligibility refused | ${learning.refusedNullEligibility} |
| Refusal counter | ${learning.refusedLearning} |
| Step index after refusals | ${learning.stepIndexAfterRefusal} |
| Learning jobs | ${learning.learningJobs} |
| Profile versions | ${learning.profileVersions} |

## Taxi access

| Field | Value |
| --- | --- |
| Any taxi allowed | ${access.alwaysAllowed} |
| Blocked selections | ${access.blockedSelections} |
| Continuing with another taxi | ${access.otherTaxiContinue} |
| Civil selection | ${access.civilSelection} |

## Ride

| Field | Value |
| --- | --- |
| Dropoff of another taxi | ${ride.foreignDropoff} |
| Dropoff without pickup | ${ride.dropoffWithoutPickup} |
| Dropoff of another ride | ${ride.wrongRide} |
| Completed by a real dropoff | ${ride.completedByDropoff} |

## Real 007 bus

| Field | Value |
| --- | --- |
| Attached run completed | ${bus.attachedCompletion} |
| PROFILE_ACTIVATE observed | ${bus.activationsObserved} |
| Foreign world refused | ${bus.foreignWorldRefused} |

## Panel projection (keyboard and mouse)

| Field | Value |
| --- | --- |
| Panel version | ${ui.version} |
| Active progress | ${ui.activeProgress} |
| Enabled buttons while active | ${ui.activeButtons.join(', ')} |
| Completed progress | ${ui.completedProgress} |
| Enabled buttons when complete | ${ui.completedButtons.join(', ') || '—'} |
| Keyboard activation | ${ui.keyboardPaths.join(' / ')} |
| Global key listeners | ${ui.globalListeners} |

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'missions', 'mission-intro-report.ts')).href
  ),
  report = reportModule.runMissionIntroReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, steps ${report.steps.length}, learning jobs ${report.playthrough.learningJobs}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`Mission intro report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`Mission intro report is current: ${output}`);
} else {
  await mkdir(directory, { recursive: true });
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
