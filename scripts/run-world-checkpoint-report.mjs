function markdownCosts(cost) {
  const line = (label, stats) => `| ${label} | ${stats.min} | ${stats.median} | ${stats.max} |`;
  return `# 206 real checkpoint cost

Machine-readable values: [cost.json](cost.json). This is the only wall-clock measurement of PBI
206; it is **not** part of the deterministic transcript. It is produced by \`--cost\` on the machine
that ran it.

Contract: ${cost.contract}

- Samples: ${cost.sampleCount}
- Vehicles: ${cost.vehicles}
- Snapshot bytes: ${cost.bytes} of ${cost.byteBudget} (${cost.bodyUtilizationPercent}%)
- Checksum: \`${cost.checksum}\`
- Measured at: ${cost.measuredAt}

| Phase | Min (ms) | Median (ms) | Max (ms) |
| --- | --- | --- | --- |
${[
  line('Synchronous capture', cost.captureMs),
  line('Validation and checksum', cost.encodeMs),
  line('Durable commit', cost.commitMs),
  line('Total', cost.totalMs),
].join('\n')}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'persistence', 'world-checkpoint-report.ts')).href
  ),
  report = await reportModule.runWorldCheckpointReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`World checkpoint report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`World checkpoint report is current: ${output}`);
} else {
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}

if (process.argv.includes('--cost')) {
  const samples = Number(argument('--samples') ?? '20');
  const cost = await reportModule.measureWorldCheckpointCosts(
    Number.isSafeInteger(samples) && samples > 0 ? samples : 20,
  );
  await writeFile(costOutput, `${JSON.stringify(cost, null, 2)}\n`);
  console.log(
    `COST capture ${cost.captureMs.min}/${cost.captureMs.median}/${cost.captureMs.max} ms, encode ${cost.encodeMs.min}/${cost.encodeMs.median}/${cost.encodeMs.max} ms, commit ${cost.commitMs.min}/${cost.commitMs.median}/${cost.commitMs.max} ms, total ${cost.totalMs.min}/${cost.totalMs.median}/${cost.totalMs.max} ms over ${cost.sampleCount} samples, ${cost.bytes} bytes`,
  );
  console.log(`Wrote ${costOutput}`);
  await writeFile(join(directory, 'cost.md'), markdownCosts(cost));
  console.log(`Wrote ${join(directory, 'cost.md')}`);
}
