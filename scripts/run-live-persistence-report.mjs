import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  directory = join(root, 'Docs', 'Evidence', '278-live-persistence'),
  defaultOutput = join(directory, 'report.json'),
  reportMarkdown = join(directory, 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function markdown(report) {
  const numbers = report.numbers,
    fingerprints = report.fingerprints;
  const checks = report.checks
    .map(
      (entry) =>
        `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
    )
    .join('\n');
  const refusals = numbers.refusals
    .map((entry) => `| ${entry.case} | \`${entry.code}\` |`)
    .join('\n');
  return `# 278 live persistence, autosave and savefile report

Machine-readable transcript: [report.json](report.json). Generated by \`${report.generatedBy}\`;
the transcript is deterministic and contains no wall-clock value.

Contract: \`${report.contract}\`. ${report.oracleRule}

## Numbers

| Field | Value |
| --- | ---: |
| Interval | ${numbers.intervalTicks} ticks |
| Generation | ${numbers.generation} |
| Checkpoint tick | ${numbers.checkpointTick} |
| Created at | ${numbers.createdAt} |
| Checksum | \`${numbers.checksum}\` |
| File bytes | ${numbers.bytes} / ${numbers.maxFileBytes} |
| 225 body bytes | ${numbers.bodyBytes} / ${numbers.maxBodyBytes} |
| Commit time | ${numbers.commitMs} ms |
| Simulated tick | ${numbers.simulatedTick} |
| Last saved tick | ${numbers.lastSavedTick} |
| Unsaved ticks | ${numbers.unsavedTicks} |
| Next due tick | ${numbers.nextDueTick} |
| Preview identity | \`${numbers.previewId}\` |
| First import ΔXP | ${numbers.firstImportXpDelta} |
| Second import ΔXP | ${numbers.secondImportXpDelta} |
| Second import Δ daily rewards | ${numbers.secondImportDailyRewardsDelta} |
| XP / level | ${numbers.xp} / ${numbers.level} |
| Daily rewards | ${numbers.dailyRewards} |
| KPI days / revenue | ${numbers.kpiDays} / ${numbers.kpiRevenueMinorUnits} |
| Company cash / revenue / profit | ${numbers.companyCashMinorUnits} / ${numbers.companyRevenueMinorUnits} / ${numbers.companyProfitMinorUnits} |
| Resume | ${numbers.previousSegment}, ${numbers.openSegments.join(', ') || 'no open segment'} |
| Offline income / XP | ${numbers.offlineIncome} / ${numbers.offlineXp} |

## Refusals

| Case | Code |
| --- | --- |
${refusals}

## Fingerprints

| Field | Value |
| --- | --- |
| XP | \`${fingerprints.xp}\` |
| Daily | \`${fingerprints.daily}\` |
| KPI | \`${fingerprints.kpi}\` |
| Company | \`${fingerprints.company}\` |
| Profile | \`${fingerprints.profile}\` |
| Challenges | \`${fingerprints.challenges}\` |
| After reload XP | \`${fingerprints.afterReloadXp}\` |
| After reload KPI | \`${fingerprints.afterReloadKpi}\` |
| After reload company | \`${fingerprints.afterReloadCompany}\` |
| After second import XP | \`${fingerprints.afterSecondImportXp}\` |
| After second import company | \`${fingerprints.afterSecondImportCompany}\` |

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

Summary: ${report.summary.passed}/${report.summary.checks} checks passed; ${report.summary.pass ? 'PASS' : 'FAIL'}.

Limits: the report is deterministic and headless. It uses the real 213/212 daily owners, the real
268/269 company owners and the real 209 economy fixture; it does not measure FPS/GPU, does not
certify a browser session and does not replace the 287 playtest.
`;
}

const outputPath = argument('--out') ?? defaultOutput;
const modulePath = join(root, 'tests', 'persistence', 'live-persistence-report.ts');
const { runLivePersistenceReport } = await import(pathToFileURL(modulePath).href);
const report = await runLivePersistenceReport();
const json = `${JSON.stringify(report, null, 2)}\n`;

if (process.argv.includes('--check')) {
  let current;
  try {
    current = await readFile(outputPath, 'utf8');
  } catch {
    current = null;
  }
  if (current !== json) {
    console.error(`278 live persistence report is stale: ${outputPath}`);
    console.error('Run: npm run save:live');
    process.exit(1);
  }
  console.log(`278 live persistence report is current: ${outputPath}`);
  process.exit(0);
}

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, json);
await writeFile(reportMarkdown, markdown(report));
console.log(`Wrote ${outputPath}`);
console.log(`Wrote ${reportMarkdown}`);
if (!report.summary.pass) {
  console.error(`${report.summary.checks - report.summary.passed} checks failed`);
  process.exit(1);
}
