import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  directory = join(root, 'Docs', 'Evidence', '132-data-retention'),
  defaultOutput = join(directory, 'report.json'),
  reportMarkdown = join(directory, 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function rows(entries) {
  return entries.map(([label, entry]) => `| ${label} | ${value(entry)} |`).join('\n');
}

function usageRows(usage) {
  return [
    ['Domain', usage.domain],
    ['Status', usage.status],
    ['Artifacts', usage.artifacts],
    ['Protected artifacts', usage.protectedArtifacts],
    ['Evictable artifacts', usage.evictableArtifacts],
    ['RAM bytes', usage.ramBytes],
    ['RAM cap (bytes)', usage.ramCapBytes],
    ['RAM over (bytes)', usage.ramOverBytes],
    ['DB bytes', usage.dbBytes],
    ['DB cap (bytes)', usage.dbCapBytes],
    ['DB over (bytes)', usage.dbOverBytes],
  ];
}

function scenario(report, title, block) {
  return `## ${title}

### Before

| Field | Value |
| --- | --- |
${rows(usageRows(block.before))}

### Export (taken before any deletion)

| Field | Value |
| --- | --- |
${rows([
  ['Digest', block.export.digest],
  ['Reason', block.export.reason],
  ['Artifacts', block.export.artifacts],
  ['Partial artifacts already declared', block.export.partialArtifacts],
  ['RAM bytes', block.export.ramBytes],
  ['DB bytes', block.export.dbBytes],
])}

### Plan

| Field | Value |
| --- | --- |
${rows([
  ['Criterion', block.plan.criterion],
  ['Plan digest', block.plan.digest],
  ['Export digest', block.plan.exportDigest],
  ['Evicted', block.plan.evicted],
  ['Evicted RAM bytes', block.plan.evictedRamBytes],
  ['Evicted DB bytes', block.plan.evictedDbBytes],
  ['Projected status', block.plan.projected.status],
  ['Projected RAM bytes', block.plan.projected.ramBytes],
  ['Projected DB bytes', block.plan.projected.dbBytes],
])}

### Cleanup result

| Field | Value |
| --- | --- |
${rows([
  ['Result digest', block.cleanup.digest],
  ['Evicted', block.cleanup.evicted],
  ['Evicted RAM bytes', block.cleanup.evictedBytes.ram],
  ['Evicted DB bytes', block.cleanup.evictedBytes.db],
  ['Retained artifacts', block.cleanup.retained.artifacts],
  ['Retained protected artifacts', block.cleanup.retained.protectedArtifacts],
  ['Retained RAM bytes', block.cleanup.retained.ramBytes],
  ['Retained DB bytes', block.cleanup.retained.dbBytes],
  ['Declared partial clips', block.cleanup.partials],
])}

### After

| Field | Value |
| --- | --- |
${rows(usageRows(block.after))}
`;
}

function markdown(report) {
  const checks = report.checks
    .map(
      (entry) =>
        `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
    )
    .join('\n');
  return `# 132 Data retention and local quotas report

Machine-readable transcript: [report.json](report.json). Generated by
\`${report.generatedBy}\`. The transcript contains no wall clock and is deterministic.

Version: \`${report.version}\`.

Oracle rule: ${report.oracleRule}

## Budgets and gaps

| Field | Value |
| --- | --- |
${rows([
  ['Source', report.budgets.source],
  ['Budget version', report.budgets.budgetVersion],
  ['Recorder RAM (bytes)', report.budgets.recorderRamBytes],
  ['Optional replay storage (bytes)', report.budgets.optionalReplayStorageBytes],
  ['Persistence ingress (bytes)', report.budgets.persistenceIngressBytes],
  ['069 record store (bytes)', report.budgets.interventionRecordStoreBytes],
  ['Declared gaps', report.budgets.gaps],
])}

## Domain quotas (bytes)

| Domain | RAM bytes | RAM source | DB bytes | DB source |
| --- | --- | --- | --- | --- |
${report.quotas
  .map(
    (quota) =>
      `| ${quota.domain} | ${quota.ramBytes} | ${quota.ramProvenance}: ${quota.ramKey} | ${quota.dbBytes} | ${quota.dbProvenance}: ${quota.dbKey} |`,
  )
  .join('\n')}

## Inventory fixture

| Field | Value |
| --- | --- |
${rows([
  ['Artifacts', report.inventory.artifacts],
  ['Protected artifacts', report.inventory.protectedArtifacts],
  ['Evictable artifacts', report.inventory.evictableArtifacts],
  ['RAM bytes', report.inventory.ramBytes],
  ['DB bytes', report.inventory.dbBytes],
  ['Per domain', report.inventory.byDomain],
])}

${scenario(report, 'Scenario 1 — world recorder over its RAM quota (oldest first)', report.worldRecorder)}
Isolation: the intervention telemetry domain stayed at
${report.worldRecorder.interventionUsageAfter.artifacts} artifacts and
${report.worldRecorder.interventionUsageAfter.dbBytes} DB bytes.

${scenario(report, 'Scenario 2 — intervention telemetry over its DB quota (largest first)', report.interventionTelemetry)}

${scenario(report, 'Scenario 3 — explicit size target leaves a declared partial telemetry clip', report.telemetryPartialClip)}
## Scenario 4 — explicit whole-domain cleanup

| Field | Value |
| --- | --- |
${rows([
  ['Domain', report.wholeDomain.domain],
  ['Evicted', report.wholeDomain.evicted],
  ['Retained', report.wholeDomain.retained],
  ['Evicted RAM bytes', report.wholeDomain.evictedBytes.ram],
  ['Evicted DB bytes', report.wholeDomain.evictedBytes.db],
  ['World recorder untouched', report.wholeDomain.worldRecorderUntouched],
])}

## Scenario 5 — only protected rows over quota

| Field | Value |
| --- | --- |
${rows([
  ['Telemetry status', report.protectedOnly.telemetryStatus],
  ['World recorder status', report.protectedOnly.worldStatus],
  ['Planned evictions', report.protectedOnly.planEvictions],
  ['Apply code', report.protectedOnly.applyCode],
  ['Protected rows after', report.protectedOnly.protectedAfter],
  ['Missing protected rows', report.protectedOnly.missingAfter],
])}

## Scenario 6 — determinism

| Field | Value |
| --- | --- |
${rows([
  ['Forward export digest', report.determinism.forward.exportDigest],
  ['Forward plan digest', report.determinism.forward.planDigest],
  ['Forward result digest', report.determinism.forward.resultDigest],
  ['Forward evicted', report.determinism.forward.evicted],
  ['Reversed export digest', report.determinism.reversed.exportDigest],
  ['Reversed plan digest', report.determinism.reversed.planDigest],
  ['Reversed result digest', report.determinism.reversed.resultDigest],
  ['Reversed evicted', report.determinism.reversed.evicted],
  ['Identical', report.determinism.identical],
])}

## Scenario 7 — refusals

| Field | Value |
| --- | --- |
${rows([
  ['Missing budget', report.refusalCodes.missingBudget],
  ['Cleanup without export', report.refusalCodes.cleanupWithoutExport],
  ['Forged plan', report.refusalCodes.forgedPlan],
  ['Replayed (stale) plan', report.refusalCodes.stalePlan],
])}

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'persistence', 'data-retention-report.ts')).href
  ),
  report = reportModule.runDataRetentionReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`Data retention report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`Data retention report is current: ${output}`);
} else {
  await mkdir(directory, { recursive: true });
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
