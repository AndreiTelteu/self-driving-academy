import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  directory = join(root, 'Docs', 'Evidence', '275-live-missions'),
  defaultOutput = join(directory, 'report.json'),
  reportMarkdown = join(directory, 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function markdown(report) {
  const checks = report.checks
    .map(
      (entry) =>
        `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
    )
    .join('\n');
  return `# 275 live campaign, tutorial and missions report

Machine-readable transcript: [report.json](report.json). Generated by
\`${report.generatedBy}\`; there is no wall-clock value and the transcript is deterministic.

Version: \`${report.version}\`.

Oracle rule: ${report.oracleRule}

## Tutorial

| Field | Value |
| --- | --- |
| Steps | ${report.tutorial.steps.join(' → ')} |
| State | ${report.tutorial.state} |
| Completed by | ${report.tutorial.completedBy} |
| Skipped steps | ${report.tutorial.skippedSteps} |
| Learning jobs | ${report.tutorial.learningJobs} |
| Profile versions | ${report.tutorial.profileVersions} |
| Learning gate | ${report.tutorial.learningGate} |

## Campaign

| Field | Value |
| --- | --- |
| Missions | ${report.campaign.missions} |
| Stage 1 state | ${report.campaign.stage1State} |
| Stage 1 attempt | ${report.campaign.stage1Attempt} |
| Stage 1 XP | ${report.campaign.stage1RewardXp} |
| Stage 1 rewards granted | ${report.campaign.stage1RewardsGranted} |
| Stage 2 state | ${report.campaign.stage2State} |
| Stage 2 attempt | ${report.campaign.stage2Attempt} |

## Replay

| Field | Value |
| --- | --- |
| Attempt | ${report.replay.attempt} |
| Previous instance | \`${report.replay.previous}\` |
| Settled completions | ${report.replay.settledCompletions} |
| Duplicate rewards | ${report.replay.duplicateRewards} |
| XP after replay | ${report.replay.xpAfterReplay} |
| Rewards granted after replay | ${report.replay.rewardsGrantedAfterReplay} |

## Failure

| Field | Value |
| --- | --- |
| Mission | \`${report.failure.missionId}\` |
| State | ${report.failure.state} |
| Reason | ${report.failure.reason} |
| Failed tick | ${report.failure.failedTick} |
| XP before | ${report.failure.xpBefore} |
| XP after | ${report.failure.xpAfter} |
| Profile writes | ${report.failure.profileWrites} |
| Replay available | ${report.failure.replayAvailable} |
| Failure label | ${report.failure.failureLabel} |

## Window and incident budget

| Field | Value |
| --- | --- |
| Window mission | \`${report.windowFailure.missionId}\` |
| Window ticks | ${report.windowFailure.windowTicks} |
| Started tick | ${report.windowFailure.startedTick} |
| Expired tick | ${report.windowFailure.expiredTick} |
| Window state/reason | ${report.windowFailure.state} / ${report.windowFailure.reason} |
| Budget mission | \`${report.incidentFailure.missionId}\` |
| Incident budget | ${report.incidentFailure.budget} |
| Incidents | ${report.incidentFailure.incidents} |
| Budget state/reason | ${report.incidentFailure.state} / ${report.incidentFailure.reason} |

## Panel and ledger

| Field | Value |
| --- | --- |
| Panel version | ${report.panel.version} |
| Missions listed | ${report.panel.missions} |
| Stage 1 state label | ${report.panel.stage1StateLabel} |
| Stage 1 replay label | ${report.panel.stage1ReplayLabel} |
| Failure limits label | ${report.panel.failureLimitsLabel} |
| Failure replay label | ${report.panel.failureReplayLabel} |
| Reward rows | ${report.ledger.rewards} |
| XP in reward ledger | ${report.ledger.xp} |
| Unlocks | ${report.ledger.unlocks} |
| Duplicate rewards | ${report.ledger.duplicates} |

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'missions', 'live-missions-report.ts')).href
  ),
  report = reportModule.runLiveMissionsReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, stages ${report.campaign.stage1State}, XP ${report.campaign.stage1RewardXp}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`Live missions report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`Live missions report is current: ${output}`);
} else {
  await mkdir(directory, { recursive: true });
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
