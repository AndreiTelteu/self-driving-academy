import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  defaultOutput = join(root, 'Docs', 'Evidence', '058-civil-traffic', 'report.json'),
  reportMarkdown = join(root, 'Docs', 'Evidence', '058-civil-traffic', 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function markdown(report) {
  const checks = report.checks
      .map(
        (entry) =>
          `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
      )
      .join('\n'),
    spawn = report.spawn,
    mixed = report.mixed,
    resume = report.resume,
    clean = report.clean;
  return `# 058 civil traffic report

Machine-readable transcript: [report.json](report.json). Generated by
\`npm run civil:traffic\`; the transcript contains no wall-clock value and is deterministic.

Version: \`${report.version}\`; style: \`${report.style.profileId}\` / \`${report.style.versionId}\`.

## Spawn

| Metric | Value |
| --- | ---: |
| Civilians from 057 | ${spawn.civilians} |
| Unique IDs | ${spawn.uniqueIds} |
| READY routes | ${spawn.readyRoutes} |
| Routes returned by 041 | ${spawn.routesFromPlanner} |
| On-lane poses | ${spawn.onLane} |
| Common city style | ${spawn.commonStyle} |
| Shortest route (lanes) | ${spawn.shortestRouteLanes} |
| Longest route (lanes) | ${spawn.longestRouteLanes} |
| Routes with authored TURN | ${spawn.turnRoutes} |

## Mixed traffic and resume

| Metric | Value |
| --- | ---: |
| Mixed ticks | ${mixed.ticks} |
| Taxi observed as 044 leader | ${mixed.taxiLeaderObserved} |
| Minimum leader gap (m) | ${mixed.minimumLeaderGapM ?? 'none'} |
| Followed speed (m/s) | ${mixed.followedSpeedMps} |
| Control speed (m/s) | ${mixed.controlSpeedMps} |
| On-lane actor frames | ${mixed.onLaneFrames} |
| Same-lane overlap frames | ${mixed.sameLaneOverlap} |
| Style before release | ${resume.styleBefore} |
| Style after resume | ${resume.styleAfter} |
| Route preserved | ${resume.routePreserved} |
| Registry mode/profile | ${resume.registryMode} / ${resume.registryProfile} |
| Moved after resume | ${resume.movedAfterResume} |

## Disposal

| Metric | Value |
| --- | ---: |
| Disposed | ${clean.disposed} |
| Actors | ${clean.actors} |
| Longitudinal actors | ${clean.longitudinalActors} |
| Road-context vehicles | ${clean.roadContextVehicles} |
| Planner searches | ${clean.routeSearches} |

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'fleet', 'civil-traffic-report.ts')).href
  ),
  report = reportModule.runCivilTrafficReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, mixed ${report.mixed.onLaneFrames} on-lane frames, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`Civil traffic report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`Civil traffic report is current: ${output}`);
} else {
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
