import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { createServer } from 'node:http';
import { dirname, extname, join, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/**
 * PBI 282 browser probe.
 *
 * The real production build is opened in Chrome. The player enters the parked taxi with G, brakes
 * from speed with S, drives into the parked compact, presses R for the physical 030 recovery and
 * walks the real M boundary. The probe reads only the live read model: Rapier wheel/contact state,
 * 029 availability, 030 history, 024 mode/authority and separated tick/present/physics costs.
 * Playwright is optional; without it the result is NOT_RUN with the real reason, never PASS.
 */
const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  directory = join(root, 'Docs', 'Evidence', '282-live-physics'),
  browserJson = join(directory, 'browser.json'),
  browserMarkdown = join(directory, 'browser.md'),
  screenshots = join(directory, 'screenshots'),
  distDirectory = join(root, 'dist');

async function loadPlaywright() {
  const explicit = process.env.PLAYWRIGHT_MODULE;
  try {
    if (explicit) {
      const resolved = resolve(explicit),
        entry = /\.(?:c|m)?js$/.test(resolved) ? resolved : join(resolved, 'index.js');
      return await import(pathToFileURL(entry).href);
    }
    return await import('playwright');
  } catch {
    return null;
  }
}

function mimeType(file) {
  return (
    {
      '.html': 'text/html; charset=utf-8',
      '.js': 'text/javascript; charset=utf-8',
      '.css': 'text/css; charset=utf-8',
      '.json': 'application/json',
      '.png': 'image/png',
      '.svg': 'image/svg+xml',
      '.wasm': 'application/wasm',
      '.glb': 'model/gltf-binary',
      '.ktx2': 'image/ktx2',
    }[extname(file)] ?? 'application/octet-stream'
  );
}

async function serve(directoryPath) {
  const server = createServer(async (request, response) => {
    try {
      if (request.method !== 'GET') {
        response.writeHead(405).end();
        return;
      }
      const url = new URL(request.url ?? '/', 'http://127.0.0.1'),
        pathname = decodeURIComponent(url.pathname);
      if (pathname === '/favicon.ico') {
        response.writeHead(204).end();
        return;
      }
      const file = resolve(directoryPath, '.' + (pathname === '/' ? '/index.html' : pathname));
      if (!file.startsWith(directoryPath + sep) || !(await stat(file)).isFile()) {
        response.writeHead(404).end();
        return;
      }
      const data = await readFile(file);
      response.writeHead(200, {
        'Content-Type': mimeType(file),
        'Cache-Control': 'no-store',
        'Content-Length': data.length,
      });
      response.end(data);
    } catch {
      response.writeHead(404);
      response.end();
    }
  });
  await new Promise((ready) => server.listen(0, '127.0.0.1', ready));
  const address = server.address(),
    origin = `http://127.0.0.1:${
      typeof address === 'object' && address !== null ? address.port : 0
    }`;
  return { server, origin };
}

function markdown(result) {
  if (!result.run)
    return `# 282 — live Rapier browser probe

Generated by \`npm run physics:live:probe\`.

**NOT_RUN** — ${result.reason}

No PASS is simulated. The deterministic report covers the Rapier metrics.
`;
  const checks = result.run.checks
    .map((check) => `- \`${check.name}\`: ${check.pass ? 'PASS' : 'FAIL'} — ${check.detail}`)
    .join('\n');
  return `# 282 — live Rapier browser probe

Generated by \`npm run physics:live:probe\`; Chromium ${result.run.browser}, ${result.run.backend}, viewport ${result.run.viewport}.

Real flow: start → G enter taxi → W accelerate → S brake → W impact the parked compact → R physical
recovery → M AUTO → M MANUAL. The probe reads only the live 282 read model.

${checks}

## Costs

| Metric | p50 | p95 | max |
| --- | ---: | ---: | ---: |
| Shell tick | ${result.run.costs.tick.p50Ms.toFixed(3)} | ${result.run.costs.tick.p95Ms.toFixed(3)} | ${result.run.costs.tick.maxMs.toFixed(3)} |
| Babylon present | ${result.run.costs.present.p50Ms.toFixed(3)} | ${result.run.costs.present.p95Ms.toFixed(3)} | ${result.run.costs.present.maxMs.toFixed(3)} |
| Frame interval | ${result.run.costs.frame.p50Ms.toFixed(3)} | ${result.run.costs.frame.p95Ms.toFixed(3)} | ${result.run.costs.frame.maxMs.toFixed(3)} |
| Rapier live step | ${result.run.costs.physics.p50Ms.toFixed(3)} | ${result.run.costs.physics.p95Ms.toFixed(3)} | ${result.run.costs.physics.maxMs.toFixed(3)} |

## Limits

- This is a short functional Chrome run, not a full playtest and not a hardware FPS/GPU gate.
- Frame numbers are the real Chrome/ANGLE path of this run, not a certified hardware budget.
- 058 traffic is a bounded kinematic proxy; 284 owns complete civil autonomy.
`;
}

const result = {
  version: '282-live-physics-probe-v1',
  generatedAt: new Date().toISOString(),
};
const playwright = await loadPlaywright();
if (playwright === null) {
  result.reason =
    'Playwright is not installed in this checkout (no `playwright` module and no PLAYWRIGHT_MODULE); the browser probe was not run.';
  await mkdir(directory, { recursive: true });
  await writeFile(browserJson, JSON.stringify(result, null, 2) + '\n');
  await writeFile(browserMarkdown, markdown(result));
  console.log('Live physics browser probe NOT_RUN: Playwright is not installed.');
  process.exit(0);
}

const executablePath =
  process.env.PLAYWRIGHT_EXECUTABLE ??
  (process.platform === 'win32' ? 'C:/Program Files/Google/Chrome/Application/chrome.exe' : null);
let server;
let browser;
let debugPage;
try {
  const served = await serve(distDirectory);
  server = served.server;
  const { chromium } = playwright.default ?? playwright;
  const headless = process.env.PLAYWRIGHT_HEADED !== '1';
  browser = await chromium.launch({
    headless,
    ...(executablePath === null ? {} : { executablePath }),
    ...(process.env.PLAYWRIGHT_CHANNEL ? { channel: process.env.PLAYWRIGHT_CHANNEL } : {}),
    args: [
      ...(headless
        ? ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader']
        : []),
      '--disable-gpu-sandbox',
      '--disable-frame-rate-limit',
      '--disable-background-timer-throttling',
      '--disable-backgrounding-occluded-windows',
      '--disable-renderer-backgrounding',
      '--disable-features=CalculateNativeWinOcclusion',
    ],
  });
  const context = await browser.newContext({
    viewport: { width: 1440, height: 900 },
    deviceScaleFactor: 1,
  });
  const page = await context.newPage();
  debugPage = page;
  const pageErrors = [];
  const consoleErrors = [];
  page.on('pageerror', (error) => pageErrors.push(String(error)));
  page.on('console', (message) => {
    if (message.type() === 'error') consoleErrors.push(message.text());
  });
  await page.bringToFront();
  await page.goto(
    `${served.origin}/?capture=1&debug=1&backend=WEBGL2&preset=LOW&models=procedural&nofocuspause`,
    { waitUntil: 'load', timeout: 180000 },
  );
  await page.waitForFunction(() => globalThis.__v3Composition?.ready() === true, null, {
    timeout: 180000,
  });
  await page.waitForFunction(
    () => globalThis.document?.querySelector('.game-shell')?.getAttribute('data-state') === 'READY',
    null,
    { timeout: 180000 },
  );
  const play = page.getByRole('button', { name: 'Joacă' });
  const resumeStart = page.getByRole('button', { name: 'Pornește' });
  const startButton = (await play.count()) > 0 ? play : resumeStart;
  await startButton.click();
  await page.waitForTimeout(500);
  const focusCanvas = () =>
    page.evaluate(() => {
      const canvas = globalThis.document?.querySelector('canvas');
      if (canvas instanceof globalThis.HTMLCanvasElement) canvas.focus();
    });
  const pumpFrame = () =>
    page.evaluate(
      () => new Promise((resolve) => globalThis.requestAnimationFrame(() => resolve(true))),
    );
  const read = () => page.evaluate(() => globalThis.__v3Composition.read());
  const physics = () => page.evaluate(() => globalThis.__v3Composition.physics());
  const shell = () => page.evaluate(() => globalThis.__v3Composition.shell());
  const ensurePlaying = async () => {
    const state = await page.evaluate(() => globalThis.__v3Composition.lifecycle());
    if (state?.kind !== 'PAUSED') return false;
    const resume = page.locator('[data-shell-action="resume"]');
    if ((await resume.count()) > 0) {
      await resume.click();
      await page.waitForTimeout(250);
      await focusCanvas();
      return true;
    }
    return false;
  };
  const lifecycle = () => page.evaluate(() => globalThis.__v3Composition.lifecycle());
  const waitPlaying = async () => {
    const deadline = Date.now() + 120000;
    while ((await lifecycle())?.kind !== 'PLAYING') {
      if (Date.now() > deadline) throw new Error('PLAYING timeout');
      if (!(await ensurePlaying())) {
        await pumpFrame();
        await page.waitForTimeout(20);
      }
    }
    await focusCanvas();
  };
  const waitTicks = async (count) => {
    const start = (await read()).tick;
    const deadline = Date.now() + 120000;
    while ((await read()).tick < start + count) {
      if (Date.now() > deadline) throw new Error(`Tick timeout after ${start} + ${count}`);
      if (await ensurePlaying()) continue;
      await pumpFrame();
      await page.waitForTimeout(20);
    }
  };
  const press = async (key) => {
    await page.bringToFront();
    await focusCanvas();
    await page.keyboard.press(key);
  };
  const hold = async (key) => {
    await page.bringToFront();
    await focusCanvas();
    await page.keyboard.down(key);
  };
  const release = async (key) => {
    await focusCanvas();
    await page.keyboard.up(key);
  };
  const holdUntil = async (key, predicate, timeoutMs, label) => {
    const deadline = Date.now() + timeoutMs;
    let held = false;
    try {
      while (Date.now() < deadline) {
        if ((await lifecycle())?.kind !== 'PLAYING') {
          if (held) {
            try {
              await release(key);
            } catch {
              // A suspended shell already cleared held input.
            }
            held = false;
          }
          if (!(await ensurePlaying())) {
            await pumpFrame();
            await page.waitForTimeout(20);
          }
          continue;
        }
        if (!held) {
          await hold(key);
          held = true;
        }
        if (await predicate()) return;
        await pumpFrame();
        await page.waitForTimeout(20);
      }
      throw new Error(`${label} timeout`);
    } finally {
      if (held) await release(key).catch(() => undefined);
    }
  };
  const vehicle = async (id) => {
    const model = await physics();
    return model?.vehicles?.find((entry) => entry.vehicleId === id) ?? null;
  };
  const waitFor = async (predicate, timeoutMs, label) => {
    const deadline = Date.now() + timeoutMs;
    while (Date.now() < deadline) {
      if (await predicate()) return true;
      if (await ensurePlaying()) continue;
      await pumpFrame();
      await page.waitForTimeout(20);
    }
    throw new Error(`${label} timeout`);
  };
  const checks = [];
  const check = (name, pass, detail) => checks.push({ name, pass, detail: String(detail) });
  const shots = [];
  const shot = async (name) => {
    await mkdir(screenshots, { recursive: true });
    const relative = `screenshots/${name}.png`;
    await page.screenshot({ path: join(directory, relative), timeout: 120000 });
    shots.push(relative);
    return relative;
  };

  await waitTicks(20);
  for (let attempt = 0; attempt < 3; attempt += 1) {
    await waitPlaying();
    await press('KeyG');
    try {
      await waitFor(
        async () =>
          (await page.evaluate(
            () => globalThis.__v3Composition.read().selection.playerVehicleId,
          )) === 'taxi-01',
        8000,
        'enter taxi',
      );
      break;
    } catch (error) {
      if (attempt === 2) throw error;
    }
  }
  await waitTicks(10);
  const entered = await physics();
  check(
    'real Rapier car with four wheels and suspension',
    entered?.vehicles?.find((entry) => entry.vehicleId === 'taxi-01')?.wheelContacts === 4 &&
      entered?.stats?.native?.controller?.vehicles >= 2 &&
      (entered?.stats?.cost?.samples ?? 0) > 0,
    `contacts ${entered?.vehicles?.find((entry) => entry.vehicleId === 'taxi-01')?.wheelContacts}, cars ${entered?.stats?.native?.controller?.vehicles}`,
  );

  // Braking from real speed.
  await holdUntil(
    'KeyW',
    async () => ((await vehicle('taxi-01'))?.speedMps ?? 0) > 8,
    60000,
    'acceleration',
  );
  const brakeStartActual = await vehicle('taxi-01');
  await holdUntil(
    'KeyS',
    async () => ((await vehicle('taxi-01'))?.speedMps ?? 1) < 0.2,
    60000,
    'brake stop',
  );
  const brakeEnd = await vehicle('taxi-01');
  const brakeDistance = Math.hypot(
    brakeEnd.positionM.x - brakeStartActual.positionM.x,
    brakeEnd.positionM.z - brakeStartActual.positionM.z,
  );
  check(
    'S brakes the real car to rest',
    brakeDistance > 1 && Math.abs(brakeEnd.speedMps) < 0.2,
    `${brakeDistance.toFixed(2)} m, final ${brakeEnd.speedMps.toFixed(3)} m/s`,
  );
  shots.push(await shot('01-braked'));

  // Real impact with the parked compact.
  await holdUntil(
    'KeyW',
    async () => ((await vehicle('taxi-01'))?.availability ?? 'AVAILABLE') !== 'AVAILABLE',
    90000,
    'impact damage',
  );
  await holdUntil(
    'KeyS',
    async () => Math.abs((await vehicle('taxi-01'))?.speedMps ?? 1) < 0.3,
    60000,
    'impact stop',
  );
  const taxiImpact = await vehicle('taxi-01');
  const civilImpact = await vehicle('civil-01');
  const gap = Math.hypot(
    taxiImpact.positionM.x - civilImpact.positionM.x,
    taxiImpact.positionM.z - civilImpact.positionM.z,
  );
  const impactState = await physics();
  check(
    'impact produces real 029 damage on both cars',
    taxiImpact.availability !== 'AVAILABLE' && civilImpact.availability !== 'AVAILABLE',
    `${taxiImpact.availability}/${civilImpact.availability}`,
  );
  check(
    'impact does not pass the bodies through each other',
    gap > 3.7,
    `${gap.toFixed(3)} m center gap`,
  );
  check(
    'impact is a real 028/029 incident, not a UI state',
    taxiImpact.lastIncidentId !== null &&
      taxiImpact.wheelContacts === 4 &&
      civilImpact.wheelContacts === 4,
    `${taxiImpact.lastIncidentId}, contacts ${taxiImpact.wheelContacts}/${civilImpact.wheelContacts}`,
  );
  shots.push(await shot('02-impact'));

  // Physical R recovery.
  await waitPlaying();
  await press('KeyR');
  await waitFor(async () => (await physics())?.recovery?.status === 'COMPLETED', 30000, 'recovery');
  await waitTicks(4);
  const recovered = await vehicle('taxi-01');
  const recovery = (await physics()).recovery;
  check(
    'R performs a real 030 lane teleport and zeroes velocity',
    recovery.status === 'COMPLETED' &&
      Math.abs(recovered.speedMps) < 0.1 &&
      (recovery.history ?? 0) >= 1,
    `${recovery.status}, speed ${recovered.speedMps.toFixed(4)} m/s, history ${recovery.history}`,
  );
  check(
    'recovery restores 029 availability',
    recovered.availability === 'AVAILABLE',
    `${recovered.availability}`,
  );
  shots.push(await shot('03-recovered'));

  // Real M boundary continuity.
  await waitPlaying();
  const beforeMode = await vehicle('taxi-01');
  const beforeModeRead = await read();
  await press('KeyM');
  await waitTicks(3);
  const afterMode = await vehicle('taxi-01');
  const afterModeRead = await read();
  const modeDelta = Math.hypot(
    afterMode.positionM.x - beforeMode.positionM.x,
    afterMode.positionM.z - beforeMode.positionM.z,
  );
  const speedDelta = Math.abs(afterMode.speedMps - beforeMode.speedMps);
  const yawDelta = Math.abs(afterMode.yawRad - beforeMode.yawRad);
  check(
    'M changes mode without a teleport',
    afterMode.controlMode === 'AUTO' && modeDelta < 0.5 && speedDelta < 0.3 && yawDelta < 0.05,
    `${afterMode.controlMode}, ${modeDelta.toFixed(3)} m, ${speedDelta.toFixed(3)} m/s, ${yawDelta.toFixed(4)} rad`,
  );
  check(
    'AUTO and MANUAL use the same live physics owner',
    afterModeRead.physics?.native?.controller?.players === 0 &&
      beforeModeRead.physics?.native?.controller?.players === 1,
    `players ${beforeModeRead.physics?.native?.controller?.players} → ${afterModeRead.physics?.native?.controller?.players}`,
  );
  shots.push(await shot('04-auto'));

  await press('KeyM');
  await waitTicks(3);
  const manualAgain = await vehicle('taxi-01');
  check(
    'M returns to MANUAL with the same body',
    manualAgain.controlMode === 'MANUAL' &&
      Math.abs(manualAgain.positionM.x - afterMode.positionM.x) < 0.6,
    `${manualAgain.controlMode}, ${Math.abs(manualAgain.positionM.x - afterMode.positionM.x).toFixed(3)} m`,
  );

  const costs = (await read()).costs;
  const final = await physics();
  result.run = {
    browser: await page.evaluate(() => globalThis.navigator.userAgent),
    backend:
      (await page.evaluate(() => globalThis.__v3Composition.backend()))?.rendererKind ?? null,
    viewport: '1440x900',
    tick: (await read()).tick,
    checks,
    screenshots: shots,
    pageErrors,
    consoleErrors,
    braking: { distanceM: brakeDistance, finalSpeedMps: brakeEnd.speedMps },
    impact: {
      gapM: gap,
      taxi: { availability: taxiImpact.availability, contacts: taxiImpact.wheelContacts },
      civil: { availability: civilImpact.availability, contacts: civilImpact.wheelContacts },
      contacts: impactState.stats.contacts,
      incidents: impactState.stats.incidents,
    },
    recovery: {
      status: recovery.status,
      speedMps: recovered.speedMps,
      availability: recovered.availability,
      history: final.recoveryHistory?.length ?? 0,
    },
    mode: {
      from: beforeMode.controlMode,
      to: afterMode.controlMode,
      deltaM: modeDelta,
      speedDelta,
      yawDelta,
    },
    costs: {
      tick: costs.tick,
      present: costs.present,
      frame: costs.frame,
      physics: costs.physics,
    },
    shell: await shell(),
    physicsStats: final.stats,
  };
  await mkdir(directory, { recursive: true });
  await writeFile(browserJson, JSON.stringify(result, null, 2) + '\n');
  await writeFile(browserMarkdown, markdown(result));
  const passed = checks.filter((check) => check.pass).length;
  console.log(`Live physics browser probe: ${passed}/${checks.length} PASS`);
  if (passed !== checks.length || pageErrors.length > 0) process.exitCode = 1;
} catch (error) {
  result.reason = `Browser launch/run failed: ${error instanceof Error ? error.message : String(error)}`;
  if (debugPage !== undefined) {
    try {
      result.diagnostics = await debugPage.evaluate(() => ({
        life: globalThis.__v3Composition?.lifecycle?.() ?? null,
        shell: globalThis.__v3Composition?.shell?.() ?? null,
        read: globalThis.__v3Composition?.read?.() ?? null,
        physics: globalThis.__v3Composition?.physics?.() ?? null,
        hidden: globalThis.document?.hidden ?? null,
      }));
    } catch (inspect) {
      result.diagnostics = { error: String(inspect) };
    }
  }
  await mkdir(directory, { recursive: true });
  await writeFile(browserJson, JSON.stringify(result, null, 2) + '\n');
  await writeFile(browserMarkdown, markdown(result));
  console.log(`Live physics browser probe NOT_RUN: ${result.reason}`);
  process.exitCode = 1;
} finally {
  await browser?.close().catch(() => undefined);
  if (server !== undefined) await new Promise((close) => server.close(close));
}
