import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { createServer } from 'node:http';
import { dirname, extname, join, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/**
 * PBI 286 browser probe.
 *
 * The page runs the real 164 population, the real 165 hazards and the real 282 Rapier world in
 * Chromium. It advances exactly the requested number of fixed steps; no synthetic result is written.
 * The screenshots must show a pedestrian, a physical yield, an obstacle and the avoidance.
 */
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const directory = join(root, 'Docs', 'Evidence', '286-live-pedestrians');
const browserJson = join(directory, 'browser.json');
const browserMarkdown = join(directory, 'browser.md');
const screenshots = join(directory, 'screenshots');
const buildDirectory = join(root, '.pbi-validation-286', 'build');

async function loadPlaywright() {
  const explicit = process.env.PLAYWRIGHT_MODULE;
  try {
    if (explicit) {
      const resolved = resolve(explicit);
      const entry = /\.(?:c|m)?js$/.test(resolved) ? resolved : join(resolved, 'index.js');
      return await import(pathToFileURL(entry).href);
    }
    return await import('playwright');
  } catch {
    return null;
  }
}

function mimeType(file) {
  return (
    {
      '.html': 'text/html; charset=utf-8',
      '.js': 'text/javascript; charset=utf-8',
      '.css': 'text/css; charset=utf-8',
      '.json': 'application/json',
      '.png': 'image/png',
      '.svg': 'image/svg+xml',
      '.wasm': 'application/wasm',
      '.glb': 'model/gltf-binary',
      '.ktx2': 'image/ktx2',
    }[extname(file)] ?? 'application/octet-stream'
  );
}

async function serve(directoryPath) {
  const server = createServer(async (request, response) => {
    try {
      if (request.method !== 'GET') {
        response.writeHead(405).end();
        return;
      }
      const url = new URL(request.url ?? '/', 'http://127.0.0.1');
      const pathname = decodeURIComponent(url.pathname);
      if (pathname === '/favicon.ico') {
        response.writeHead(204).end();
        return;
      }
      const file = resolve(directoryPath, '.' + (pathname === '/' ? '/index.html' : pathname));
      if (!file.startsWith(directoryPath + sep) || !(await stat(file)).isFile()) {
        response.writeHead(404).end();
        return;
      }
      const data = await readFile(file);
      response.writeHead(200, {
        'Content-Type': mimeType(file),
        'Cache-Control': 'no-store',
        'Content-Length': data.length,
      });
      response.end(data);
    } catch {
      response.writeHead(404);
      response.end();
    }
  });
  await new Promise((ready) => server.listen(0, '127.0.0.1', ready));
  const address = server.address();
  const origin = `http://127.0.0.1:${
    typeof address === 'object' && address !== null ? address.port : 0
  }`;
  return { server, origin };
}

function markdown(result) {
  if (result.status === 'NOT_RUN') {
    return `# 286 — browser probe

Generated by \`npm run pedestrians:live:probe\` on ${result.generatedAt}.

**NOT_RUN** — ${result.reason}

No PASS is simulated. The deterministic 286 report and the native integration test cover the
contracts.
`;
  }
  const run = result.run;
  const checks = run?.checks ?? [];
  if (result.status !== 'PASS') {
    return `# 286 — browser probe

Generated by \`npm run pedestrians:live:probe\` on ${result.generatedAt}.

**${result.status}** — ${result.reason ?? 'unknown failure'}

Page errors: ${run?.pageErrors ?? 0}; console errors: ${run?.consoleErrors ?? 0}.

${(run?.errors ?? []).map((line) => `- ${line}`).join('\n')}
${(run?.console ?? []).map((line) => `- console: ${line}`).join('\n')}

No PASS is simulated.
`;
  }
  return `# 286 — browser probe

Generated by \`npm run pedestrians:live:probe\` on ${result.generatedAt}; Chromium ${run.browser},
viewport ${run.viewport}. The page runs the real 164 pedestrian population, the real 165 hazards and
the real 282 Rapier world.

| Metric | Value |
| --- | --- |
| Pedestrian crossing | tick ${run.pedestrian.crossingTick} |
| Physical yield | ${run.pedestrian.yieldOutcome} at tick ${run.pedestrian.yieldTick} |
| Speed at yield | ${run.pedestrian.speedAtYield.toFixed(2)} m/s |
| Pedestrian stop during crossing | ${run.pedestrian.stopDuringCrossing} |
| Obstacle outcome | ${run.obstacle.outcome} at tick ${run.obstacle.tick} |
| Obstacle contact | ${run.obstacle.contact ?? 'none'} |
| Obstacle clearance | ${run.obstacle.minimumDistanceM?.toFixed(2)} m |
| Physical hazard boxes | ${run.obstacle.physicalHazards} |
| Incidents | ${run.obstacle.incidents} |
| Page errors / console errors | ${run.pageErrors} / ${run.consoleErrors} |

Checks: ${checks.filter((check) => check.pass).length}/${checks.length} passed.

${checks.map((check) => `- \`${check.name}\`: ${check.pass ? 'PASS' : 'FAIL'} - ${check.detail}`).join('\n')}

Screenshots: ${run.screenshots.map((file) => `[${file}](${file})`).join(', ')}.
`;
}

const generatedAt = new Date().toISOString();
await mkdir(screenshots, { recursive: true });
const playwright = await loadPlaywright();
if (playwright === null) {
  const result = {
    version: '286-live-pedestrians-browser-v1',
    generatedAt,
    status: 'NOT_RUN',
    reason:
      'Playwright is not installed in this checkout (no `playwright` module and no PLAYWRIGHT_MODULE); the browser probe was not run.',
    run: null,
  };
  await writeFile(browserJson, `${JSON.stringify(result, null, 2)}\n`);
  await writeFile(browserMarkdown, markdown(result));
  console.log('286 browser probe NOT_RUN: Playwright is not installed.');
  process.exit(0);
}

const { build } = await import('vite');
await build({
  configFile: join(root, 'vite.config.ts'),
  logLevel: 'error',
  build: {
    outDir: buildDirectory,
    emptyOutDir: true,
    rollupOptions: { input: join(root, 'tests', 'browser', 'live-pedestrians', 'index.html') },
  },
});
const { server, origin } = await serve(buildDirectory);
const { chromium } = playwright.default ?? playwright;
const channel = process.env.PLAYWRIGHT_CHANNEL || undefined;
let browser;
try {
  browser = await chromium.launch({
    headless: true,
    ...(channel === undefined ? {} : { channel }),
    args: [
      '--use-gl=angle',
      '--use-angle=swiftshader',
      '--enable-unsafe-swiftshader',
      '--disable-gpu-sandbox',
      '--disable-frame-rate-limit',
    ],
  });
} catch (error) {
  const result = {
    version: '286-live-pedestrians-browser-v1',
    generatedAt,
    status: 'NOT_RUN',
    reason: `Browser launch failed: ${error instanceof Error ? error.message : String(error)}`,
    run: null,
  };
  await writeFile(browserJson, `${JSON.stringify(result, null, 2)}\n`);
  await writeFile(browserMarkdown, markdown(result));
  server.close();
  console.log('286 browser probe NOT_RUN: browser launch failed.');
  process.exit(0);
}

const pageErrors = [];
const consoleErrors = [];
const consoleLines = [];
const captured = [];
try {
  const context = await browser.newContext({ viewport: { width: 1100, height: 620 } });
  const page = await context.newPage();
  page.on('pageerror', (error) => pageErrors.push(String(error)));
  page.on('console', (message) => {
    if (message.type() === 'error') consoleErrors.push(message.text());
    else consoleLines.push(message.text());
  });
  await page.bringToFront();
  await page.goto(`${origin}/tests/browser/live-pedestrians/index.html`, {
    waitUntil: 'load',
    timeout: 90000,
  });
  await page.waitForFunction(() => globalThis.__livePedestriansProbe?.ready === true, null, {
    timeout: 120000,
    polling: 100,
  });

  await page.evaluate(() => globalThis.__livePedestriansProbe.start('PEDESTRIAN'));
  let pedestrian = await page.evaluate(() => globalThis.__livePedestriansProbe.read());
  for (let index = 0; index < 400 && pedestrian.crossingTick === null; index += 1) {
    await page.evaluate(() => globalThis.__livePedestriansProbe.advance(5));
    pedestrian = await page.evaluate(() => globalThis.__livePedestriansProbe.read());
  }
  await page.screenshot({ path: join(screenshots, 'pedestrian-crossing.png'), timeout: 60000 });
  captured.push('screenshots/pedestrian-crossing.png');
  for (let index = 0; index < 400 && pedestrian.yieldTick === null; index += 1) {
    await page.evaluate(() => globalThis.__livePedestriansProbe.advance(5));
    pedestrian = await page.evaluate(() => globalThis.__livePedestriansProbe.read());
  }
  await page.waitForTimeout(120);
  pedestrian = await page.evaluate(() => globalThis.__livePedestriansProbe.read());
  await page.screenshot({ path: join(screenshots, 'physical-yield.png'), timeout: 60000 });
  captured.push('screenshots/physical-yield.png');

  await page.evaluate(() => globalThis.__livePedestriansProbe.start('OBSTACLE'));
  let obstacle = await page.evaluate(() => globalThis.__livePedestriansProbe.read());
  await page.evaluate(() => globalThis.__livePedestriansProbe.advance(70));
  obstacle = await page.evaluate(() => globalThis.__livePedestriansProbe.read());
  await page.screenshot({ path: join(screenshots, 'obstacle-approach.png'), timeout: 60000 });
  captured.push('screenshots/obstacle-approach.png');
  for (
    let index = 0;
    index < 400 && (obstacle.obstacleOutcome === null || obstacle.obstacleOutcome === 'PENDING');
    index += 1
  ) {
    await page.evaluate(() => globalThis.__livePedestriansProbe.advance(5));
    obstacle = await page.evaluate(() => globalThis.__livePedestriansProbe.read());
  }
  await page.waitForTimeout(120);
  obstacle = await page.evaluate(() => globalThis.__livePedestriansProbe.read());
  await page.screenshot({ path: join(screenshots, 'obstacle-avoidance.png'), timeout: 60000 });
  captured.push('screenshots/obstacle-avoidance.png');

  const checks = [];
  const check = (name, pass, detail) => checks.push({ name, pass, detail });
  check(
    'pedestrian-visible',
    pedestrian.pedestrians > 0 && pedestrian.meshes.pedestrians > 0,
    `${pedestrian.pedestrians} active, ${pedestrian.meshes.pedestrians} meshes`,
  );
  check(
    'crossing-phase',
    pedestrian.crossingTick !== null && pedestrian.crossings.crossingsStarted > 0,
    `crossing tick ${pedestrian.crossingTick}, started ${pedestrian.crossings.crossingsStarted}`,
  );
  check(
    'physical-yield',
    pedestrian.yieldOutcome === 'YIELDED' &&
      pedestrian.yieldTick !== null &&
      pedestrian.crossingTick !== null &&
      pedestrian.yieldTick >= pedestrian.crossingTick &&
      pedestrian.speedMps <= 0.2,
    `yield ${pedestrian.yieldOutcome} at ${pedestrian.yieldTick}, speed ${pedestrian.speedMps.toFixed(2)}`,
  );
  check(
    'stop-during-crossing',
    pedestrian.stops > 0,
    `${pedestrian.stops} pedestrian stop(s) during crossing`,
  );
  check(
    'obstacle-visible',
    obstacle.meshes.hazards > 0 && obstacle.physicalHazards === 1,
    `${obstacle.meshes.hazards} hazard mesh(es), ${obstacle.physicalHazards} physical`,
  );
  check(
    'obstacle-same-physics',
    obstacle.physicsObstacles.added >= 1 && obstacle.incidents === 0,
    `physics added ${obstacle.physicsObstacles.added}, incidents ${obstacle.incidents}`,
  );
  check(
    'obstacle-avoided',
    (obstacle.obstacleOutcome === 'PASSED_CLEAR' || obstacle.obstacleOutcome === 'STOPPED') &&
      obstacle.obstacleContact === null &&
      obstacle.minimumDistanceM !== null &&
      obstacle.minimumDistanceM > 1.5,
    `${obstacle.obstacleOutcome}, contact ${obstacle.obstacleContact ?? 'none'}, clearance ${obstacle.minimumDistanceM?.toFixed(2)}`,
  );
  const failed = checks.filter((entry) => !entry.pass);
  const result = {
    version: '286-live-pedestrians-browser-v1',
    generatedAt,
    status: failed.length === 0 && pageErrors.length === 0 ? 'PASS' : 'FAIL',
    reason:
      failed.length === 0
        ? null
        : failed.map((entry) => `${entry.name}: ${entry.detail}`).join('; '),
    run: {
      browser: browser.version(),
      viewport: '1100x620',
      pedestrian: {
        crossingTick: pedestrian.crossingTick,
        yieldTick: pedestrian.yieldTick,
        yieldOutcome: pedestrian.yieldOutcome,
        speedAtYield: pedestrian.speedMps,
        stopDuringCrossing: pedestrian.stops,
        crossings: pedestrian.crossings,
      },
      obstacle: {
        tick: obstacle.tick,
        outcome: obstacle.obstacleOutcome,
        contact: obstacle.obstacleContact,
        minimumDistanceM: obstacle.minimumDistanceM,
        physicalHazards: obstacle.physicalHazards,
        incidents: obstacle.incidents,
        physicsObstacles: obstacle.physicsObstacles,
        hud: obstacle.hud,
      },
      checks,
      pageErrors: pageErrors.length,
      consoleErrors: consoleErrors.length,
      errors: [...pageErrors, ...consoleErrors],
      console: consoleLines.slice(0, 20),
      screenshots: captured,
    },
  };
  await writeFile(browserJson, `${JSON.stringify(result, null, 2)}\n`);
  await writeFile(browserMarkdown, markdown(result));
  console.log(
    `286 browser probe ${result.status}: ${checks.filter((e) => e.pass).length}/${checks.length}`,
  );
  if (result.status !== 'PASS') process.exitCode = 1;
} catch (error) {
  const result = {
    version: '286-live-pedestrians-browser-v1',
    generatedAt,
    status: 'FAIL',
    reason: `Probe error: ${error instanceof Error ? error.message : String(error)}`,
    run: {
      pageErrors: pageErrors.length,
      consoleErrors: consoleErrors.length,
      errors: [
        ...pageErrors,
        ...consoleErrors,
        error instanceof Error ? error.message : String(error),
      ],
      console: consoleLines.slice(0, 20),
      checks: [],
      screenshots: captured,
    },
  };
  await writeFile(browserJson, `${JSON.stringify(result, null, 2)}\n`);
  await writeFile(browserMarkdown, markdown(result));
  console.log('286 browser probe FAIL');
  process.exitCode = 1;
} finally {
  await browser.close();
  server.close();
}
