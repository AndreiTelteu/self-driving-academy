import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import './register-typescript.mjs';

/**
 * Deterministic visual-semantic report for the PBI042 neighbourhood.
 *
 * It reads the real 032 map, derives the city layout, builds the Babylon scene on a NullEngine and
 * writes the rendered-element inventory, source coverage and alignment result. No simulation state,
 * browser or GPU is required; the same numbers are asserted by the tests.
 *
 * Usage: node scripts/city-visual-report.mjs [--json <file>] [--md <file>]
 */
const root = dirname(dirname(fileURLToPath(import.meta.url)));
const world = pathToFileURL(join(root, 'src/world/index.ts')).href;
const cityScene = pathToFileURL(join(root, 'src/rendering/babylon/city-scene.ts')).href;
const { createNeighbourhoodMap, createCityLayout, createCityLayoutReport, verifyCityAlignment } =
  await import(world);
const { NullEngine } = await import('@babylonjs/core/Engines/nullEngine.js');
const { Scene } = await import('@babylonjs/core/scene.js');
const { createCityScene } = await import(cityScene);

const args = process.argv.slice(2);
const option = (name) => {
  const index = args.indexOf(name);
  return index >= 0 ? args[index + 1] : null;
};

const map = createNeighbourhoodMap();
const layout = createCityLayout(map);
const engine = new NullEngine();
const scene = new Scene(engine);
const city = createCityScene(scene, layout);
const rendered = city.getRenderedElementIds();
const report = createCityLayoutReport(layout, rendered);
const issues = verifyCityAlignment(map, layout);
const resources = city.getResourceCounts();

const unrenderedByType = report.unrendered.reduce((counts, entry) => {
  counts[entry.sourceType] = (counts[entry.sourceType] ?? 0) + 1;
  return counts;
}, {});

const junctions = layout.intersections.map((intersection) => {
  const crosswalkIds = new Set();
  for (const laneId of intersection.incomingLaneIds)
    for (const crosswalkId of map.crosswalks)
      if (crosswalkId.laneIds.includes(laneId)) crosswalkIds.add(crosswalkId.id);
  const heads = layout.elements.filter(
    (element) =>
      element.kind === 'SIGNAL_HEAD' && element.intersectionId === intersection.intersectionId,
  );
  const stopLines = layout.elements.filter(
    (element) =>
      element.kind === 'STOP_LINE' && element.intersectionId === intersection.intersectionId,
  );
  return {
    id: intersection.intersectionId,
    type: intersection.type,
    incomingLanes: intersection.incomingLaneIds.length,
    movements: intersection.movementIds.length,
    signalHeads: heads.length,
    stopLines: stopLines.length,
    crosswalks: crosswalkIds.size,
  };
});

const payload = {
  fixture: '042-city-visual-v1',
  mapId: map.mapId,
  sourceEntities: {
    lanes: map.lanes.length,
    intersections: map.intersections.length,
    signals: map.signals.length,
    stopLines: map.stopLines.length,
    crosswalks: map.crosswalks.length,
    serviceZones: map.serviceZones.length,
    movements: map.intersections.reduce((sum, junction) => sum + junction.movements.length, 0),
    conflictZones: map.intersections.reduce(
      (sum, junction) => sum + junction.conflictZones.length,
      0,
    ),
    recoveryPoints: map.recoveryPoints.length,
  },
  layout: {
    elements: layout.stats.elements,
    elementsByKind: layout.stats.elementsByKind,
    elementsBySourceType: layout.stats.elementsBySourceType,
    footprintVertices: layout.stats.footprintVertices,
    blocks: layout.stats.blocks,
    buildings: layout.stats.buildings,
  },
  scene: {
    ...city.stats,
    resources,
    meshesAfterDisposeProbe: null,
  },
  report: {
    intersectionTypes: report.intersectionTypes,
    roadClasses: report.roadClasses,
    unrenderedByType,
    unrenderedTotal: report.unrendered.length,
    phantomElementIds: report.phantomElementIds.length,
    missingRenderedElementIds: report.missingRenderedElementIds.length,
    unknownRenderedElementIds: report.unknownRenderedElementIds.length,
  },
  alignment: { issues: issues.length, firstIssues: issues.slice(0, 10) },
  junctions,
};

city.dispose();
payload.scene.meshesAfterDisposeProbe = {
  meshes: scene.meshes.length,
  materials: scene.materials.length,
  geometries: scene.geometries.length,
  nodes: scene.transformNodes.length,
};
scene.dispose();
engine.dispose();

const jsonPath = option('--json');
if (jsonPath) await writeFile(jsonPath, `${JSON.stringify(payload, null, 2)}\n`);

const lines = [
  '# PBI042 deterministic geometry report',
  '',
  `Generated by \`node scripts/city-visual-report.mjs\` for \`${payload.mapId}\`.`,
  '',
  `Source entities: ${Object.entries(payload.sourceEntities)
    .map(([key, value]) => `${key}=${value}`)
    .join(', ')}`,
  '',
  '| Rendered element | Count |',
  '| --- | ---: |',
  ...Object.entries(payload.layout.elementsByKind).map(([kind, count]) => `| ${kind} | ${count} |`),
  '',
  `Elements: **${payload.layout.elements}**; footprint vertices: ${payload.layout.footprintVertices}; blocks: ${payload.layout.blocks}; buildings: ${payload.layout.buildings}.`,
  '',
  `Babylon meshes: **${payload.scene.meshes}** (${payload.scene.batches} merged batches, ${payload.scene.individualElements} individual elements, ${payload.scene.mergedElements} merged elements, ${payload.scene.vertices} vertices, ${payload.scene.triangles} triangles).`,
  '',
  `Intersection types: SIGNALIZED=${payload.report.intersectionTypes.SIGNALIZED}, STOP_CONTROLLED=${payload.report.intersectionTypes.STOP_CONTROLLED}, UNCONTROLLED=${payload.report.intersectionTypes.UNCONTROLLED}.`,
  `Road classes: ARTERIAL=${payload.report.roadClasses.ARTERIAL}, RESIDENTIAL=${payload.report.roadClasses.RESIDENTIAL}.`,
  '',
  'Unrendered source entities (explicit, no silent omission):',
  '',
  '| Source type | Count | Reason |',
  '| --- | ---: | --- |',
  ...Object.entries(unrenderedByType).map(
    ([type, count]) => `| ${type} | ${count} | SEMANTIC_ONLY |`,
  ),
  '',
  `Phantom elements: ${payload.report.phantomElementIds}; missing rendered: ${payload.report.missingRenderedElementIds}; unknown rendered: ${payload.report.unknownRenderedElementIds}; alignment issues: ${payload.alignment.issues}.`,
  '',
  '| Junction | Type | Incoming lanes | Movements | Signal heads | Stop lines | Crosswalks |',
  '| --- | --- | ---: | ---: | ---: | ---: | ---: |',
  ...junctions.map(
    (junction) =>
      `| ${junction.id} | ${junction.type} | ${junction.incomingLanes} | ${junction.movements} | ${junction.signalHeads} | ${junction.stopLines} | ${junction.crosswalks} |`,
  ),
  '',
  `Disposal probe after \`dispose()\`: meshes=${payload.scene.meshesAfterDisposeProbe.meshes}, materials=${payload.scene.meshesAfterDisposeProbe.materials}, geometries=${payload.scene.meshesAfterDisposeProbe.geometries}, nodes=${payload.scene.meshesAfterDisposeProbe.nodes}.`,
  '',
];
const mdPath = option('--md');
if (mdPath) await writeFile(mdPath, lines.join('\n'));
else process.stdout.write(`${lines.join('\n')}\n`);
