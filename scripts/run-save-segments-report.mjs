import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  directory = join(root, 'Docs', 'Evidence', '129-save-segments'),
  defaultOutput = join(directory, 'report.json'),
  reportMarkdown = join(directory, 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function rows(entries) {
  return entries.map(([label, entry]) => `| ${label} | ${value(entry)} |`).join('\n');
}

function markdown(report) {
  const checks = report.checks
    .map(
      (entry) =>
        `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
    )
    .join('\n');
  return `# 129 Segment and checkpoint save report

Machine-readable transcript: [report.json](report.json). Generated by
\`${report.generatedBy}\`; the transcript has no wall-clock value and is deterministic.

Version: \`${report.version}\`.

Oracle rule: ${report.oracleRule}

## Closed segment

| Field | Value |
| --- | --- |
${rows([
  ['Write status', report.closedSegment.status],
  ['Completeness', report.closedSegment.completeness],
  ['Incomplete reason', report.closedSegment.reason],
  ['Close reason', report.closedSegment.closeReason],
  ['Stored events', report.closedSegment.eventCount],
  ['Declared events', report.closedSegment.expectedEventCount],
  ['First event', report.closedSegment.firstEventId],
  ['Last event', report.closedSegment.lastEventId],
  ['Event sequences', report.closedSegment.sequences],
  ['Sealed', report.closedSegment.sealed],
  ['Digest matches', report.closedSegment.digestMatches],
])}

## Long intervention

| Field | Value |
| --- | --- |
${rows([
  ['Chunks', report.longIntervention.chunkCount],
  ['Stored events', report.longIntervention.eventCount],
  ['Completeness', report.longIntervention.completeness],
  ['Missing chunks', report.longIntervention.missingChunks],
  ['Sequences monotonic', report.longIntervention.sequencesMonotonic],
])}

## Crash before the chunks

| Field | Value |
| --- | --- |
${rows([
  ['Write status', report.crashBeforeChunks.writeStatus],
  ['Completeness', report.crashBeforeChunks.completeness],
  ['Reason', report.crashBeforeChunks.reason],
  ['Stored events', report.crashBeforeChunks.storedEvents],
  ['Declared events', report.crashBeforeChunks.expectedEvents],
  ['Missing chunks', report.crashBeforeChunks.missingChunks],
])}

## Crash in the middle of the chunks

| Field | Value |
| --- | --- |
${rows([
  ['Write status', report.crashInTheMiddle.writeStatus],
  ['Completeness', report.crashInTheMiddle.completeness],
  ['Reason', report.crashInTheMiddle.reason],
  ['Stored events', report.crashInTheMiddle.storedEvents],
  ['Declared events', report.crashInTheMiddle.expectedEvents],
  ['Present chunks', report.crashInTheMiddle.presentChunks],
  ['Missing chunks', report.crashInTheMiddle.missingChunks],
])}

## Missing and tampered chunk

| Field | Value |
| --- | --- |
${rows([
  ['Missing chunk completeness', report.missingChunk.completeness],
  ['Missing chunk reason', report.missingChunk.reason],
  ['Missing chunk stored events', report.missingChunk.storedEvents],
  ['Missing chunk declared events', report.missingChunk.expectedEvents],
  ['Missing chunk indices', report.missingChunk.missingChunks],
  ['Tampered completeness', report.tamperedChunk.completeness],
  ['Tampered reason', report.tamperedChunk.reason],
  ['Tampered digest matches', report.tamperedChunk.digestMatches],
  ['Incomplete source completeness', report.incompleteSource.completeness],
  ['Incomplete source reason', report.incompleteSource.reason],
  ['Incomplete source detail', report.incompleteSource.sourceReason],
])}

## Write queue

| Field | Value |
| --- | --- |
${rows([
  ['Rows written while the input loop continued', report.writeQueue.rowsBeforeTheGate],
  ['Rows after the drain', report.writeQueue.rowsAfterDrain],
  ['Settled order', report.writeQueue.settledOrder],
  ['Written segments', report.writeQueue.written],
  ['Refused segments', report.writeQueue.refused],
  ['Refusal code', report.writeQueue.refusalCode],
])}

## Checkpoint of an active intervention

| Field | Value |
| --- | --- |
${rows([
  ['Write status', report.checkpoint.status],
  ['Generation', report.checkpoint.generation],
  ['Learning epoch', report.checkpoint.learningEpoch],
  ['Body fields', report.checkpoint.bodyKeys],
  ['Older generation', report.checkpoint.olderGeneration],
  ['Contains a world snapshot', report.checkpoint.hasWorldSnapshot],
])}

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'persistence', 'save-segments-report.ts')).href
  ),
  report = await reportModule.runSaveSegmentsReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`Save segments report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`Save segments report is current: ${output}`);
} else {
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
