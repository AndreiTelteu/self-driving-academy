import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  defaultOutput = join(root, 'Docs', 'Evidence', '062-pickup', 'report.json'),
  reportMarkdown = join(root, 'Docs', 'Evidence', '062-pickup', 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function markdown(report) {
  const checks = report.checks
      .map(
        (entry) =>
          `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
      )
      .join('\n'),
    reasons = report.checks.find((entry) => entry.name === 'rejection-reasons')?.actual ?? [],
    simulation = report.simulation,
    zoneRejections = report.zoneRejections;
  return `# 062 pickup report

Machine-readable transcript: [report.json](report.json). Generated by
\`npm run ride:pickup\`; the transcript contains no wall-clock value and is deterministic.

Version: \`${report.version}\`; ${report.fleet.taxis} taxis and ${report.fleet.civilians} civilians from
the real 057 registry, ${report.fleet.requests} requests from the real 059 schedule and real 060
assignments, resolved against the real 032 service-zone polygons.

## Rules

| Rule | Value |
| --- | ---: |
| Tick rate | ${report.defaults.tickRateHz} Hz |
| Speed threshold | ${report.defaults.speedThresholdMps} m/s |
| Required dwell | ${report.defaults.dwellTicks} ticks (${report.defaults.dwellTicks / report.defaults.tickRateHz} s) |
| Displacement tolerance | ${report.defaults.displacementToleranceM} m |

Closed rejection reasons: ${reasons.join(', ')}.

## Exact dwell

| Field | Value |
| --- | --- |
| Start tick | ${report.exactDwell.startTick} |
| Board tick | ${report.exactDwell.boardTick} |
| Pending dwell before boarding | ${report.exactDwell.pendingBeforeBoard} |
| Dwell at boarding | ${report.exactDwell.dwellAtBoard} ticks (${report.exactDwell.dwellSeconds} s) |
| State after boarding | ${report.exactDwell.stateAfterBoard} |
| Events | ${report.exactDwell.events.join(' → ')} |
| Transition ticks | ${report.exactDwell.transitionTicks.join(', ')} |
| Replay duplicate | ${report.exactDwell.replayDuplicate} |
| Transitions after replay | ${report.exactDwell.transitionsAfterReplay} |

## Rejections

| Probe | Result |
| --- | --- |
| Fast pass | ${report.fastPass.samples} samples (${report.fastPass.insideSamples} inside the zone), reasons ${report.fastPass.reasons.join(', ')}, max dwell ${report.fastPass.maxDwell}, state ${report.fastPass.state} |
| Outside the pickup zone | ${zoneRejections.outside.samples} samples, ${zoneRejections.outside.reason} |
| Other authored pickup zone (${zoneRejections.otherPickupZone.zoneId}) | ${zoneRejections.otherPickupZone.samples} samples, ${zoneRejections.otherPickupZone.reason} |
| Dropoff-only zone | ${zoneRejections.dropoffZone.samples} samples, ${zoneRejections.dropoffZone.reason} |
| Exact boundary | in zone=${report.boundary.exactBoundaryInZone}, ${report.boundary.exactBoundaryReason} |
| Just outside the boundary | ${report.boundary.outsideReason} |
| Re-entered zone | ${report.boundary.reentryReason}, boards at ${report.boundary.boardTick} |
| Unknown / foreign / cancelled ride | ${report.wrongRide.unknown} / ${report.wrongRide.foreign} / ${report.wrongRide.cancelled} |
| Stale before / after advance | ${report.stale.staleBefore} / ${report.stale.staleAfterAdvance} |
| Same-tick / later boarding replay | ${report.idempotency.sameTickDuplicate} / ${report.idempotency.laterDuplicate} |

## Simulation (real 059 schedule, real 060 dispatcher, real 032 zones)

| Metric | Value |
| --- | ---: |
| Requests | ${simulation.requests} |
| Assignments / boardings | ${simulation.assignments} / ${simulation.boarded} |
| Completed / failed / cancelled | ${simulation.completed} / ${simulation.failed} / ${simulation.cancelled} |
| Active after horizon | ${simulation.active} |
| Dispatcher releases | ${simulation.releases} |
| Unique pickup zones | ${simulation.uniquePickupZones} |
| Unique boarding event ids | ${simulation.uniqueBoardedEvents} |
| Dwell min / max | ${simulation.minDwellTicks} / ${simulation.maxDwellTicks} |
| Rides with exact dwell | ${simulation.exactDwellRides} |
| Pickup rejections / duplicates | ${simulation.pickupRejections} / ${simulation.pickupDuplicates} |
| Transitions per ride min / max | ${simulation.minTransitions} / ${simulation.maxTransitions} |
| Duplicate taxi ownership | ${simulation.duplicateTaxis} |

## Disposal

| Metric | Value |
| --- | --- |
| Disposed | ${report.disposal.disposed} |
| Attempts / boardings after disposal | ${report.disposal.attempts} / ${report.disposal.boardings} |
| Observations / boarded / tick after disposal | ${report.disposal.observations} / ${report.disposal.boarded} / ${report.disposal.tick} |
| Ride state / taxi status / releases | ${report.disposal.rideState} / ${report.disposal.taxiStatus} / ${report.disposal.releases} |

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'fleet', 'pickup-report.ts')).href
  ),
  report = reportModule.runPickupReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, boardings ${report.simulation.boarded}, dwell ${report.defaults.dwellTicks} ticks, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`Pickup report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`Pickup report is current: ${output}`);
} else {
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
