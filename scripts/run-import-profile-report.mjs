import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  directory = join(root, 'Docs', 'Evidence', '134-import-profile'),
  defaultOutput = join(directory, 'report.json'),
  reportMarkdown = join(directory, 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function rows(entries) {
  return entries.map(([label, entry]) => `| ${label} | ${value(entry)} |`).join('\n');
}

function markdown(report) {
  const checks = report.checks
    .map(
      (entry) =>
        `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
    )
    .join('\n');
  return `# 134 Import profile report

Machine-readable transcript: [report.json](report.json). Generated by
\`${report.generatedBy}\`; the transcript has no wall-clock value and is deterministic.

Version: \`${report.version}\`. Contract: \`${report.contract}\`.

Oracle rule: ${report.oracleRule}

## Format and budgets

| Field | Value |
| --- | --- |
${rows([
  ['Format', report.format.format],
  ['Format version', report.format.formatVersion],
  ['Schema version', report.format.schemaVersion],
  ['Maximum file bytes', report.format.maxFileBytes],
  ['Maximum versions', report.format.maxVersions],
])}

## Validation

| Field | Value |
| --- | --- |
${rows([
  ['Status', report.validation.status],
  ['Checksum verified', report.validation.checksumVerified],
  ['Versions', report.validation.versions],
  ['Base versions', report.validation.baseVersions],
  ['Derived versions', report.validation.derivedVersions],
  ['Tip version', report.validation.tipVersionId],
  ['Active version named by the file', report.validation.activeVersionId],
  ['Reserved (R) parameters', report.validation.reservedParameters],
  ['Canonical bytes', report.validation.bytes],
])}

## Atomic import

| Field | Value |
| --- | --- |
${rows([
  ['Status', report.import.status],
  ['Version ids', report.import.versionIds],
  ['Versions created', report.import.versionsCreated],
  ['Versions already present', report.import.versionsExisting],
  ['Activated by the import', report.import.activated],
  ['Activation payload', report.import.activation],
  ['Stored versions', report.import.storedVersions],
  ['Stored active version', report.import.storedActiveVersionId],
  ['Stored activation sequence', report.import.storedActivationSequence],
])}

## Explicit 205/110 activation

| Field | Value |
| --- | --- |
${rows([
  ['Stale tick refusal', report.activation.staleTickCode],
  ['Tick 0 status', report.activation.pendingStatus],
  ['Tick 0 writes an activation', report.activation.pendingWritesActivation],
  ['Tick 1 status', report.activation.appliedStatus],
  ['Stored sequence', report.activation.sequence],
  ['Learning epoch', report.activation.lifecycleEpoch],
  ['110 activate-at tick', report.activation.activateAtTick],
  ['Durable version', report.activation.durableVersionId],
  ['Fleet before the 110 tick', report.activation.fleetBefore],
  ['Fleet after the 110 tick', report.activation.fleetApplied],
  ['Old-generation result', report.activation.lateResultStatus],
  ['Old-generation accepted', report.activation.lateResultAccepted],
  ['Repeated activation', report.activation.repeatedStatus],
])}

## Closed refusals

| Field | Value |
| --- | --- |
${rows([
  ['Modified document', report.refusals.modifiedDocument],
  ['Per-version 109 checksum', report.refusals.perVersionChecksum],
  ['Unknown unit', report.refusals.unknownUnit],
  ['Out of the 092 range', report.refusals.outOfRange],
  ['Reserved key with a value', report.refusals.reservedKeyWithValue],
  ['Unknown usable key', report.refusals.unknownParameter],
  ['Newer schema', report.refusals.schemaTooNew],
  ['Newer format', report.refusals.formatVersionTooNew],
  ['Malformed JSON', report.refusals.malformedJson],
  ['Duplicate key', report.refusals.duplicateKey],
  ['Above the size budget', report.refusals.fileTooLarge],
  ['Above the size budget, imported', report.refusals.fileTooLargeImported],
])}

## Atomicity

| Field | Value |
| --- | --- |
${rows([
  ['Fault code', report.atomicity.faultCode],
  ['Stored versions after the fault', report.atomicity.storedVersionsAfterFault],
  ['Activation after the fault', report.atomicity.activationAfterFault],
  ['Versions created by the retry', report.atomicity.retryCreated],
])}

## Digest

| Field | Value |
| --- | --- |
${rows([
  ['Canonical bytes', report.digest.canonicalBytes],
  ['Platform SHA-256', report.digest.platform],
  ['Own SHA-256', report.digest.own],
  ['Equal', report.digest.equal],
])}

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'persistence', 'import-profile-report.ts')).href
  ),
  report = await reportModule.runImportProfileReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, contract ${report.contract}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`Import profile report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`Import profile report is current: ${output}`);
  const savedMarkdown = await readFile(reportMarkdown, 'utf8');
  if (savedMarkdown !== markdown(report)) {
    console.error(`Import profile report markdown is stale: ${reportMarkdown}`);
    process.exitCode = 1;
  } else console.log(`Import profile report markdown is current: ${reportMarkdown}`);
} else {
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
