import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  evidenceDir = join(root, 'Docs', 'Evidence', '217-three-modes'),
  defaultOutput = join(evidenceDir, 'report.json'),
  reportMarkdown = join(evidenceDir, 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

const checkMode = process.argv.includes('--check'),
  output = argument('--output') ?? defaultOutput;

/**
 * Targeted-validation-v1 preflight: the full suite runs once before the probe. The single skipped
 * assertion is this PBI's artifact-freshness check, which is by definition stale before the
 * artifact is regenerated; every other test runs unchanged.
 */
function preflight() {
  console.log('PREFLIGHT full test suite (npm test) before the latency probe');
  const result = spawnSync(
    process.execPath,
    ['--import', './scripts/register-typescript.mjs', '--test', 'tests/**/*.test.ts'],
    {
      cwd: root,
      stdio: 'inherit',
      env: { ...process.env, THREE_MODES_PREFLIGHT: '1' },
    },
  );
  if (result.status !== 0) {
    console.error('Preflight failed: the full suite is not green; the probe was not measured.');
    process.exit(1);
  }
  console.log('PREFLIGHT PASS');
}

function matrixRowTable(rows) {
  return rows
    .map(
      (row) =>
        `| ${row.kind} | ${row.transition} | ${row.action} | ${row.previousTick} | ${row.atTick} | ${row.closed.segmentId ?? '—'} | ${row.closed.mode ?? '—'} | ${row.closed.closeReason ?? '—'} | ${row.opened.segmentId ?? '—'} | ${row.opened.mode ?? '—'} | ${row.opened.learningEligible ?? '—'} | ${row.seat.count} | ${row.physics.preserved} | ${row.learning.status ?? '—'} | ${row.learning.versionId ?? '—'} | ${row.ok ? 'PASS' : 'FAIL'} |`,
    )
    .join('\n');
}

function scenarioTable(report) {
  const lines = [];
  for (const scenario of report.scenarios) {
    lines.push(
      `| ${scenario.id} | ${scenario.checks.length} | ${scenario.checks.filter((entry) => entry.pass).length} | ${scenario.ok ? 'PASS' : 'FAIL'} | ${scenario.description} |`,
    );
  }
  return lines.join('\n');
}

function checkTable(checks) {
  return checks
    .map(
      (entry) =>
        `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} |`,
    )
    .join('\n');
}

function latencyTable(latency) {
  if (latency === null)
    return '| — | — | — | — | — | — |\nThe committed report was generated without the local probe.';
  const rows = [
    ['Mode intent → accepted transition', latency.modeIntentToAcceptedTransition],
    ['Selection change → accepted camera target', latency.selectionChangeToCameraTarget],
    [
      'LEARNING close → 103 queue admission (busy worker)',
      latency.learningSegmentCloseToQueueAdmission,
    ],
  ];
  return rows
    .map(
      ([label, stats]) =>
        `| ${label} | ${stats.samples} | ${stats.minMs} | ${stats.p50Ms} | ${stats.p95Ms} | ${stats.maxMs} |`,
    )
    .join('\n');
}

function markdown(report) {
  const latency = report.latency,
    admission = latency?.learningSegmentCloseToQueueAdmission ?? null;
  return `# 217 AUTO / MANUAL / LEARNING report

Machine-readable transcript: [report.json](report.json). Generated by \`npm run modes:three\`.

Version: \`${report.version}\` · level \`${report.level}\` · scope \`${report.scope}\`.

## Oracle

${report.oracleRule}

## Preflight

${report.preflight.rule} (\`${report.preflight.suite}\`, run by \`${report.preflight.runBy}\`).

## Transition matrix (AUTO / MANUAL / LEARNING × TAXI / CIVIL)

| Class | Transition | Key | Before | Accepted | Closed | Closed mode | Close reason | Opened | Opened mode | Eligible | Seats | Physics | Learning | Version | Result |
| --- | --- | --- | ---: | ---: | --- | --- | --- | --- | --- | --- | ---: | --- | --- | --- | --- |
${matrixRowTable(report.matrix.rows)}

Counts: ${report.matrix.counts.transitionRows} transition rows, ${report.matrix.counts.closedSegments} closed segments,
${report.matrix.counts.manualClosed} MANUAL closes, ${report.matrix.counts.learningClosed} LEARNING closes,
max ${report.matrix.counts.maxPlayerSeats} PLAYER seat, ${report.matrix.counts.learningJobs} learning jobs,
${report.matrix.counts.profileVersions} profile versions, ${report.matrix.counts.manualPublications} MANUAL publications.

## Acceptance scenarios

| Scenario | Checks | Passed | Result | Description |
| --- | ---: | ---: | --- | --- |
${scenarioTable(report)}

## Latency (local, provisional, machine-local)

| Channel | Samples | min ms | p50 ms | p95 ms | max ms |
| --- | ---: | ---: | ---: | ---: | ---: |
${latencyTable(latency)}

${
  admission === null
    ? ''
    : `Admission samples taken with a busy serial worker: ${admission.busySamples}/${admission.samples};
confirmed admissions ${admission.admissions}; extra jobs from replayed segments ${admission.duplicateJobs}.
`
}
Local observation (informational, never a gate): mode p95 below one ${latency?.budget.tickMs ?? 16.6667} ms
tick = ${latency?.budget.modeIntentWithinTick ?? false}; selection p95 below one tick =
${latency?.budget.selectionChangeWithinTick ?? false}.

These are local single-process Node numbers with no FPS, GPU, renderer or hardware claim. They are
**excluded from \`--check\` equality**: the freshness comparison normalizes \`min/p50/p95/max/mean\` and
the one-tick observation to fixed values and keeps every structural field, exactly as documented in
\`Docs/three-modes.md\`.

## Checks

| Check | Expected | Actual | Result |
| --- | --- | --- | --- |
${checkTable(report.checks)}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Scenarios: ${report.scenarios.filter((entry) => entry.ok).length}/${report.scenarios.length}
- Matrix: ${report.matrix.pass ? 'PASS' : 'FAIL'}
- Determinism: ${report.determinism.identical} across ${report.determinism.runs} identical matrix runs
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}

## Limitations

${report.limitations.map((entry) => `- ${entry}`).join('\n')}
`;
}

const fixture = await import(
    pathToFileURL(join(root, 'tests', 'app', 'three-modes-fixture.ts')).href
  ),
  reportModule = await import(
    pathToFileURL(join(root, 'tests', 'app', 'three-modes-report.ts')).href
  ),
  services = fixture.createThreeModesServices();

if (!checkMode) preflight();

const report = await reportModule.runThreeModesReport(services, { measureLatency: true }),
  json = `${JSON.stringify(report, null, 2)}\n`;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, scenarios ${report.scenarios.filter((entry) => entry.ok).length}/${report.scenarios.length}, matrix ${report.matrix.pass ? 'PASS' : 'FAIL'}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (report.latency !== null) {
  const latency = report.latency;
  console.log(
    `LATENCY mode p50/p95/max ${latency.modeIntentToAcceptedTransition.p50Ms}/${latency.modeIntentToAcceptedTransition.p95Ms}/${latency.modeIntentToAcceptedTransition.maxMs} ms; selection ${latency.selectionChangeToCameraTarget.p50Ms}/${latency.selectionChangeToCameraTarget.p95Ms}/${latency.selectionChangeToCameraTarget.maxMs} ms; admission(busy) ${latency.learningSegmentCloseToQueueAdmission.p50Ms}/${latency.learningSegmentCloseToQueueAdmission.p95Ms}/${latency.learningSegmentCloseToQueueAdmission.maxMs} ms`,
  );
}

if (checkMode) {
  const saved = await readFile(output, 'utf8');
  const normalize = reportModule.normalizeThreeModesReport;
  if (JSON.stringify(normalize(JSON.parse(saved))) !== JSON.stringify(normalize(report))) {
    console.error(`217 three-mode report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`217 three-mode report is current (latency normalized): ${output}`);
} else {
  await mkdir(evidenceDir, { recursive: true });
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
