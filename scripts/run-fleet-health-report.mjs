import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  defaultOutput = join(root, 'Docs', 'Evidence', '065-fleet-health', 'report.json'),
  reportMarkdown = join(root, 'Docs', 'Evidence', '065-fleet-health', 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function markdown(report) {
  const checks = report.checks
      .map(
        (entry) =>
          `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
      )
      .join('\n'),
    fixture = report.fixture.populations
      .map(
        (entry) =>
          `| ${entry.taxis} | ${entry.civilians} | ${entry.total} | ${entry.requests} | ${entry.uniqueTaxis} | ${entry.lanesAssigned} | ${entry.reproducible} |`,
      )
      .join('\n');
  return `# 065 Fleet health and scenario reset report

Machine-readable transcript: [report.json](report.json). Generated by \`npm run fleet:health\`; the
transcript contains no wall-clock value and is deterministic.

Version: \`${report.version}\`; real 057 population, real 059 schedule, real 060 dispatcher, real 061
lifecycle, real 064 ETA and real 041 routes over the real 032 map.

## Closed contracts

| Contract | Values |
| --- | --- |
| Health states | ${report.states.join(', ')} |
| Facts | ${report.facts.join(', ')} |
| Reset policies | ${report.policies.join(', ')} |
| Taxis tracked | ${report.limits.taxis} |
| Fact history | ${report.limits.historyEntries} |
| Fact ids | ${report.limits.factIds} |

## Gate 220 fixture presets

| Taxis | Civilians | Total | Requests | Unique taxis | Lanes assigned | Reproducible |
| ---: | ---: | ---: | ---: | ---: | ---: | --- |
${fixture}

## Health facts and release

| Probe | Fact | Ride reason | Dispatcher status | Health | Claim released | Lifecycle release | Direct release |
| --- | --- | --- | --- | --- | --- | --- | --- |
| Damage | COLLISION_DAMAGE | ${report.damage.reason} | ${report.damage.dispatcherStatus} | ${report.damage.healthState} | ${report.damage.claimReleased} | ${report.damage.lifecycleReleaseReason} | ${report.damage.directReleaseReason} |
| Block | TRAFFIC_BLOCK | ${report.block.reason} | ${report.block.dispatcherStatus} | ${report.block.healthState} | ${report.block.claimReleased} | ${report.block.lifecycleReleaseReason} | ${report.block.directReleaseReason} |
| Offline | SERVICE_WITHDRAWN | ${report.offline.reason} | ${report.offline.dispatcherStatus} | ${report.offline.healthState} | ${report.offline.claimReleased} | ${report.offline.lifecycleReleaseReason} | ${report.offline.directReleaseReason} |

Claim without a ride: block \`${report.claimOnly.blockRelease}\`, withdrawal
\`${report.claimOnly.offlineRelease}\`, assignments after release ${report.claimOnly.assignments},
statuses ${report.claimOnly.statuses.join(' / ')}.

Availability: damaged taxi \`${report.availability.damagedTaxiId}\` is never assigned
(\`assignedIsDamaged\` ${report.availability.assignedIsDamaged}, excluded from available
${report.availability.availableExcludesDamaged}); with every taxi damaged the step reports
\`${report.availability.allDamagedBlocker}\` and ${report.availability.allDamagedAssignments}
assignments.

## Scenario reset

| Field | Value |
| --- | --- |
| Tick | ${report.reset.tick} |
| Closed rides | ${report.reset.closedRides} (${report.reset.closedReasons.join(', ')}) |
| Released remaining claims | ${report.reset.releasedAssignments} |
| Cleared health marks | ${report.reset.clearedHealth} |
| Discarded rides | ${report.reset.discardedRides} |
| Active rides / assignments | ${report.reset.activeRides} / ${report.reset.assignments} |
| Pending requests / estimates | ${report.reset.pending} / ${report.reset.estimates} |
| Health AVAILABLE / dispatcher assigned | ${report.reset.healthAvailable} / ${report.reset.assigned} |
| Consistent | ${report.reset.consistent} |
| Stale ride ids / estimates | ${report.reset.staleRideIds} / ${report.reset.staleEstimates} |
| Second reset: rides / releases / health marks | ${report.reset.secondReset.closedRides} / ${report.reset.secondReset.releasedAssignments} / ${report.reset.secondReset.clearedHealth} |

Policies: preserved profile \`${report.policy.preservedProfile}\`, preserved facts
${report.policy.preservedFacts}, preserved reset profiles ${report.policy.preservedResetProfiles};
after RESET profile \`${report.policy.resetProfile}\`, facts ${report.policy.resetFacts}, reset
profiles ${report.policy.resetResetProfiles}. Health is AVAILABLE for every taxi after either policy.

Vanished taxi: closed rides ${report.vanished.closedRides}, discarded
${report.vanished.discardedRides}, reason \`${report.vanished.closedReason}\`, assignments
${report.vanished.assignments}, active rides ${report.vanished.activeRides}, remaining taxis
${report.vanished.taxis}, consistent ${report.vanished.consistent}.

Next scenario after reset: request \`${report.nextScenario.requestId}\` still reuses its stable id
(${report.nextScenario.sameRequestId}), assignment \`${report.nextScenario.assignmentId}\`, ride
\`${report.nextScenario.rideId}\` in \`${report.nextScenario.state}\`, ETA
\`${report.nextScenario.etaStatus}\`. Reusing a pre-reset fact id is accepted
(${report.nextScenario.reusedFactAccepted}) and the new ride closes with
\`${report.nextScenario.reusedRideReason}\`.

## Simulation

| Metric | Value |
| --- | ---: |
| Requests / assignments / begun | ${report.simulation.requests} / ${report.simulation.assigned} / ${report.simulation.begun} |
| Completed / failed health / failed timeout / cancelled | ${report.simulation.completed} / ${report.simulation.failedHealth} / ${report.simulation.failedTimeout} / ${report.simulation.cancelled} |
| Active before reset / closed by reset | ${report.simulation.activeBeforeReset} / ${report.simulation.closedByReset} |
| ETA samples | ${report.simulation.etaSamples} |

## Disposal

| Metric | Value |
| --- | ---: |
| Disposed | ${report.disposal.disposed} |
| Health taxis / facts | ${report.disposal.healthTaxis} / ${report.disposal.healthFacts} |
| Estimates / assignments / pending | ${report.disposal.estimates} / ${report.disposal.assignments} / ${report.disposal.pending} |
| Active rides / registry vehicles | ${report.disposal.activeRides} / ${report.disposal.vehicles} |

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'fleet', 'fleet-health-report.ts')).href
  ),
  report = reportModule.runFleetHealthReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, closed ${report.reset.closedRides}, presets ${report.fixture.presets.join('/')}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`Fleet health report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`Fleet health report is current: ${output}`);
} else {
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
