import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  defaultOutput = join(root, 'Docs', 'Evidence', '059-ride-demand', 'report.json'),
  reportMarkdown = join(root, 'Docs', 'Evidence', '059-ride-demand', 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function markdown(report) {
  const checks = report.checks
      .map(
        (entry) =>
          `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
      )
      .join('\n'),
    schedule = report.schedule
      .map(
        (entry) =>
          `| ${entry.spawnTick} | ${entry.windowId} | ${entry.demandLevel} | ${entry.originZoneId} | ${entry.destinationZoneId} | ${entry.validation} | ${entry.requestId} |`,
      )
      .join('\n'),
    plan = report.plan,
    generated = report.generated,
    determinism = report.determinism,
    invalid = report.invalid,
    queue = report.queue,
    disposal = report.disposal;
  return `# 059 ride demand report

Machine-readable transcript: [report.json](report.json). Generated by
\`npm run ride:demand\`; the transcript contains no wall-clock value and is deterministic.

Version: \`${report.version}\`; scenario \`${plan.scenarioId}\` on map \`${plan.mapId}\`.

## Schedule

| Metric | Value |
| --- | ---: |
| Seed | ${plan.seed} |
| Windows | ${plan.windows} |
| Requests | ${plan.requests} |
| LOW / NORMAL / HIGH | ${plan.levels.LOW} / ${plan.levels.NORMAL} / ${plan.levels.HIGH} |
| First spawn tick | ${plan.firstSpawnTick} |
| Last spawn tick | ${plan.lastSpawnTick} |

| Tick | Window | Level | Origin | Destination | Validation | Request |
| ---: | --- | --- | --- | --- | --- | --- |
${schedule}

## Generation and validation

| Metric | Value |
| --- | ---: |
| Unique ids | ${generated.uniqueIds} |
| Valid requests | ${generated.valid} |
| Invalid requests | ${generated.invalid} |
| Planner searches | ${generated.routeSearches} |
| Pending after horizon | ${generated.pendingAfterHorizon} |
| Admitted after horizon | ${generated.admittedAfterHorizon} |
| Invalid destination | ${invalid.accessMismatch} |
| Unknown destination | ${invalid.unknownDestination} |
| Same zone | ${invalid.sameZone} |
| Blocked route | ${invalid.blockedRoute} / ${invalid.blockedRouteStatus} |

## Determinism and bounds

| Check | Value |
| --- | --- |
| Same seed | ${determinism.sameSeed} |
| Different seed | ${determinism.differentSeed} |
| Window order independent | ${determinism.windowOrderIndependent} |
| Advance granularity independent | ${determinism.advanceGranularityIndependent} |
| Stale tick rejected | ${determinism.staleTickRejected} |
| Overflow policy | ${queue.policy} |
| Queue limit | ${queue.limit} |
| Admitted / overflow | ${queue.admitted} / ${queue.overflow} |
| Queue bounded | ${queue.bounded} |

## Disposal

| Metric | Value |
| --- | ---: |
| Disposed | ${disposal.disposed} |
| Requests / pending | ${disposal.requests} / ${disposal.pending} |
| Planner searches | ${disposal.routeSearches} |
| Owned planner disposed | ${disposal.plannerDisposed} |
| External planner alive | ${disposal.externalPlannerAlive} |

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'fleet', 'ride-demand-report.ts')).href
  ),
  report = reportModule.runRideDemandReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, requests ${report.generated.requests}, overflow ${report.queue.overflow}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`Ride demand report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`Ride demand report is current: ${output}`);
} else {
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
