import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  defaultOutput = join(root, 'Docs', 'Evidence', '056-auto-scenarios', 'report.json'),
  reportMarkdown = join(root, 'Docs', 'Evidence', '056-auto-scenarios', 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}
function markdown(report) {
  const rows = report.scenarios
    .map(
      (scenario) =>
        `| ${scenario.id} | ${scenario.behavior} | ${scenario.ticks} | ${scenario.checks.length} | ${scenario.pass ? 'PASS' : 'FAIL'} |`,
    )
    .join('\n');
  const negatives = report.negativeCases
    .map(
      (entry) =>
        `| ${entry.id} | ${entry.behavior} | ${entry.stimulus} | ${entry.actual} | ${entry.pass ? 'PASS' : 'FAIL'} |`,
    )
    .join('\n');
  const mutations = report.mutationProbes
    .map((probe) => `| ${probe.name} | ${probe.pass ? 'PASS' : 'FAIL'} |`)
    .join('\n');
  return `# 056 autonomy scenario report

Machine-readable transcript: [report.json](report.json). Generated by
\`npm run scenarios:autonomy\`; the transcript contains no wall-clock value and is deterministic.

${report.oracleRule}

## Scenarios

| Scenario | Behaviour | Ticks | Checks | Result |
| --- | --- | ---: | ---: | --- |
${rows}

## Negative cases (fail closed)

| Guard | Behaviour | Stimulus | Actual | Result |
| --- | --- | --- | --- | --- |
${negatives}

## Mutation probes

| Probe | Result |
| --- | --- |
${mutations}

## Summary

- Scenarios: ${report.summary.scenariosPassed}/${report.summary.scenarios}
- Negative cases: ${report.summary.negativeCasesPassed}/${report.summary.negativeCases}
- Mutation probes: ${report.summary.mutationProbesPassed}/${report.summary.mutationProbes}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const suite = await import(
    pathToFileURL(join(root, 'tests', 'autonomy', 'auto-scenarios.ts')).href
  ),
  report = await suite.runAutoScenarioSuite(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const scenario of report.scenarios)
  console.log(
    `${scenario.pass ? 'PASS' : 'FAIL'} ${scenario.id} (${scenario.behavior}, ${scenario.checks.length} checks)`,
  );
for (const entry of report.negativeCases)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} NEGATIVE ${entry.id} -> ${entry.actual}`);
for (const probe of report.mutationProbes)
  console.log(`${probe.pass ? 'PASS' : 'FAIL'} MUTATION ${probe.name}`);
console.log(
  `SUMMARY scenarios ${report.summary.scenariosPassed}/${report.summary.scenarios}, negative ${report.summary.negativeCasesPassed}/${report.summary.negativeCases}, mutations ${report.summary.mutationProbesPassed}/${report.summary.mutationProbes}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`Scenario report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`Scenario report is current: ${output}`);
} else {
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
