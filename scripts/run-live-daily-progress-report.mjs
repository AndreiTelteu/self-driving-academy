import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  directory = join(root, 'Docs', 'Evidence', '276-daily-xp-progress'),
  defaultOutput = join(directory, 'report.json'),
  reportMarkdown = join(directory, 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function markdown(report) {
  const checks = report.checks
    .map(
      (entry) =>
        `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
    )
    .join('\n');
  const missions = report.daily.missions
    .map(
      (mission) =>
        `| ${mission.slot} | \`${mission.familyId}\` | ${mission.objectiveKind} | ${mission.controlRequirement} | ${mission.target} | ${mission.allowsManual} | ${mission.learningKey ?? '—'} |`,
    )
    .join('\n');
  const exclusions = report.exclusions
    .map(
      (entry) => `| ${entry.cause} | ${entry.status} | ${entry.reason ?? '—'} | ${entry.xpAfter} |`,
    )
    .join('\n');
  return `# 276 daily missions, XP, level and player progress report

Machine-readable transcript: [report.json](report.json). Generated by
\`${report.generatedBy}\`; there is no wall-clock value and the transcript is deterministic.

Version: \`${report.version}\`.

Oracle rule: ${report.oracleRule}

## Daily set

Date: ${report.daily.date} (${report.daily.timeZone}); signature \`${report.daily.signature}\`;
manual objectives without learning: ${report.daily.manualWithoutLearning}.

| Slot | Family | Objective | Control | Target | Allows MANUAL | Learning key |
| ---: | --- | --- | --- | ---: | --- | --- |
${missions}

- same day stable: ${report.daily.sameDayStable}
- reload stable: ${report.daily.reloadStable}
- checkpoint: \`${report.daily.checkpointVersion}\`

## DST

| Field | Value |
| --- | --- |
| Spring date | ${report.dst.springDate} |
| Spring day length | ${report.dst.springLength} s |
| Fall date | ${report.dst.fallDate} |
| Fall day length | ${report.dst.fallLength} s |
| Spring offset | ${report.dst.springOffset} s |
| Fall offset | ${report.dst.fallOffset} s |
| Continuation gap | ${report.dst.continuationGapMs} ms |

## XP and level

| Field | Value |
| --- | --- |
| Initial | ${report.xp.initial} XP |
| After daily objectives | ${report.xp.afterDaily} XP |
| After mission settlement | ${report.xp.afterMission} XP |
| Level | ${report.xp.levelAfterDailyAndMission} |
| Fingerprint | \`${report.xp.fingerprint}\` |
| Debits | ${report.xp.debits} |
| Negative credits | ${report.xp.negativeCredits} |
| Balance is sum of entries | ${report.xp.balanceIsSumOfEntries} |
| 30 s active time | ${report.xp.active30sMicroXp} micro-XP |
| 70 s active time | ${report.xp.active70sMicroXp} micro-XP |
| Duplicate event credited | ${report.xp.duplicateEventCredited} |
| Duplicate daily credited | ${report.xp.duplicateDailyCredited} |
| Replay credited | ${report.xp.replayCredited} |

## Rollback and expiry

| Field | Value |
| --- | --- |
| Rollback date | ${report.rollback.date} |
| Rollback phase | ${report.rollback.phase} |
| XP before / after | ${report.rollback.xpBefore} / ${report.rollback.xpAfter} |
| Rewards retained | ${report.rollback.rewards} |
| Last millisecond phase | ${report.expiry.lastMillisecondPhase} |
| Boundary | ${report.expiry.boundaryStatus} / ${report.expiry.boundaryReason} |
| Expired phase | ${report.expiry.expiredPhase} |
| Expired objective reason | ${report.expiry.expiredObjectiveReason} |
| XP at expiry | ${report.expiry.xpAtExpiry} |

## Exclusions

| Cause | Status | Reason | XP after |
| --- | --- | --- | ---: |
${exclusions}

## Negative KPI and failed mission

| Field | Value |
| --- | --- |
| KPI fingerprint before / after | \`${report.negative.kpiFingerprintBefore}\` / \`${report.negative.kpiFingerprintAfter}\` |
| Failed mission fingerprint | \`${report.negative.failedMissionFingerprint}\` |
| Replay credited | ${report.negative.replayCredited} |
| Profile writes | ${report.negative.profileWrites} |

## Panel projection

| Field | Value |
| --- | --- |
| XP | ${report.panel.xpLabel} |
| Level | ${report.panel.levelLabel} |
| History rows | ${report.panel.history} |
| Daily completed | ${report.panel.dailyCompleted} |
| Window | ${report.panel.windowLabel} |
| Reset | ${report.panel.resetLabel} |
| Expiry reason | ${report.panel.expiryReason ?? '—'} |
| Forbidden fragments | ${report.panel.forbiddenFragments} |

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

Summary: ${report.summary.passed}/${report.summary.checks} checks passed; ${report.summary.pass ? 'PASS' : 'FAIL'}.

Limits: the report is deterministic and headless; it does not measure FPS/GPU, does not certify a
real browser session and does not replace the 287 playtest.
`;
}

const outputPath = argument('--out') ?? defaultOutput;
const modulePath = join(root, 'tests', 'missions', 'live-daily-progress-report.ts');
const { runLiveDailyProgressReport } = await import(pathToFileURL(modulePath).href);
const report = runLiveDailyProgressReport();
const json = `${JSON.stringify(report, null, 2)}\n`;

if (process.argv.includes('--check')) {
  let current;
  try {
    current = await readFile(outputPath, 'utf8');
  } catch {
    current = null;
  }
  if (current !== json) {
    console.error(`Daily/XP report is stale: ${outputPath}`);
    console.error(`Run: npm run progress:daily`);
    process.exit(1);
  }
  console.log(`Daily/XP report is current: ${outputPath}`);
  process.exit(0);
}

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, json);
await writeFile(reportMarkdown, markdown(report));
console.log(`Wrote ${outputPath}`);
console.log(`Wrote ${reportMarkdown}`);
if (!report.summary.pass) {
  console.error(`${report.summary.checks - report.summary.passed} checks failed`);
  process.exit(1);
}
