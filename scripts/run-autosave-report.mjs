function markdownCosts(cost) {
  const line = (label, stats) => `| ${label} | ${stats.min} | ${stats.median} | ${stats.max} |`;
  return `# 131 real autosave cost

Machine-readable values: [cost.json](cost.json). This is the only wall-clock measurement of PBI 131;
it is **not** part of the deterministic transcript. It was produced by \`--cost\` on the machine that
ran it and it is a local sample set, not a p95 and not a hardware certification.

Contract: ${cost.contract}

- Samples: ${cost.sampleCount}
- Vehicles: ${cost.vehicles}
- Checkpoint body bytes: ${cost.snapshotBytes}
- Clock: ${cost.clock}
- Measured at: ${cost.measuredAt}
- Authoritative tick budget: ${cost.tickBudgetDesktopMs} ms desktop / ${cost.tickBudgetLaptopMs} ms laptop (single sample, not a percentile)

| Phase | Min (ms) | Median (ms) | Max (ms) |
| --- | --- | --- | --- |
${[
  line('capture (in the tick)', cost.captureMs),
  line('encode', cost.encodeMs),
  line('copy', cost.copyMs),
  line('transfer', cost.transferMs),
  line('progress (inside commit)', cost.progressMs),
  line('checkpoint (inside commit)', cost.checkpointMs),
  line('commit', cost.commitMs),
  line('total', cost.totalMs),
].join('\n')}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'persistence', 'autosave-report.ts')).href
  ),
  report = await reportModule.runAutosaveReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`Autosave report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`Autosave report is current: ${output}`);
} else {
  await mkdir(directory, { recursive: true });
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}

if (process.argv.includes('--cost')) {
  const samples = Number(argument('--samples') ?? '20');
  const cost = await reportModule.measureAutosaveCosts(
    Number.isSafeInteger(samples) && samples > 0 ? samples : 20,
  );
  await mkdir(directory, { recursive: true });
  await writeFile(costOutput, `${JSON.stringify(cost, null, 2)}\n`);
  await writeFile(costMarkdown, markdownCosts(cost));
  console.log(
    `COST capture ${cost.captureMs.min}/${cost.captureMs.median}/${cost.captureMs.max} ms, encode ${cost.encodeMs.min}/${cost.encodeMs.median}/${cost.encodeMs.max} ms, copy ${cost.copyMs.min}/${cost.copyMs.median}/${cost.copyMs.max} ms, transfer ${cost.transferMs.min}/${cost.transferMs.median}/${cost.transferMs.max} ms, progress ${cost.progressMs.min}/${cost.progressMs.median}/${cost.progressMs.max} ms, checkpoint ${cost.checkpointMs.min}/${cost.checkpointMs.median}/${cost.checkpointMs.max} ms, commit ${cost.commitMs.min}/${cost.commitMs.median}/${cost.commitMs.max} ms, total ${cost.totalMs.min}/${cost.totalMs.median}/${cost.totalMs.max} ms over ${cost.sampleCount} samples`,
  );
  console.log(`Wrote ${costOutput}`);
  console.log(`Wrote ${costMarkdown}`);
}
