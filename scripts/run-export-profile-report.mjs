import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  directory = join(root, 'Docs', 'Evidence', '133-export-profile'),
  defaultOutput = join(directory, 'report.json'),
  sampleOutput = join(directory, 'sample-export.json'),
  reportMarkdown = join(directory, 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function rows(entries) {
  return entries.map(([label, entry]) => `| ${label} | ${value(entry)} |`).join('\n');
}

function markdown(report) {
  const checks = report.checks
    .map(
      (entry) =>
        `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
    )
    .join('\n');
  return `# 133 Profile export report

Machine-readable transcript: [report.json](report.json). Generated by
\`${report.generatedBy}\`; the transcript has no wall-clock value and is deterministic.

Version: \`${report.version}\`. Contract: \`${report.contract}\`.

Oracle rule: ${report.oracleRule}

## Format

| Field | Value |
| --- | --- |
${rows([
  ['Format', report.format.format],
  ['Format version', report.format.formatVersion],
  ['Schema version', report.format.schemaVersion],
  ['Units', report.format.units],
  ['Checksum algorithm', report.format.checksumAlgorithm],
  ['Canonicalization', report.format.canonicalization],
  ['Canonical document bytes', report.format.documentBytes],
  ['Checksum', report.format.checksum],
])}

## Profile

| Field | Value |
| --- | --- |
${rows([
  ['Profile id', report.profile.profileId],
  ['Engine version', report.profile.engineVersion],
  ['Versions', report.profile.versions],
  ['Active version', report.profile.activeVersionId],
  ['Provenance', report.profile.source],
  ['Effective parameters', report.profile.parameters],
  ['Reserved (R) parameters', report.profile.reservedParameters],
  ['Activation sequence', report.profile.activationSequence],
])}

## Aggregates

| Field | Value |
| --- | --- |
${rows([
  ['Base versions', report.aggregates.counts.baseVersions],
  ['Derived versions', report.aggregates.counts.derivedVersions],
  ['Manual tuning versions', report.aggregates.counts.manualTuningVersions],
  ['Learning versions', report.aggregates.counts.learningVersions],
  ['Source segments', report.aggregates.counts.sourceSegments],
  ['Source interventions', report.aggregates.counts.sourceInterventions],
  ['Indicator rows', report.aggregates.indicators],
  ['Evidence rows', report.aggregates.evidence],
  ['Referenced segments', report.aggregates.referencedSegments],
])}

## Raw telemetry

| Field | Value |
| --- | --- |
${rows([
  ['Included by default', report.telemetry.includedByDefault],
  ['Raw events by default', report.telemetry.rawEventCountByDefault],
  ['Raw event limit', report.telemetry.rawEventLimit],
  ['Raw events dropped by default', report.telemetry.omittedByDefault],
  ['Included on request', report.telemetry.includedOnRequest],
  ['Raw events on request', report.telemetry.rawEventCountOnRequest],
  ['Above the cap', report.telemetry.limitExceededCode],
])}

## Roundtrip

| Field | Value |
| --- | --- |
${rows([
  ['Read status', report.roundtrip.readStatus],
  ['Checksum verified', report.roundtrip.checksumVerified],
  ['Parameters', report.roundtrip.parameters],
  ['Reserved keys', report.roundtrip.reservedParameters],
  ['Versions', report.roundtrip.versions],
  ['Provenance', report.roundtrip.sources],
])}

## Refusals

| Field | Value |
| --- | --- |
${rows([
  ['Modified document', report.refusals.modifiedDocument],
  ['Reserved key with a value', report.refusals.reservedKeyWithValue],
  ['Missing reserved key', report.refusals.missingReservedKey],
  ['Usable key in the reserved map', report.refusals.usableKeyInReservedMap],
  ['Duplicate key', report.refusals.duplicateKey],
  ['Trailing content', report.refusals.trailingContent],
  ['Non JSON number', report.refusals.nonJsonNumber],
  ['Unsupported format version', report.refusals.unsupportedFormatVersion],
])}

## Repository export

| Field | Value |
| --- | --- |
${rows([
  ['Status', report.repository.status],
  ['Versions', report.repository.versions],
  ['Active version', report.repository.activeVersionId],
  ['Activation sequence', report.repository.activationSequence],
  ['Raw telemetry included', report.repository.included],
])}

## Digest

| Field | Value |
| --- | --- |
${rows([
  ['Canonical bytes', report.digest.sample],
  ['Platform SHA-256', report.digest.platform],
  ['Own SHA-256', report.digest.own],
  ['Equal', report.digest.equal],
])}

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'persistence', 'export-profile-report.ts')).href
  ),
  report = await reportModule.runExportProfileReport(),
  sample = `${JSON.stringify(reportModule.buildExportProfileSample(), null, 2)}\n`,
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, contract ${report.contract}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`Export profile report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`Export profile report is current: ${output}`);
  const savedSample = await readFile(sampleOutput, 'utf8');
  if (savedSample !== sample) {
    console.error(`Export profile sample is stale: ${sampleOutput}`);
    process.exitCode = 1;
  } else console.log(`Export profile sample is current: ${sampleOutput}`);
} else {
  await writeFile(output, json);
  await writeFile(sampleOutput, sample);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${sampleOutput}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
