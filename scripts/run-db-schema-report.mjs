import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  directory = join(root, 'Docs', 'Evidence', '127-db-schema'),
  defaultOutput = join(directory, 'report.json'),
  reportMarkdown = join(directory, 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function rows(entries) {
  return entries.map(([label, entry]) => `| ${label} | ${value(entry)} |`).join('\n');
}

function markdown(report) {
  const checks = report.checks
      .map(
        (entry) =>
          `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
      )
      .join('\n'),
    steps = report.schema.steps
      .map(
        (step) =>
          `| ${step.version} | \`${step.id}\` | ${step.creates.map((name) => `\`${name}\``).join(', ') || '—'} | ${step.indexes.map((name) => `\`${name}\``).join(', ') || '—'} |`,
      )
      .join('\n'),
    stores = report.schema.stores
      .map(
        (store) =>
          `| \`${store.name}\` | \`${store.keyPath}\` | ${store.indexes.map((entry) => `\`${entry.name}\` → \`${entry.keyPath}\`${entry.unique ? ' (unique)' : ''}`).join(', ') || '—'} |`,
      )
      .join('\n');
  return `# 127 IndexedDB schema and local repository report

Machine-readable transcript: [report.json](report.json). Generated by
\`${report.generatedBy}\`; the transcript has no wall-clock value and is deterministic.

Version: \`${report.version}\`.

Oracle rule: ${report.oracleRule}

Production database name: \`${report.productionDatabase}\` (this transcript uses the sandbox name \`${report.sandboxDatabase}\`).

## Declared schema

Current version: ${report.schema.currentVersion}.

| Version | Step | Creates | Indexes |
| --- | --- | --- | --- |
${steps}

| Store | Key path | Indexes |
| --- | --- | --- |
${stores}

## Fresh database

| Field | Value |
| --- | --- |
${rows([
  ['Status', report.freshDatabase.status],
  ['Version', report.freshDatabase.version],
  ['Previous version', report.freshDatabase.previousVersion],
  ['Applied migrations', report.freshDatabase.appliedMigrations],
  ['Role', report.freshDatabase.role],
  ['Stores', report.freshDatabase.stores],
  ['Format marker', report.freshDatabase.marker],
])}

## Upgrade 1 → 2

| Field | Value |
| --- | --- |
${rows([
  ['From / to', `${report.upgrade.fromVersion} → ${report.upgrade.toVersion}`],
  ['Applied migrations', report.upgrade.appliedMigrations],
  ['Rows before / after', `${report.upgrade.rowsBefore} / ${report.upgrade.rowsAfter}`],
  ['Added stores', report.upgrade.addedStores],
  ['Added indexes', report.upgrade.addedIndexes],
  ['Rows found through the new index', report.upgrade.indexHits],
])}

## Blocked upgrade

| Field | Value |
| --- | --- |
${rows([
  ['Repository state', report.blockedUpgrade.repositoryState],
  ['Reason', report.blockedUpgrade.reason],
  [
    'Requested / on disk',
    `${report.blockedUpgrade.requestedVersion} / ${report.blockedUpgrade.currentVersion}`,
  ],
  ['Open connections while blocked', report.blockedUpgrade.openConnectionsWhileBlocked],
  [
    'After the blocking tab closed',
    `${report.blockedUpgrade.afterCloseStatus} (v${report.blockedUpgrade.afterCloseVersion})`,
  ],
])}

## Version change

| Field | Value |
| --- | --- |
${rows([
  ['State', report.versionChange.state],
  ['Reason', report.versionChange.reason],
  ['Role', report.versionChange.role],
  ['Status before the change', report.versionChange.initialStatus],
  ['Open connections after release', report.versionChange.openConnectionsAfter],
  ['Write after release', report.versionChange.writeAfterRelease],
  ['Reopen status', report.versionChange.reopenedStatus],
])}

## Single writer

| Field | Value |
| --- | --- |
${rows([
  ['First tab role', report.writer.firstTabRole],
  ['Second tab role', report.writer.secondTabRole],
  ['Second tab reason', report.writer.secondTabReason],
  ['Queued role', report.writer.waitingRole],
  ['Role after transfer', report.writer.transferRole],
  ['Write before transfer', report.writer.writeDeniedBeforeTransfer],
  ['Write after transfer', report.writer.writeCommittedAfterTransfer],
  ['Previous writer after release', report.writer.previousWriterRole],
])}

## Failure states

| Field | Value |
| --- | --- |
${rows([
  ['Open failure status', report.openFailure.status],
  ['Open failure code', report.openFailure.code],
  ['Repository state', report.openFailure.repositoryState],
  ['Without Web Locks', report.unavailableLocks.role],
  ['Write without Web Locks', report.unavailableLocks.writeResult],
])}

## Transactions and guarded writes

| Field | Value |
| --- | --- |
${rows([
  ['Stores committed', report.transactions.committedStores],
  ['Segments after rollback', report.transactions.rolledBackSegments],
  ['Progress after rollback', report.transactions.rolledBackProgress],
  ['Activation without its version', report.transactions.orphanActivation],
  ['Activation rows after the orphan attempt', report.transactions.activationRowsAfterOrphan],
  ['Stale revision', report.transactions.staleRevision],
  ['Changed stored version', report.transactions.immutableProfile],
  ['Corrupted checksum', report.transactions.checksumMismatch],
  ['Identical re-put', report.transactions.idempotentProfile],
  ['Oversized body', report.transactions.oversizedBody],
  ['List budget', report.transactions.listLimit],
])}

## Bounds

| Field | Value |
| --- | --- |
${rows([
  ['Sample body bytes', report.bounds.bodyBytes],
  ['Body budget', report.bounds.maxBodyBytes],
  ['Record budget', report.bounds.maxRecordBytes],
  ['List budget', report.bounds.maxListEntries],
  ['Nesting budget', report.bounds.maxBodyDepth],
])}

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'persistence', 'db-schema-report.ts')).href
  ),
  report = await reportModule.runDbSchemaReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, schema v${report.schema.currentVersion}, stores ${report.schema.stores.length}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`DB schema report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`DB schema report is current: ${output}`);
} else {
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
