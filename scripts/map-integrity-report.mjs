import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import './register-typescript.mjs';

/**
 * PBI043 map-integrity gate for the authored neighbourhood.
 *
 * It runs the real PBI032/PBI042 document through the deterministic integrity audit, prints the
 * closed reason vocabulary, the machine-readable coverage matrix and every issue with its field
 * path, entity ID and position. Exit code 1 means at least one integrity error.
 *
 * Usage:
 *   node scripts/map-integrity-report.mjs [--json <file>] [--md <file>] [--map <map.json>]
 */
const root = dirname(dirname(fileURLToPath(import.meta.url)));
const world = pathToFileURL(join(root, 'src/world/index.ts')).href;
const { checkMapIntegrity, createNeighbourhoodMap, MAP_INTEGRITY_VERSION } = await import(world);

const args = process.argv.slice(2);
const option = (name) => {
  const index = args.indexOf(name);
  return index >= 0 ? args[index + 1] : null;
};

const mapPath = option('--map');
const input = mapPath
  ? JSON.parse(await readFile(resolve(mapPath), 'utf8'))
  : createNeighbourhoodMap();
const report = checkMapIntegrity(input, { maxIssues: 512 });

const positionText = (position) =>
  position ? `(${position.x},${position.y},${position.z})` : 'n/a';

const lines = [
  '# PBI043 map integrity report',
  '',
  `Generated by \`node scripts/map-integrity-report.mjs\` - validator \`${MAP_INTEGRITY_VERSION}\`.`,
  '',
  `- Map: \`${report.mapId ?? 'unknown'}\` - schemaVersion: ${report.schemaVersion ?? 'unknown'}`,
  `- Result: **${report.ok ? 'PASS' : 'FAIL'}** - issues: ${report.issueCount}${report.truncated ? ' (truncated)' : ''}`,
  `- Schema error: ${report.schemaError ? `\`${report.schemaError}\`` : 'none'}`,
  '',
  '## Entity inventory',
  '',
  '| Entity | Count |',
  '| --- | ---: |',
  ...Object.entries(report.coverage.entityCounts).map(([kind, count]) => `| ${kind} | ${count} |`),
  '',
  `References checked: ${report.coverage.references.checked}; unresolved: ${report.coverage.references.missing}.`,
  '',
  '## Checks',
  '',
  '| Check | Status | Examined | Issues | Note |',
  '| --- | --- | ---: | ---: | --- |',
  ...report.coverage.checks.map(
    (check) =>
      `| ${check.id} | ${check.status} | ${check.examined} | ${check.issues} | ${check.note ?? 'none'} |`,
  ),
  '',
  '## Scenario coverage',
  '',
  `Lane directions: FORWARD=${report.coverage.scenarios.laneDirections.FORWARD}, REVERSE=${report.coverage.scenarios.laneDirections.REVERSE}.`,
  `Lane access: TAXI=${report.coverage.scenarios.laneAccess.TAXI}, CIVIL=${report.coverage.scenarios.laneAccess.CIVIL}.`,
  `Road classes: ARTERIAL=${report.coverage.scenarios.roadClasses.ARTERIAL}, RESIDENTIAL=${report.coverage.scenarios.roadClasses.RESIDENTIAL}.`,
  `Intersections: SIGNALIZED=${report.coverage.scenarios.intersectionTypes.SIGNALIZED}, STOP_CONTROLLED=${report.coverage.scenarios.intersectionTypes.STOP_CONTROLLED}, UNCONTROLLED=${report.coverage.scenarios.intersectionTypes.UNCONTROLLED}.`,
  `Stop lines: STOP=${report.coverage.scenarios.stopLineKinds.STOP}, SIGNAL=${report.coverage.scenarios.stopLineKinds.SIGNAL}, CROSSWALK=${report.coverage.scenarios.stopLineKinds.CROSSWALK}.`,
  `Service zones: PICKUP=${report.coverage.scenarios.serviceZoneKinds.PICKUP}, DROPOFF=${report.coverage.scenarios.serviceZoneKinds.DROPOFF}, BOTH=${report.coverage.scenarios.serviceZoneKinds.BOTH}; access TAXI=${report.coverage.scenarios.serviceZoneAccess.TAXI}, CIVIL=${report.coverage.scenarios.serviceZoneAccess.CIVIL}, TAXI+CIVIL=${report.coverage.scenarios.serviceZoneAccess['TAXI+CIVIL']}.`,
  `Pickup/dropoff zones routable: ${report.coverage.scenarios.routablePickupDropoffZones}/${report.coverage.scenarios.pickupDropoffZones}; recovery points: ${report.coverage.scenarios.recoveryPoints}.`,
  '',
  '## Connectivity',
  '',
  `Strongly connected components: ${report.coverage.connectivity.stronglyConnectedComponents}; weakly connected: ${report.coverage.connectivity.weaklyConnectedComponents}; largest component: ${report.coverage.connectivity.largestComponentLanes} lanes.`,
  `Disconnected lanes: ${report.coverage.connectivity.disconnectedLaneIds.length === 0 ? 'none' : report.coverage.connectivity.disconnectedLaneIds.join(', ')}.`,
  '',
  '| Access | Lanes | Zones | Reachable lane/zone pairs | Unreachable |',
  '| --- | ---: | ---: | ---: | ---: |',
  ...Object.entries(report.coverage.connectivity.byAccess).map(
    ([access, value]) =>
      `| ${access} | ${value.lanes} | ${value.zones} | ${value.reachableLaneZonePairs} | ${value.unreachableLaneZonePairs} |`,
  ),
  '',
  '## Route matrix',
  '',
  '| Access | Requested | READY | Failed |',
  '| --- | ---: | ---: | ---: |',
  ...Object.entries(report.coverage.routing.byAccess).map(
    ([access, value]) => `| ${access} | ${value.requested} | ${value.ready} | ${value.failed} |`,
  ),
  '',
  `Total: ${report.coverage.routing.ready}/${report.coverage.routing.requested} READY, ${report.coverage.routing.failed} failed.`,
  '',
  '## Issues',
  '',
];
if (report.issues.length === 0) lines.push('None.');
else {
  lines.push(
    '| Reason | Path | Entity | Related | Position (m) | Message |',
    '| --- | --- | --- | --- | --- | --- |',
    ...report.issues.map(
      (issue) =>
        `| ${issue.reason} | \`${issue.path}\` | ${issue.entityId ?? 'n/a'} | ${issue.relatedId ?? 'n/a'} | ${positionText(issue.positionM)} | ${issue.message.replaceAll('|', '\\|')} |`,
    ),
  );
  if (report.truncated)
    lines.push(
      '',
      `> Issue list truncated at ${report.issues.length}; ${report.issueCount} total.`,
    );
}
lines.push('');

const jsonPath = option('--json');
if (jsonPath) await writeFile(jsonPath, `${JSON.stringify(report, null, 2)}\n`);
const mdPath = option('--md');
if (mdPath) await writeFile(mdPath, `${lines.join('\n')}`);
else process.stdout.write(`${lines.join('\n')}\n`);

if (!report.ok) {
  process.stderr.write(
    `map integrity FAILED: ${report.issueCount} issue(s): ${Object.entries(report.errorsByReason)
      .map(([reason, count]) => `${reason}=${count}`)
      .join(', ')}\n`,
  );
  process.exitCode = 1;
}
