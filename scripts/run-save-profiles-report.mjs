import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  directory = join(root, 'Docs', 'Evidence', '128-save-profiles'),
  defaultOutput = join(directory, 'report.json'),
  reportMarkdown = join(directory, 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function rows(entries) {
  return entries.map(([label, entry]) => `| ${label} | ${value(entry)} |`).join('\n');
}

function markdown(report) {
  const checks = report.checks
    .map(
      (entry) =>
        `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
    )
    .join('\n');
  return `# 128 Atomic profile version and activation report

Machine-readable transcript: [report.json](report.json). Generated by
\`${report.generatedBy}\`; the transcript has no wall-clock value and is deterministic.

Version: \`${report.version}\`. Contract: \`${report.contract}\`.

Oracle rule: ${report.oracleRule}

## Atomic commit

| Field | Value |
| --- | --- |
${rows([
  ['Status', report.atomicCommit.status],
  ['Version created', report.atomicCommit.versionCreated],
  ['Activation changed', report.atomicCommit.activationChanged],
  ['Provenance classification', report.atomicCommit.source],
  ['Measured bytes', report.atomicCommit.bytes],
  ['Profile rows', report.atomicCommit.profileRows],
  ['Activation rows', report.atomicCommit.activationRows],
])}

## Crash before the commit

| Field | Value |
| --- | --- |
${rows([
  ['Status', report.crashBeforeCommit.status],
  ['Rejection', report.crashBeforeCommit.rejection],
  ['Profile rows', report.crashBeforeCommit.profileRows],
  ['Activation rows', report.crashBeforeCommit.activationRows],
  ['Active version', report.crashBeforeCommit.activeVersionId],
  ['Active version loadable', report.crashBeforeCommit.activeVersionLoadable],
])}

## Crash after the commit

| Field | Value |
| --- | --- |
${rows([
  ['Status', report.crashAfterCommit.status],
  ['Profile rows', report.crashAfterCommit.profileRows],
  ['Activation rows', report.crashAfterCommit.activationRows],
  ['Active version', report.crashAfterCommit.activeVersionId],
  ['Active version loadable', report.crashAfterCommit.activeVersionLoadable],
])}

## Guards

| Field | Value |
| --- | --- |
${rows([
  ['Activation without its version', report.guards.orphanActivation],
  ['Rows written by the orphan attempt', report.guards.orphanRows],
  ['Derived version without its parent', report.guards.missingParent],
  ['Stored version replaced', report.guards.immutableVersion],
  ['Older activation sequence', report.guards.staleSequence],
  ['Stored activation sequence', report.guards.storedSequence],
  ['Same sequence, other version', report.guards.sameSequenceOtherVersion],
  ['Page without the writer lock', report.guards.readOnlyPage],
])}

## History and provenance

| Field | Value |
| --- | --- |
${rows([
  ['Chain', report.history.chain],
  ['Stored versions', report.history.versions],
  ['Active version', report.history.activeVersionId],
  ['Activation sequence', report.history.activationSequence],
  ['Activated at', report.history.activatedAt],
  ['Provenance classification', report.history.source],
  ['History complete', report.history.complete],
  ['Missing versions', report.history.missingVersionIds],
  ['Intervention sources', report.history.interventionIds],
  ['Driving segment sources', report.history.segmentIds],
  ['Parent version', report.history.parentVersionId],
  ['Version created at', report.history.createdAt],
  ['Repeated commit created a version', report.history.idempotentVersionCreated],
  ['Repeated commit moved the pointer', report.history.idempotentActivationChanged],
])}

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'persistence', 'save-profiles-report.ts')).href
  ),
  report = await reportModule.runSaveProfilesReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, contract ${report.contract}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`Save profiles report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`Save profiles report is current: ${output}`);
} else {
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
