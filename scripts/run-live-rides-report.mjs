import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  directory = join(root, 'Docs', 'Evidence', '264-live-rides'),
  reportJson = join(directory, 'report.json'),
  reportMarkdown = join(directory, 'report.md'),
  costJson = join(directory, 'cost.json');

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function markdown(report) {
  const checks = report.checks
    .map(
      (entry) =>
        `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
    )
    .join('\n');
  const releaseRows = Object.entries(report.dispatch.releasesByCause)
    .map(([cause, count]) => `| ${cause} | ${count} |`)
    .join('\n');
  const stateRows = Object.entries(report.state.statesBeforeReset)
    .map(([state, count]) => `| ${state} | ${count} |`)
    .join('\n');
  const minCost = report.dispatch.minCost;
  return `# 264 live ride demand and dispatch report

Machine-readable transcript: [report.json](report.json). Generated by \`npm run ride:live\`; the
transcript contains no wall-clock value and is deterministic.

Version: \`${report.version}\`; live contract: \`${report.contract}\`. Fixture: ${report.fixture.taxis}
live taxis and ${report.fixture.civilians} civilians, seed ${report.fixture.seed}, map
\`${report.fixture.scenarioId}\`, namespace \`${report.fixture.namespace}\`, ${report.fixture.ticks}
ticks plus a scenario reset at ${report.fixture.resetTick}.

## Plan and real zones

| Metric | Value |
| --- | ---: |
| Windows | ${report.plan.valid + report.plan.invalid > 0 ? report.fixture.planWindows : 0} |
| Requests | ${report.fixture.requests} |
| Valid / invalid | ${report.plan.valid} / ${report.plan.invalid} |
| First / last spawn tick | ${report.plan.firstSpawnTick} / ${report.plan.lastSpawnTick} |
| Unique origins / destinations | ${report.plan.uniqueOrigins} / ${report.plan.uniqueDestinations} |
| Same seed identical | ${report.plan.sameSeed} |
| Different seed moves zones | ${report.plan.seedMovesZones} |
| All zones real and TAXI-accessible | ${report.plan.realZones} |

## Queue and dispatch

| Metric | Value |
| --- | ---: |
| Queue limit / peak / policy | ${report.queue.limit} / ${report.queue.peak} / ${report.queue.policy} |
| Main overflow | ${report.queue.overflow} |
| Overflow fixture limit / peak / overflow | ${report.queue.overflowFixture.limit} / ${report.queue.overflowFixture.peak} / ${report.queue.overflowFixture.overflow} |
| Overflow rejects only the second window | ${report.queue.overflowFixture.rejectedSecondWindow} |
| Assignments / releases | ${report.dispatch.assignments} / ${report.dispatch.releases} |
| Active unique requests / taxis | ${report.dispatch.uniqueRequests} / ${report.dispatch.uniqueTaxis} |
| Dispatch steps | ${report.dispatch.dispatchSteps} |
| Route searches (total) | ${report.dispatch.routeSearches} |
| Max searches per step / budget | ${report.dispatch.maxSearchesPerStep} / ${report.dispatch.routeSearchBudget} |
| Max assignments per step / cap | ${report.dispatch.maxAssignmentsPerStep} / ${report.dispatch.assignmentsPerDispatch} |
| Trip cost mismatches vs 041 | ${report.dispatch.tripCostMismatch} |
| Minimum pickup cost verified | ${minCost?.pass ?? false} (${minCost ? `${minCost.expectedTaxi} ${minCost.expectedCost.toFixed(3)} s → ${minCost.actualTaxi} ${minCost.actualCost.toFixed(3)} s` : 'not observed'}) |

## Releases

| Cause | Count |
| --- | ---: |
${releaseRows}

## Request states before reset

| State | Count |
| --- | ---: |
${stateRows}

Consumed without a visible trace: ${report.state.consumed}.

## Reset

| Metric | Value |
| --- | ---: |
| Released claims | ${report.reset.releasedAssignments} |
| Preserved stats | ${report.reset.preservedStats} |
| Active after reset | ${report.reset.activeAfterReset} |
| Assignments after reset | ${report.reset.assignmentsAfterReset} |
| Duplicate active request | ${report.reset.duplicateActive} |
| Assignment identity mismatches | ${report.reset.identityMismatches} |

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}

## Limits

This is a deterministic headless functional probe on the real 032/033/041/057/058/059/060
contracts, not a browser frame, hardware or FPS measurement. Pickup/dropoff physical lifecycle,
passengers and ETA remain PBI 265; the live assignments are 060 claims without a 061 ride.
`;
}

const wantsCheck = process.argv.includes('--check'),
  wantsMeasure = process.argv.includes('--measure'),
  reportModule = await import(
    pathToFileURL(join(root, 'tests', 'fleet', 'live-rides-report.ts')).href
  ),
  report = reportModule.runLiveRidesReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  md = markdown(report);

if (wantsCheck) {
  const savedJson = await readFile(reportJson, 'utf8').catch(() => null),
    savedMarkdown = await readFile(reportMarkdown, 'utf8').catch(() => null);
  if (savedJson !== json) console.error(`Live rides report is stale: ${reportJson}`);
  if (savedMarkdown !== md) console.error(`Live rides report markdown is stale: ${reportMarkdown}`);
  if (savedJson !== json || savedMarkdown !== md) process.exitCode = 1;
  else console.log(`Live rides report is current: ${reportJson}`);
  if (!report.summary.pass) process.exitCode = 1;
} else {
  await mkdir(directory, { recursive: true });
  await writeFile(reportJson, json);
  await writeFile(reportMarkdown, md);
  console.log(`Wrote ${reportJson}`);
  console.log(`Wrote ${reportMarkdown}`);
  for (const entry of report.checks) {
    if (!entry.pass) console.error(`FAIL ${entry.name}: ${value(entry.actual)}`);
  }
  console.log(
    `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
  );
  if (!report.summary.pass) process.exitCode = 1;
}

if (wantsMeasure) {
  const cost = reportModule.measureLiveRidesCost();
  await mkdir(directory, { recursive: true });
  await writeFile(costJson, `${JSON.stringify(cost, null, 2)}\n`);
  console.log(`Wrote ${costJson}`);
  console.log(
    `COST live.step p95 ${cost.liveStep.p95Ms.toFixed(3)} ms, dispatch p95 ${cost.dispatchStep.p95Ms.toFixed(3)} ms, amortized ${cost.amortizedPerTickMs.toFixed(3)} ms of ${cost.protocol.budgetMs} ms budget, searches max ${cost.routeSearches.maxPerStep}/${cost.routeSearches.budget}, ${cost.pass ? 'PASS' : 'FAIL'}`,
  );
  if (!cost.pass) process.exitCode = 1;
}
