import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
  defaultOutput = join(root, 'Docs', 'Evidence', '060-dispatcher', 'report.json'),
  reportMarkdown = join(root, 'Docs', 'Evidence', '060-dispatcher', 'report.md');

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function value(input) {
  return typeof input === 'string' ? input : JSON.stringify(input);
}

function markdown(report) {
  const checks = report.checks
      .map(
        (entry) =>
          `| ${entry.name} | ${value(entry.expected)} | ${value(entry.actual)} | ${entry.pass ? 'PASS' : 'FAIL'} | ${entry.detail} |`,
      )
      .join('\n'),
    releases = report.releaseReasons
      .map(
        (entry) =>
          `| ${entry.reason} | ${entry.statusAfter} | ${entry.availableAfter ? 'yes' : 'no'} |`,
      )
      .join('\n'),
    simulation = report.simulation,
    costs = report.costs,
    fleet = report.fleet,
    demand = report.demand;
  return `# 060 dispatcher report

Machine-readable transcript: [report.json](report.json). Generated by
\`npm run fleet:dispatch\`; the transcript contains no wall-clock value and is deterministic.

Version: \`${report.version}\`; ${fleet.taxis} taxis and ${fleet.civilians} civilians from the real 057
registry, ${demand.requests} pending requests from the real 059 schedule on the real 032 map.

## Fleet and demand

| Metric | Value |
| --- | ---: |
| Taxis / civilians | ${fleet.taxis} / ${fleet.civilians} |
| Serviceable / blocked / damaged / offline | ${fleet.serviceable} / ${fleet.blocked} / ${fleet.damaged} / ${fleet.offline} |
| Windows / requests | ${demand.windows} / ${demand.requests} |
| First / last spawn tick | ${demand.firstSpawnTick} / ${demand.lastSpawnTick} |

## Simulation

| Metric | Value |
| --- | ---: |
| Ticks | ${simulation.ticks} |
| Assignments | ${simulation.assignments} |
| Unique requests / taxis | ${simulation.uniqueRequests} / ${simulation.uniqueTaxis} |
| Releases | ${simulation.releases} |
| Real 041 searches | ${simulation.plannerSearches} |
| Max concurrent claims | ${simulation.maxConcurrent} |
| First / last assignment tick | ${simulation.firstAssignmentTick} / ${simulation.lastAssignmentTick} |
| Duplicate taxi claims | ${simulation.duplicateTaxis} |
| Blocked / damaged / offline taxi assigned | ${simulation.blockedTaxiAssigned} / ${simulation.damagedTaxiAssigned} / ${simulation.offlineTaxiAssigned} |
| FIFO matches 059 order | ${simulation.fifoMatchesDemandOrder} |

## Costs (real 041 at assignment time)

| Metric | Value |
| --- | ---: |
| Recomputed matches / checked | ${costs.recomputedMatches} / ${costs.recomputedChecked} |
| Pickup seconds min / max | ${costs.minPickupSeconds} / ${costs.maxPickupSeconds} |
| Total pickup / trip seconds | ${costs.totalPickupSeconds} / ${costs.totalTripSeconds} |
| Equal-cost tie break | ${report.tieBreak.equalCost} → ${report.tieBreak.chosenTaxiId} |
| Reversed position insertion | ${report.tieBreak.sameResultWithReversedPositions} |

## Rejection and bound probes

| Probe | Result |
| --- | --- |
| Stale 059 snapshot (${report.staleRoute.validationBefore} → ${report.staleRoute.validationAfter}) | ${report.staleRoute.assigned} assigned, ${report.staleRoute.reason} / ${report.staleRoute.routeStatus}, ${report.staleRoute.pendingAfter} pending |
| Pickup unreachable | ${report.pickupUnreachable.assigned} assigned, ${report.pickupUnreachable.reason}, ${report.pickupUnreachable.pendingAfter} pending, ${report.pickupUnreachable.plannerSearches} searches |
| No taxi | ${report.noTaxi.assigned} assigned, ${report.noTaxi.reason}, ${report.noTaxi.pendingAfter} pending, ${report.noTaxi.plannerSearches} searches |
| No position | ${report.noPosition.assigned} assigned, ${report.noPosition.reason}, ${report.noPosition.pendingAfter} pending |
| Search budget ${report.bounds.configuredSearches} | ${report.bounds.assignmentsInStep} assigned, ${report.bounds.plannerSearches} searches, ${report.bounds.blockedReason}, ${report.bounds.pendingAfter} pending |

## Release reasons

| Reason | Next status | Available |
| --- | --- | --- |
${releases}

## Disposal

| Metric | Value |
| --- | ---: |
| Disposed | ${report.disposal.disposed} |
| Assignments / assigned / searches | ${report.disposal.assignments} / ${report.disposal.assigned} / ${report.disposal.routeSearches} |
| Registry taxis / demand requests | ${report.disposal.registryTaxis} / ${report.disposal.demandRequests} |
| Injected planner alive | ${report.disposal.plannerAlive} |

## Checks

| Check | Expected | Actual | Result | Detail |
| --- | --- | --- | --- | --- |
${checks}

## Summary

- Checks: ${report.summary.passed}/${report.summary.checks}
- Overall: ${report.summary.pass ? 'PASS' : 'FAIL'}
`;
}

const reportModule = await import(
    pathToFileURL(join(root, 'tests', 'fleet', 'dispatcher-report.ts')).href
  ),
  report = reportModule.runDispatcherReport(),
  json = `${JSON.stringify(report, null, 2)}\n`,
  output = argument('--output') ?? defaultOutput;

for (const entry of report.checks)
  console.log(`${entry.pass ? 'PASS' : 'FAIL'} CHECK ${entry.name}`);
console.log(
  `SUMMARY checks ${report.summary.passed}/${report.summary.checks}, assignments ${report.simulation.assignments}, searches ${report.simulation.plannerSearches}, overall ${report.summary.pass ? 'PASS' : 'FAIL'}`,
);

if (process.argv.includes('--check')) {
  const saved = await readFile(output, 'utf8');
  if (saved !== json) {
    console.error(`Dispatcher report is stale: ${output}`);
    process.exitCode = 1;
  } else console.log(`Dispatcher report is current: ${output}`);
} else {
  await writeFile(output, json);
  await writeFile(reportMarkdown, markdown(report));
  console.log(`Wrote ${output}`);
  console.log(`Wrote ${reportMarkdown}`);
  if (!report.summary.pass) process.exitCode = 1;
}
