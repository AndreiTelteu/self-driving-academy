async function loadPlaywright() {
  const explicit = process.env.PLAYWRIGHT_MODULE;
  try {
    if (explicit) {
      const resolved = resolve(explicit);
      const entry = /\.(?:c|m)?js$/.test(resolved) ? resolved : join(resolved, 'index.js');
      return await import(pathToFileURL(entry).href);
    }
    return await import('playwright');
  } catch {
    return null;
  }
}

function mimeType(file) {
  return (
    {
      '.html': 'text/html; charset=utf-8',
      '.js': 'text/javascript; charset=utf-8',
      '.css': 'text/css; charset=utf-8',
      '.json': 'application/json',
      '.png': 'image/png',
      '.svg': 'image/svg+xml',
      '.wasm': 'application/wasm',
      '.glb': 'model/gltf-binary',
      '.ktx2': 'image/ktx2',
    }[extname(file)] ?? 'application/octet-stream'
  );
}

async function serve(directoryPath) {
  const server = createServer(async (request, response) => {
    try {
      if (request.method !== 'GET') {
        response.writeHead(405).end();
        return;
      }
      const url = new URL(request.url ?? '/', 'http://127.0.0.1');
      const pathname = decodeURIComponent(url.pathname);
      if (pathname === '/favicon.ico') {
        response.writeHead(204).end();
        return;
      }
      const file = resolve(directoryPath, '.' + (pathname === '/' ? '/index.html' : pathname));
      if (!file.startsWith(directoryPath + sep) || !(await stat(file)).isFile()) {
        response.writeHead(404).end();
        return;
      }
      const data = await readFile(file);
      response.writeHead(200, {
        'Content-Type': mimeType(file),
        'Cache-Control': 'no-store',
        'Content-Length': data.length,
      });
      response.end(data);
    } catch {
      response.writeHead(404);
      response.end();
    }
  });
  await new Promise((ready) => server.listen(0, '127.0.0.1', ready));
  const address = server.address();
  const origin = `http://127.0.0.1:${
    typeof address === 'object' && address !== null ? address.port : 0
  }`;
  return { server, origin };
}

function markdown(result) {
  if (result.status === 'NOT_RUN') {
    return `# 285 — browser probe

Generated by \`npm run destructibles:live:probe\` on ${result.generatedAt}.

**NOT_RUN** — ${result.reason}

No PASS is simulated. The deterministic 285 report and the real 282 integration test cover the
contracts.
`;
  }
  const run = result.run;
  const checks = run.checks ?? [];
  if (result.status !== 'PASS' && checks.length === 0) {
    return `# 285 — browser probe

Generated by \`npm run destructibles:live:probe\` on ${result.generatedAt}.

**${result.status}** — ${result.reason ?? 'unknown failure'}

Page errors: ${run.pageErrors ?? 0}; console errors: ${run.consoleErrors ?? 0}.

${(run.errors ?? []).map((line) => `- ${line}`).join('\n')}
${(run.console ?? []).map((line) => `- console: ${line}`).join('\n')}

No PASS is simulated.
`;
  }
  return `# 285 — browser probe

Generated by \`npm run destructibles:live:probe\` on ${result.generatedAt}; Chromium ${run.browser},
viewport ${run.viewport}. The page runs the real 227 state machine, 228 feedback/replay, 207
recorder, 148 Web Audio engine and the real Babylon destructible scene.

The contact is **PROBE_INJECTED** through the same live path; the native 282 solver contact is
covered by \`tests/destructibles/live-physics-integration.test.ts\`, not by this page.

| Metric | Value |
| --- | --- |
| Audio state | ${run.audioState} |
| Reaction material / intensity | ${run.material} / ${run.intensity} |
| Visual variant / fallback | ${run.variant} / ${run.fallback} |
| Fragments spawned / active | ${run.fragmentsSpawned} / ${run.fragmentsActive} |
| Shock rings active | ${run.ringsActive} |
| Reset restored | ${run.restored} |
| XP before / after | ${run.xpBefore} / ${run.xpAfter} |
| Profile before / after | ${run.profileBefore} / ${run.profileAfter} |
| Replay | ${run.replayStatus}, order ${run.orderIdentical}, destruction ${run.destructionEvents}, reset ${run.resetEvents} |
| Page errors / console errors | ${run.pageErrors} / ${run.consoleErrors} |

Checks: ${checks.filter((check) => check.pass).length}/${checks.length} passed.

${checks.map((check) => `- \`${check.name}\`: ${check.pass ? 'PASS' : 'FAIL'} - ${check.detail}`).join('\n')}

Screenshots: ${run.screenshots.map((file) => `[${file}](${file})`).join(', ')}.
`;
}

const generatedAt = new Date().toISOString();
await mkdir(screenshots, { recursive: true });
const playwright = await loadPlaywright();
if (playwright === null) {
  const result = {
    version: '285-live-chaos-browser-v1',
    generatedAt,
    status: 'NOT_RUN',
    reason:
      'Playwright is not installed in this checkout (no `playwright` module and no PLAYWRIGHT_MODULE); the browser probe was not run.',
    run: null,
  };
  await writeFile(browserJson, `${JSON.stringify(result, null, 2)}\n`);
  await writeFile(browserMarkdown, markdown(result));
  console.log(`Wrote ${browserJson}`);
  console.log('285 browser probe NOT_RUN: Playwright is not installed.');
  process.exit(0);
}

const { build } = await import('vite');
await build({
  configFile: join(root, 'vite.config.ts'),
  logLevel: 'error',
  build: {
    outDir: buildDirectory,
    emptyOutDir: true,
    rollupOptions: { input: join(root, 'tests', 'browser', 'destructible-chaos', 'index.html') },
  },
});
const { server, origin } = await serve(buildDirectory);
const { chromium } = playwright.default ?? playwright;
const channel = process.env.PLAYWRIGHT_CHANNEL || undefined;
let browser;
try {
  browser = await chromium.launch({
    headless: true,
    ...(channel === undefined ? {} : { channel }),
    args: [
      '--use-gl=angle',
      '--use-angle=swiftshader',
      '--enable-unsafe-swiftshader',
      '--disable-gpu-sandbox',
      '--disable-frame-rate-limit',
      '--autoplay-policy=no-user-gesture-required',
    ],
  });
} catch (error) {
  const result = {
    version: '285-live-chaos-browser-v1',
    generatedAt,
    status: 'NOT_RUN',
    reason: `Browser launch failed: ${error instanceof Error ? error.message : String(error)}`,
    run: null,
  };
  await writeFile(browserJson, `${JSON.stringify(result, null, 2)}\n`);
  await writeFile(browserMarkdown, markdown(result));
  server.close();
  console.log('285 browser probe NOT_RUN: browser launch failed.');
  process.exit(0);
}

const pageErrors = [];
const consoleErrors = [];
const captured = [];
let activePage = null;
try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 720 } });
  const page = await context.newPage();
  activePage = page;
  page.on('pageerror', (error) => pageErrors.push(String(error)));
  page.on('console', (message) => {
    if (message.type() === 'error') consoleErrors.push(message.text());
  });
  await page.bringToFront();
  await page.goto(`${origin}/tests/browser/destructible-chaos/index.html`, {
    waitUntil: 'load',
    timeout: 90000,
  });
  await page.waitForFunction(() => globalThis.__destructibleChaosProbe?.ready === true, null, {
    timeout: 120000,
    polling: 100,
  });
  await page.screenshot({ path: join(screenshots, 'initial.png'), timeout: 60000 });
  captured.push('screenshots/initial.png');

  await page.click('#unlock');
  await page.waitForTimeout(350);
  const initial = await page.evaluate(() => globalThis.__destructibleChaosProbe.read());
  const audioState = initial.audioState;
  const target = initial.targets.find((entry) => entry.archetype === 'CONE') ?? initial.targets[0];
  await page.evaluate(
    (objectId) => globalThis.__destructibleChaosProbe.focus(objectId),
    target.objectId,
  );
  const impact = await page.evaluate(
    (objectId) => globalThis.__destructibleChaosProbe.impact(objectId),
    target.objectId,
  );
  await page.waitForTimeout(650);
  const afterImpact = await page.evaluate(() => globalThis.__destructibleChaosProbe.read());
  await page.screenshot({ path: join(screenshots, 'impact.png'), timeout: 60000 });
  captured.push('screenshots/impact.png');

  const resetOne = await page.evaluate(() => globalThis.__destructibleChaosProbe.reset());
  await page.waitForTimeout(250);
  const afterReset = await page.evaluate(() => globalThis.__destructibleChaosProbe.read());
  await page.screenshot({ path: join(screenshots, 'reset.png'), timeout: 60000 });
  captured.push('screenshots/reset.png');

  await page.evaluate(
    (objectId) => globalThis.__destructibleChaosProbe.impact(objectId),
    target.objectId,
  );
  await page.waitForTimeout(250);
  const resetTwo = await page.evaluate(() => globalThis.__destructibleChaosProbe.reset());
  await page.waitForTimeout(250);
  const replay = await page.evaluate(() => globalThis.__destructibleChaosProbe.replay());
  const final = await page.evaluate(() => globalThis.__destructibleChaosProbe.read());
  await page.screenshot({ path: join(screenshots, 'replay.png'), timeout: 60000 });
  captured.push('screenshots/replay.png');

  const reaction = afterImpact.stats.lastReaction;
  const checks = [
    {
      name: 'live-plan',
      pass: initial.stats.objects === 35 && initial.stats.definitions === 35,
      detail: `${initial.stats.objects} objects, ${initial.stats.definitions} definitions`,
    },
    {
      name: 'impact-accepted',
      pass: impact !== null && impact.accepted === true && impact.state !== 'INTACT',
      detail: `state ${impact?.state ?? 'NONE'}`,
    },
    {
      name: 'material-intensity',
      pass:
        reaction !== null &&
        typeof reaction.material === 'string' &&
        typeof reaction.intensity.tier === 'string',
      detail: `${reaction?.material ?? 'NONE'} / ${reaction?.intensity.tier ?? 'NONE'}`,
    },
    {
      name: 'audio-or-visual-fallback',
      pass:
        reaction !== null &&
        (reaction.audioPlayed === true ||
          (reaction.audioPlayed === false && reaction.visualAlternative === true)),
      detail: `audio ${reaction?.audioPlayed ?? 'NONE'}, state ${audioState}, reason ${reaction?.audioReason ?? 'NONE'}`,
    },
    {
      name: 'fragments-rendered',
      pass:
        afterImpact.scene.fragmentsSpawned > 0 &&
        (afterImpact.scene.fragmentsActive > 0 || afterImpact.scene.shockRingsActive > 0),
      detail: `spawned ${afterImpact.scene.fragmentsSpawned}, active ${afterImpact.scene.fragmentsActive}, rings ${afterImpact.scene.shockRingsActive}`,
    },
    {
      name: 'notice-visible',
      pass:
        afterImpact.notice.hidden === false &&
        afterImpact.notice.text.length > 0 &&
        afterImpact.notice.variant !== null,
      detail: `${afterImpact.notice.material ?? 'NONE'} / ${afterImpact.notice.variant ?? 'NONE'}`,
    },
    {
      name: 'reset-restores',
      pass:
        resetOne.status === 'RESET' &&
        afterReset.stats.objectsByState.BROKEN === 0 &&
        afterReset.stats.objects === 35 &&
        resetOne.restored === 35,
      detail: `restored ${resetOne.restored}, broken ${afterReset.stats.objectsByState.BROKEN}`,
    },
    {
      name: 'reset-keeps-xp-profile',
      pass:
        resetOne.xpDeltaMicroXp === 0 &&
        resetOne.profileChanged === false &&
        afterReset.xp === initial.xp &&
        afterReset.profile === initial.profile,
      detail: `XP ${initial.xp}/${afterReset.xp}, profile ${initial.profile}/${afterReset.profile}`,
    },
    {
      name: 'replay-order',
      pass:
        replay.status === 'REPLAYED' &&
        replay.orderIdentical === true &&
        replay.eventsIdentical === true &&
        replay.stepsSimulation === 0 &&
        replay.policyEvaluations === 0 &&
        replay.awardsGranted === 0 &&
        replay.learningArtifacts === 0,
      detail: `${replay.status}, order ${replay.orderIdentical}, destruction ${replay.destructionEvents}, reset ${replay.resetEvents}`,
    },
    {
      name: 'replay-includes-reset',
      pass: replay.resetEvents >= 1 && replay.destructionEvents >= 1,
      detail: `destruction ${replay.destructionEvents}, reset ${replay.resetEvents}, chunk ${replay.chunkId}`,
    },
    {
      name: 'no-page-errors',
      pass: pageErrors.length === 0 && consoleErrors.length === 0,
      detail: `${pageErrors.length} page, ${consoleErrors.length} console`,
    },
  ];
  const run = {
    status: checks.every((check) => check.pass) ? 'PASS' : 'FAIL',
    browser: await page.evaluate(() => navigator.userAgent),
    viewport: '1280x720',
    audioState,
    material: reaction?.material ?? null,
    intensity: reaction?.intensity.tier ?? null,
    variant: reaction?.variant ?? null,
    fallback: reaction?.visualAlternative ?? null,
    fragmentsSpawned: afterImpact.scene.fragmentsSpawned,
    fragmentsActive: afterImpact.scene.fragmentsActive,
    ringsActive: afterImpact.scene.shockRingsActive,
    restored: resetOne.restored,
    xpBefore: initial.xp,
    xpAfter: afterReset.xp,
    profileBefore: initial.profile,
    profileAfter: afterReset.profile,
    replayStatus: replay.status,
    orderIdentical: replay.orderIdentical,
    destructionEvents: replay.destructionEvents,
    resetEvents: replay.resetEvents,
    pageErrors: pageErrors.length,
    consoleErrors: consoleErrors.length,
    chunks: final.stats.recorder.replayChunks,
    checks,
    screenshots: captured,
    probe: 'PROBE_INJECTED',
    resetOne,
    resetTwo,
    replay,
  };
  const result = {
    version: '285-live-chaos-browser-v1',
    generatedAt,
    status: run.status,
    reason: null,
    run,
  };
  await writeFile(browserJson, `${JSON.stringify(result, null, 2)}\n`);
  await writeFile(browserMarkdown, markdown(result));
  console.log(
    `285 browser probe ${run.status}: ${checks.filter((check) => check.pass).length}/${checks.length}`,
  );
  console.log(`Wrote ${browserJson}`);
  if (run.status !== 'PASS') process.exitCode = 1;
} catch (error) {
  const result = {
    version: '285-live-chaos-browser-v1',
    generatedAt,
    status: 'FAIL',
    reason: error instanceof Error ? error.message : String(error),
    run: {
      status: 'FAIL',
      pageErrors: pageErrors.length,
      consoleErrors: consoleErrors.length,
      errors: pageErrors.slice(0, 8),
      console: consoleErrors.slice(0, 8),
      screenshots: captured,
    },
  };
  await writeFile(browserJson, `${JSON.stringify(result, null, 2)}\n`);
  await writeFile(browserMarkdown, markdown(result));
  console.error(`285 browser probe FAIL: ${result.reason}`);
  process.exitCode = 1;
} finally {
  if (activePage !== null) {
    try {
      await activePage.evaluate(() => globalThis.__destructibleChaosProbe?.dispose?.());
    } catch {
      // The page may already be closing.
    }
  }
  await browser.close();
  server.close();
}
